// Catches: a deprecated forwarder drifting from the function it stands for.
func TestDeprecatedForwarders(t *testing.T) {
	if HeaderPrefix != genutil.HeaderPrefix {
		t.Errorf("HeaderPrefix = %q, want %q", HeaderPrefix, genutil.HeaderPrefix)
	}
	for _, line := range []string{"", Header(), "// Code generated by momo v1 (format 3). DO NOT EDIT.\n", "package x"} {
		f1, ok1 := ParseHeader(line)
		f2, ok2 := genutil.ParseHeader(line)
		if f1 != f2 || ok1 != ok2 {
			t.Errorf("ParseHeader(%q) = %d, %v; want %d, %v", line, f1, ok1, f2, ok2)
		}
	}
	reserved := map[string]bool{"Table": true, "Table_": true}
	for _, n := range []string{"Name", "Table", "type"} {
		if got, want := Identifier(n, reserved), genutil.Identifier(n, reserved); got != want {
			t.Errorf("Identifier(%q) = %q, want %q", n, got, want)
		}
	}
	if !reflect.DeepEqual(DescriptorReserved(), genutil.DescriptorReserved()) {
		t.Error("DescriptorReserved differs from genutil")
	}
	for _, m := range []string{"User", "Func", "string"} {
		if got, want := SubPkgName(m, "models"), genutil.SubPkgName(m, "models"); got != want {
			t.Errorf("SubPkgName(%q) = %q, want %q", m, got, want)
		}
	}
	for _, p := range []string{"/mod", "/mod/a/b", "/other"} {
		g1, e1 := ImportPath("example.com/m", "/mod", p)
		g2, e2 := genutil.ImportPath("example.com/m", "/mod", p)
		if g1 != g2 || (e1 == nil) != (e2 == nil) {
			t.Errorf("ImportPath(%q) = %q, %v; want %q, %v", p, g1, e1, g2, e2)
		}
	}
	for _, s := range []string{"timestamptz", "timestamp(3) with time zone", "text", " TIME "} {
		if got, want := ValidTimeType(s), genutil.ValidTimeType(s); got != want {
			t.Errorf("ValidTimeType(%q) = %v, want %v", s, got, want)
		}
	}
	for _, a := range []Access{Writable, ReadOnly, CreateOnly, Immutable} {
		for _, ptr := range []bool{false, true} {
			t1, c1 := DescriptorType(a, ptr)
			t2, c2 := descriptorType(a, ptr)
			v1, d1 := VectorDescriptorType(a, ptr)
			v2, d2 := vectorDescriptorType(a, ptr)
			if t1 != t2 || c1 != c2 || v1 != v2 || d1 != d2 {
				t.Errorf("descriptor types differ for access %d pointer %v", a, ptr)
			}
		}
	}
	for _, tg := range []tags.Tags{{}, {ReadOnly: true}, {CreateOnly: true}, {ReadOnly: true, Immutable: true}} {
		a1, d1 := AccessFor(tg, "F", false)
		a2, d2 := accessFor(tg, "F", false)
		if a1 != a2 || !reflect.DeepEqual(d1, d2) {
			t.Errorf("AccessFor(%+v) differs from accessFor", tg)
		}
	}
}

// Catches: a deprecated emitter forwarder emitting something else than the
// emitter it forwards to.
func TestDeprecatedEmitterForwarders(t *testing.T) {
	dir, err := filepath.Abs("testdata/fixtures")
	if err != nil {
		t.Fatal(err)
	}
	g, diags, err := Load([]string{"./sensitive"}, Config{Dir: dir})
	if err != nil || len(diags) != 0 {
		t.Fatalf("load: %v %v", err, diags)
	}
	m := findModel(t, g, "Account")
	l1, _ := EmitLookup(m, g)
	l2, _ := emitLookup(m, g)
	d1, _ := EmitDescriptors(m, g)
	d2, _ := emitDescriptors(m, g)
	m1, _ := EmitMeta(g.Models, g)
	m2, _ := emitMeta(g.Models, g)
	if len(l1) == 0 || len(d1) == 0 || !bytes.Equal(l1, l2) || !bytes.Equal(d1, d2) || !bytes.Equal(m1, m2) {
		t.Error("an Emit forwarder differs from its emitter")
	}
}
