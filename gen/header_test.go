package gen

import (
	"regexp"
	"strings"
	"testing"
)

var goGeneratedHeader = regexp.MustCompile(`^// Code generated .* DO NOT EDIT\.$`)

func TestGeneratedHeaderRegexp(t *testing.T) {
	if !goGeneratedHeader.MatchString(Header()) {
		t.Fatalf("%q does not match the Go generated-file convention", Header())
	}
	want := "// Code generated by momo (format 1). DO NOT EDIT."
	if Header() != want {
		t.Fatalf("header = %q, want %q", Header(), want)
	}
}

// TestHeaderAgreesWithWriterDetection catches the header and the writer's
// handwritten-file detection drifting apart.
func TestHeaderAgreesWithWriterDetection(t *testing.T) {
	if !strings.HasPrefix(Header(), HeaderPrefix) {
		t.Fatalf("Header() %q does not start with HeaderPrefix %q", Header(), HeaderPrefix)
	}
}

func TestParseHeaderAcceptsOldAndNewForms(t *testing.T) {
	cases := []struct {
		line   string
		format int
		ok     bool
	}{
		{"// Code generated by momo (format 1). DO NOT EDIT.", 1, true},
		{"// Code generated by momo v0.1.0-dev (format 1). DO NOT EDIT.", 1, true},
		{"// Code generated by momo v0.3.0 (format 2). DO NOT EDIT.", 2, true},
		{"// Code generated by momo (format 1). DO NOT EDIT.\n", 1, true},
		{"// Code generated by momo v0.1.0-dev (format 1). DO NOT EDIT.\r\n", 1, true},
		{"// Code generated by momo (format x). DO NOT EDIT.", 0, false},
		{"// Code generated by other (format 1). DO NOT EDIT.", 0, false},
		{"// handwritten", 0, false},
	}
	for _, c := range cases {
		f, ok := ParseHeader(c.line)
		if f != c.format || ok != c.ok {
			t.Errorf("ParseHeader(%q) = %d, %v; want %d, %v", c.line, f, ok, c.format, c.ok)
		}
	}
	if f, ok := ParseHeader(Header()); !ok || f != FormatVersion {
		t.Errorf("ParseHeader(Header()) = %d, %v", f, ok)
	}
}
