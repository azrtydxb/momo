package gen

import (
	"regexp"
	"strings"
	"testing"
)

var goGeneratedHeader = regexp.MustCompile(`^// Code generated .* DO NOT EDIT\.$`)

func TestGeneratedHeaderRegexp(t *testing.T) {
	if !goGeneratedHeader.MatchString(Header()) {
		t.Fatalf("%q does not match the Go generated-file convention", Header())
	}
	want := "// Code generated by momo " + Version + " (format 1). DO NOT EDIT."
	if Header() != want {
		t.Fatalf("header = %q, want %q", Header(), want)
	}
}

