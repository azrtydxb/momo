func runPlugins(root string, plugins ...gen.Plugin) ([]gen.Output, error) {
	g := &gen.Graph{Plugins: plugins}
	w := gen.NewWriter(gen.WriterOptions{ModuleRoot: root})
	if err := gen.Emit(g, w); err != nil {
		return nil, err
	}
	return w.Outputs(), nil
}

type badNamePlugin struct{}

func (badNamePlugin) Name() string                           { return "Bad-Name" }
func (badNamePlugin) Generate(*gen.Graph, *gen.Writer) error { return nil }

type v2Plugin struct{ badNamePlugin }

func (v2Plugin) Name() string    { return "v2" }
func (v2Plugin) APIVersion() int { return 2 }

func TestGeneratorPlugin(t *testing.T) {
	root := t.TempDir()
	p := fixture.Plugin{Root: root}

	first, err := runPlugins(root, p)
	if err != nil {
		t.Fatal(err)
	}
	second, err := runPlugins(root, p)
	if err != nil {
		t.Fatal(err)
	}
	if len(first) != 1 || len(second) != 1 || first[0].Path != second[0].Path || !bytes.Equal(first[0].Data, second[0].Data) {
		t.Fatalf("plugin output is not deterministic: %v vs %v", first, second)
	}

	hand := filepath.Join(root, "handwritten", "hand.go")
	if err := os.MkdirAll(filepath.Dir(hand), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(hand, []byte("package handwritten\n// mine\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := runPlugins(root, fixture.Plugin{Root: root, Overwrite: true}); !errors.Is(err, gen.ErrHandwritten) {
		t.Fatalf("handwritten target: want ErrHandwritten, got %v", err)
	}
	b, err := os.ReadFile(hand)
	if err != nil {
		t.Fatal(err)
	}
	if string(b) != "package handwritten\n// mine\n" {
		t.Fatal("handwritten file was modified")
	}

	if _, err := runPlugins(root, badNamePlugin{}); err == nil || !strings.Contains(err.Error(), "invalid plugin name") {
		t.Fatalf("bad name: got %v", err)
	}
	if _, err := runPlugins(root, v2Plugin{}); err == nil || !strings.Contains(err.Error(), "targets API v2") {
		t.Fatalf("api version: got %v", err)
	}
}

// recorder is a plugin that records its call order and writes one file.
type recorder struct {
	name  string
	root  string
	order *[]string
	err   error
}

func (r recorder) Name() string { return r.name }
func (r recorder) Generate(_ *gen.Graph, w *gen.Writer) error {
	*r.order = append(*r.order, r.name)
	src := []byte("// Code generated by momo (format 1). DO NOT EDIT.\n\npackage " + r.name + "\n")
	if err := w.File(filepath.Join(r.root, r.name, "zz_gen.go"), src); err != nil {
		return err
	}
	return r.err
}

func TestPluginsRunInSliceOrder(t *testing.T) {
	root := t.TempDir()
	var order []string
	g := &gen.Graph{Plugins: []gen.Plugin{
		recorder{name: "zeta", root: root, order: &order},
		recorder{name: "alpha", root: root, order: &order},
	}}
	w := gen.NewWriter(gen.WriterOptions{ModuleRoot: root})
	if err := gen.Emit(g, w); err != nil {
		t.Fatal(err)
	}
	if strings.Join(order, ",") != "zeta,alpha" {
		t.Fatalf("plugins ran in order %v, want slice order zeta,alpha", order)
	}
	outs := w.Outputs()
	if len(outs) != 2 || !strings.Contains(string(outs[0].Data), "package alpha") || !strings.Contains(string(outs[1].Data), "package zeta") {
		t.Fatalf("each plugin must write its own distinct file: %v", outs)
	}
}

func TestInvalidPluginLeavesNoOutput(t *testing.T) {
	root := t.TempDir()
	cases := map[string][]gen.Plugin{
		"bad name":    {nil, badNamePlugin{}},
		"bad version": {nil, v2Plugin{}},
		"duplicate":   {nil, nil},
	}
	for name, ps := range cases {
		t.Run(name, func(t *testing.T) {
			var order []string
			first := recorder{name: "first", root: root, order: &order}
			ps[0] = first
			if name == "duplicate" {
				ps[1] = recorder{name: "first", root: root, order: &order}
			}
			w := gen.NewWriter(gen.WriterOptions{ModuleRoot: root})
			err := gen.Emit(&gen.Graph{Plugins: ps}, w)
			if err == nil {
				t.Fatal("want an error")
			}
			if name == "duplicate" && !strings.Contains(err.Error(), `duplicate plugin name "first"`) {
				t.Fatalf("got %v", err)
			}
			if len(order) != 0 || len(w.Outputs()) != 0 {
				t.Fatalf("a rejected plugin set must run nothing and buffer nothing: ran %v, outputs %v", order, w.Outputs())
			}
		})
	}
}

func TestPluginErrorWrapped(t *testing.T) {
	root := t.TempDir()
	var order []string
	sentinel := errors.New("sentinel")
	g := &gen.Graph{Plugins: []gen.Plugin{recorder{name: "boom", root: root, order: &order, err: sentinel}}}
	err := gen.Emit(g, gen.NewWriter(gen.WriterOptions{ModuleRoot: root}))
	if !errors.Is(err, sentinel) {
		t.Fatalf("errors.Is must see through Emit: %v", err)
	}
	if !strings.Contains(err.Error(), "plugin boom") {
		t.Fatalf("error does not name the plugin: %v", err)
	}
}

// fsFuncs are the filesystem-mutating functions generator code must not call.
var fsFuncs = map[string]bool{
	"WriteFile": true, "Create": true, "CreateTemp": true, "OpenFile": true,
	"Rename": true, "Mkdir": true, "MkdirAll": true, "Remove": true, "RemoveAll": true,
}

// fsViolations returns the filesystem-mutating calls in src, resolving import
// aliases for os, io/ioutil and syscall. Comments and strings never match.
func fsViolations(fset *token.FileSet, f *ast.File) []string {
	local := map[string]string{}
	for _, imp := range f.Imports {
		path, err := strconv.Unquote(imp.Path.Value)
		if err != nil || (path != "os" && path != "io/ioutil" && path != "syscall") {
			continue
		}
		name := filepath.Base(path)
		if imp.Name != nil {
			name = imp.Name.Name
		}
		if name == "_" || name == "." {
			continue
		}
		local[name] = path
	}
	var out []string
	ast.Inspect(f, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		id, ok := sel.X.(*ast.Ident)
		if !ok || id.Obj != nil {
			return true
		}
		if path, ok := local[id.Name]; ok && fsFuncs[sel.Sel.Name] {
			out = append(out, fmt.Sprintf("%s: %s.%s", fset.Position(call.Pos()), path, sel.Sel.Name))
		}
		return true
	})
	return out
}

func TestFsViolationsDetector(t *testing.T) {
	src := `package p
import (
	"os"
	o "os"
	"io/ioutil"
)
// os.WriteFile( in a comment
var _ = "os.WriteFile("
func f() {
	_ = os.WriteFile("a", nil, 0)
	_ = o.Mkdir("a", 0)
	_ = ioutil.WriteFile("a", nil, 0)
	_, _ = os.ReadFile("a")
}
`
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "p.go", src, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	if got := fsViolations(fset, f); len(got) != 3 {
		t.Fatalf("want 3 violations, got %v", got)
	}
}

// TestPluginsUseWriter fails if any non-test generator or plugin source under
// gen/ (testdata/plugins included) mutates the filesystem other than through
// gen.Writer. Only gen/writer.go is exempt.
func TestPluginsUseWriter(t *testing.T) {
	scanned := 0
	err := filepath.WalkDir(".", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(p, ".go") || strings.HasSuffix(p, "_test.go") || filepath.ToSlash(p) == "writer.go" {
			return nil
		}
		fset := token.NewFileSet()
		f, perr := parser.ParseFile(fset, p, nil, 0)
		if perr != nil {
			t.Errorf("parsing %s: %v", p, perr)
			return nil
		}
		scanned++
		for _, v := range fsViolations(fset, f) {
			t.Errorf("%s; generator code must write through gen.Writer", v)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if scanned == 0 {
		t.Fatal("scanned no files")
	}
	if _, err := os.Stat(filepath.Join("testdata", "plugins", "fixture", "fixture.go")); err != nil {
		t.Fatalf("fixture plugin must be in scope: %v", err)
	}
}
