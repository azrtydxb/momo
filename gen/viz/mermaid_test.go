// Catches: any change to the Mermaid output of the example models, which the
// golden file records after review.
func TestVizMermaidGolden(t *testing.T) {
	g := loadExample(t)
	got := Mermaid(Tables(g), EdgesFromGraph(g))
	ok, err := golden.Diff("testdata/example.mmd", got, *update)
	if err != nil || !ok {
		t.Fatalf("golden mismatch (err=%v); got:\n%s\nrun with -update after review", err, got)
	}
}

// Catches: SQL types that Mermaid cannot parse, a missing key marker, or an
// edge drawn child-first (which reads as the wrong cardinality).
func TestMermaidShape(t *testing.T) {
	tb := []schema.Table{{
		Name:       "docs",
		PrimaryKey: []string{"id"},
		Columns: []schema.Column{
			{Name: "id", Type: "bigint"},
			{Name: "embedding", Type: "vector(1536)"},
			{Name: "owner_id", Type: "character varying(20)"},
		},
		ForeignKeys: []schema.ForeignKey{{Columns: []string{"owner_id"}, RefTable: "owners", RefColumns: []string{"id"}}},
		Uniques:     []schema.Unique{{Name: "u", Columns: []string{"owner_id"}}},
	}}
	got := string(Mermaid(tb, []Edge{
		{From: "docs", To: "owners", Cardinality: OneToMany, Label: "owner_id"},
		{From: "docs", To: "tags", Cardinality: ManyToMany, Label: "doc_tags"},
		{From: "docs", To: "profiles", Cardinality: OneToOne, Label: "profile_id"},
	}))
	for _, want := range []string{
		"%% Code generated by momo (format 1). DO NOT EDIT.\nerDiagram\n",
		"        bigint id PK\n",
		"        vector_1536 embedding\n",
		"        character_varying_20 owner_id FK, UK\n",
		`    owners ||--o{ docs : "owner_id"`,
		`    docs }o--o{ tags : "doc_tags"`,
		`    profiles ||--|| docs : "profile_id"`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("output lacks %q:\n%s", want, got)
		}
	}
}
