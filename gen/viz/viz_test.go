// Catches: a regression in either renderer of the example models, and a
// renderer that drops the generated-file header.
func TestViz(t *testing.T) {
	g := loadExample(t)
	tables := Tables(g)
	edges := EdgesFromGraph(g)
	cases := []struct {
		name   string
		golden string
		render func([]schema.Table, []Edge) []byte
	}{
		{name: "mermaid", golden: "testdata/example.mmd", render: Mermaid},
		{name: "dot", golden: "testdata/example.dot", render: DOT},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := c.render(tables, edges)
			if !strings.Contains(string(got[:min(len(got), 80)]), "Code generated by momo") {
				t.Fatalf("%s output lacks the generated header", c.name)
			}
			for _, tb := range tables {
				if !strings.Contains(string(got), tb.Name) {
					t.Errorf("%s output lacks table %s", c.name, tb.Name)
				}
			}
			ok, err := golden.Diff(c.golden, got, *update)
			if err != nil {
				t.Fatal(err)
			}
			if !ok {
				t.Fatalf("%s differs from %s; got:\n%s\nreview and rerun with -update", c.name, c.golden, got)
			}
		})
	}
}

// Catches: unescaped HTML in a DOT label and an edge with the wrong arrow
// ends.
func TestDOTShape(t *testing.T) {
	tb := []schema.Table{{
		Name:       "a<b",
		PrimaryKey: []string{"id"},
		Columns:    []schema.Column{{Name: "id", Type: "bigint"}},
	}}
	got := string(DOT(tb, []Edge{
		{From: "a<b", To: "p", Cardinality: OneToMany, Label: "p_id"},
		{From: "a<b", To: "m", Cardinality: ManyToMany, Label: "j"},
	}))
	for _, want := range []string{
		"// Code generated by momo (format 1). DO NOT EDIT.\ndigraph momo {\n    rankdir=LR;\n    node [shape=plaintext];\n",
		"<B>a&lt;b</B>",
		`"a<b" -> "p" [label="p_id", arrowhead=tee, arrowtail=crow, dir=both];`,
		`"a<b" -> "m" [label="j", arrowhead=crowodot, arrowtail=crowodot, dir=both];`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("output lacks %q:\n%s", want, got)
		}
	}
}
