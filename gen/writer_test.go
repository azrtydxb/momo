const testHeader = "// Code generated by momo v0 (format 1). DO NOT EDIT.\n\npackage pkg\n"

func TestGenerateRefusesHandwritten(t *testing.T) {
	root := t.TempDir()
	hand := filepath.Join(root, "pkg", "momo_gen.go")
	if err := os.MkdirAll(filepath.Dir(hand), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(hand, []byte("package pkg\n// my own file\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	w := NewWriter(WriterOptions{ModuleRoot: root})
	err := w.File(hand, []byte(testHeader))
	if !errors.Is(err, ErrHandwritten) {
		t.Fatalf("want ErrHandwritten, got %v", err)
	}
	if !strings.Contains(err.Error(), hand) {
		t.Fatalf("error does not name the path: %v", err)
	}
	b, err := os.ReadFile(hand)
	if err != nil {
		t.Fatal(err)
	}
	if string(b) != "package pkg\n// my own file\n" {
		t.Fatal("handwritten file was modified")
	}

	gen := filepath.Join(root, "pkg", "other_gen.go")
	w = NewWriter(WriterOptions{ModuleRoot: root})
	if err := w.File(gen, []byte(testHeader)); err != nil {
		t.Fatal(err)
	}
	if err := w.File(gen, []byte(testHeader+"var x = 1\n")); !errors.Is(err, ErrCollision) {
		t.Fatalf("want ErrCollision, got %v", err)
	}
	outside := filepath.Join(filepath.Dir(root), "escape_gen.go")
	if err := w.File(outside, []byte(testHeader)); err == nil {
		t.Fatal("write outside the module root accepted")
	}
	if err := w.File("relative_gen.go", []byte(testHeader)); err == nil {
		t.Fatal("relative path accepted")
	}
	if err := w.File(filepath.Join(root, "bad_gen.go"), []byte("not go")); err == nil {
		t.Fatal("unformattable source accepted")
	}
}

func TestWriterCollisionSameBytesOK(t *testing.T) {
	root := t.TempDir()
	p := filepath.Join(root, "a_gen.go")
	w := NewWriter(WriterOptions{ModuleRoot: root})
	for i := 0; i < 2; i++ {
		if err := w.File(p, []byte(testHeader)); err != nil {
			t.Fatalf("identical repeat rejected: %v", err)
		}
	}
	changed, err := w.Commit()
	if err != nil || len(changed) != 1 {
		t.Fatalf("changed=%v err=%v", changed, err)
	}
}

func TestWriterIdempotentAndCheck(t *testing.T) {
	root := t.TempDir()
	p := filepath.Join(root, "sub", "a_gen.go")
	q := filepath.Join(root, "sub", "b_gen.go")
	run := func(check bool) ([]string, error) {
		w := NewWriter(WriterOptions{ModuleRoot: root, Check: check})
		for _, f := range []string{q, p} {
			if err := w.File(f, []byte(testHeader)); err != nil {
				t.Fatal(err)
			}
		}
		return w.Commit()
	}
	changed, err := run(true)
	if err != nil || len(changed) != 2 {
		t.Fatalf("check on empty tree: %v %v", changed, err)
	}
	if _, err := os.Stat(p); !os.IsNotExist(err) {
		t.Fatal("check mode wrote a file")
	}
	changed, err = run(false)
	if err != nil || !reflect.DeepEqual(changed, []string{p, q}) {
		t.Fatalf("first run: %v %v", changed, err)
	}
	fi, err := os.Stat(p)
	if err != nil {
		t.Fatal(err)
	}
	if fi.Mode().Perm() != 0o644 {
		t.Fatalf("mode too wide: %v", fi.Mode())
	}
	old := time.Now().Add(-time.Hour).Truncate(time.Second)
	if err := os.Chtimes(p, old, old); err != nil {
		t.Fatal(err)
	}
	changed, err = run(false)
	if err != nil || len(changed) != 0 {
		t.Fatalf("second run changed %v %v", changed, err)
	}
	fi, _ = os.Stat(p)
	if !fi.ModTime().Equal(old) {
		t.Fatal("unchanged file was rewritten")
	}
	changed, err = run(true)
	if err != nil || len(changed) != 0 {
		t.Fatalf("check on clean tree: %v %v", changed, err)
	}
	if err := os.WriteFile(p, []byte(testHeader+"// drift\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	changed, err = run(true)
	if err != nil || !reflect.DeepEqual(changed, []string{p}) {
		t.Fatalf("drift not reported: %v %v", changed, err)
	}
}

func TestWriterFailedWriteLeavesNothing(t *testing.T) {
	root := t.TempDir()
	dir := filepath.Join(root, "pkg")
	p := filepath.Join(dir, "a_gen.go")
	w := NewWriter(WriterOptions{ModuleRoot: root})
	if err := w.File(p, []byte(testHeader)); err != nil {
		t.Fatal(err)
	}
	// A directory appears at the target after buffering: the rename must fail.
	if err := os.MkdirAll(p, 0o755); err != nil {
		t.Fatal(err)
	}
	if _, err := w.Commit(); err == nil {
		t.Fatal("expected commit failure")
	}
	ents, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(ents) != 1 || ents[0].Name() != "a_gen.go" || !ents[0].IsDir() {
		t.Fatalf("stray entries after failed write: %v", ents)
	}
}

func TestWriterOrphans(t *testing.T) {
	root := t.TempDir()
	dir := filepath.Join(root, "pkg")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	files := map[string]string{
		"keep_gen.go":  testHeader,
		"stale_gen.go": testHeader,
		"hand.go":      "package pkg\n",
		"notgo.txt":    testHeader,
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	w := NewWriter(WriterOptions{ModuleRoot: root})
	if err := w.File(filepath.Join(dir, "keep_gen.go"), []byte(testHeader)); err != nil {
		t.Fatal(err)
	}
	got, err := w.Orphans([]string{dir})
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{filepath.Join(dir, "stale_gen.go")}; !reflect.DeepEqual(got, want) {
		t.Fatalf("orphans %v want %v", got, want)
	}
}

func TestWriterRejectsSymlinkEscape(t *testing.T) {
	root := t.TempDir()
	outside := t.TempDir()
	if err := os.Symlink(outside, filepath.Join(root, "link")); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	w := NewWriter(WriterOptions{ModuleRoot: root})
	for _, p := range []string{
		filepath.Join(root, "link", "x_gen.go"),
		filepath.Join(root, "link", "newdir", "x_gen.go"),
	} {
		if err := w.File(p, []byte(testHeader)); err == nil {
			t.Fatalf("symlink escape accepted for %s", p)
		}
	}
	ents, err := os.ReadDir(outside)
	if err != nil || len(ents) != 0 {
		t.Fatalf("outside dir touched: %v %v", ents, err)
	}
	// A symlinked module root itself is fine.
	alias := filepath.Join(t.TempDir(), "alias")
	if err := os.Symlink(root, alias); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	w = NewWriter(WriterOptions{ModuleRoot: alias})
	if err := w.File(filepath.Join(alias, "ok_gen.go"), []byte(testHeader)); err != nil {
		t.Fatalf("symlinked root rejected: %v", err)
	}
}

func TestWriterDetectsCRLFHeaderAsGenerated(t *testing.T) {
	root := t.TempDir()
	p := filepath.Join(root, "x_gen.go")
	if err := os.WriteFile(p, []byte(Header()+"\r\n\r\npackage pkg\r\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if hand, err := isHandwritten(p); err != nil || hand {
		t.Fatalf("isHandwritten=%v,%v want false,nil", hand, err)
	}
	w := NewWriter(WriterOptions{ModuleRoot: root})
	if err := w.File(p, []byte(testHeader)); err != nil {
		t.Fatalf("File over CRLF generated file: %v", err)
	}
}

