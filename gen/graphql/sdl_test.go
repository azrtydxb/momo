var update = flag.Bool("update", false, "rewrite golden files")

// Catches: any change to the schema generated for the example models, which
// the golden file records after review.
func TestGraphQLSDL(t *testing.T) {
	root, err := filepath.Abs("../../internal/testmodels/example")
	if err != nil {
		t.Fatal(err)
	}
	g, diags, err := gen.Load([]string{"./"}, gen.Config{Dir: root})
	if err != nil || len(diags) != 0 {
		t.Fatalf("load: %v %v", err, diags)
	}
	src, ds := SDL(g)
	if len(ds) != 0 {
		t.Fatalf("diags %v", ds)
	}
	ok, err := golden.Diff("testdata/example.graphqls", src, *update)
	if err != nil || !ok {
		t.Fatalf("golden mismatch (err=%v); got:\n%s\nrun with -update after review", err, src)
	}
}

func syntheticGraph() *gen.Graph {
	things := &gen.Model{
		GoName: "Thing", Table: "things",
		Fields: []*gen.Field{
			{GoName: "ID", Column: "id", BaseType: "int64"},
			{GoName: "Secret", Column: "secret", BaseType: "string", Tags: tags.Tags{Sensitive: true}},
			{GoName: "Embedding", Column: "embedding", BaseType: "vector.Vector"},
			{GoName: "Note", Column: "note_text", BaseType: "string", Nullable: true},
			{GoName: "Blob", Column: "blob", BaseType: "types.Hstore"},
		},
	}
	owner := &gen.Model{
		GoName: "Owner", Table: "owners",
		Fields: []*gen.Field{{GoName: "Code", Column: "code", BaseType: "string"}},
	}
	things.Relations = []*gen.Relation{{GoName: "Owner", Kind: gen.BelongsTo, Target: owner}}
	owner.Relations = []*gen.Relation{{GoName: "Things", Kind: gen.HasMany, Target: things}}
	return &gen.Graph{
		Models: []*gen.Model{things, owner},
		Schema: &schema.Schema{Tables: []schema.Table{
			{Name: "things", PrimaryKey: []string{"id"}},
			{Name: "owners", PrimaryKey: []string{"code"}},
		}},
	}
}

// Catches: vector or sensitive columns leaking into the schema, a type with
// no filter being skipped silently, wrong relation shapes, or an ID field on
// a non-integer key.
func TestSDLRules(t *testing.T) {
	src, diags := SDL(syntheticGraph())
	s := string(src)
	for _, bad := range []string{"secret", "embedding", "Embedding", "blob:"} {
		if strings.Contains(s, bad) {
			t.Errorf("schema exposes %q:\n%s", bad, s)
		}
	}
	for _, want := range []string{
		"  id: ID!\n",
		"  noteText: String\n",
		"  owner: Owner\n",
		"  things: [Thing!]!\n",
		"  code: String!\n",
		"  things(first: Int, after: String, filter: ThingFilter, order: ThingOrder): ThingConnection!\n",
		"  thing(id: ID!): Thing\n",
		"  NOTE_TEXT\n",
	} {
		if !strings.Contains(s, want) {
			t.Errorf("schema lacks %q:\n%s", want, s)
		}
	}
	if strings.Contains(s, "(id: ID!): Owner") {
		t.Errorf("a string key must not get a single-object query:\n%s", s)
	}
	if len(diags) != 1 || !strings.Contains(diags[0].Msg, "no GraphQL filter for types.Hstore") {
		t.Fatalf("diags = %v, want one for types.Hstore", diags)
	}
	if !strings.HasPrefix(s, "# Code generated by momo") {
		t.Errorf("missing generated header:\n%s", s)
	}
}
