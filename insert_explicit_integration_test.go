// explicitServer is one database an Explicit test runs on. The MySQL entries
// open MySQL 8.4, 9.7 and MariaDB (testopen.Each opens only PostgreSQL and
// SQLite) and skip when their URL is unset, so each integration-mysql job
// runs the one server it provides.
type explicitServer struct {
	name string
	open func(*testing.T, ...momo.Option) *momo.DB
	// receipts creates the NovaCRM Receipt (text key plus a serial column that
	// is not the key); empty where the dialect cannot have one (SQLite).
	receipts string
	// keyed creates default_rows with a generated integer primary key.
	keyed string
}

const mysqlReceipts = "CREATE TABLE receipts (id varchar(40) NOT NULL PRIMARY KEY, seq int NOT NULL AUTO_INCREMENT UNIQUE, note varchar(100) NOT NULL)"
const mysqlKeyed = "CREATE TABLE default_rows (id bigint NOT NULL AUTO_INCREMENT PRIMARY KEY, body varchar(100) NOT NULL)"

var explicitServers = []explicitServer{
	{"postgres", testopen.Postgres,
		"CREATE TABLE receipts (id text PRIMARY KEY, seq serial NOT NULL, note text NOT NULL)",
		"CREATE TABLE default_rows (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, body text NOT NULL)"},
	{"sqlite", testopen.SQLite, "",
		"CREATE TABLE default_rows (id INTEGER PRIMARY KEY AUTOINCREMENT, body TEXT NOT NULL)"},
	{"mysql84", testopen.MySQL84, mysqlReceipts, mysqlKeyed},
	{"mysql97", testopen.MySQL97, mysqlReceipts, mysqlKeyed},
	{"mariadb118", testopen.MariaDB, mysqlReceipts, mysqlKeyed},
}

func explicitExec(t *testing.T, db *momo.DB, sql string) {
	t.Helper()
	if _, err := momo.Exec(context.Background(), db, sql); err != nil {
		t.Fatalf("%s: %v", sql, err)
	}
}

func receiptSeqs(t *testing.T, db *momo.DB) map[string]int64 {
	t.Helper()
	rows, err := momo.Query[explReceipt](context.Background(), db, "SELECT id, seq, note FROM receipts")
	if err != nil {
		t.Fatal(err)
	}
	out := map[string]int64{}
	for _, r := range rows {
		out[r.ID] = r.Seq
	}
	return out
}

// Catches: Explicit that renders the right SQL but still loses the value on a
// real server: a non-key serial (PostgreSQL) or AUTO_INCREMENT (MySQL,
// MariaDB) column must read back exactly the struct value on Model, Models,
// Values and Upsert, while an insert without Explicit still takes a generated
// number and drops the struct value.
func TestInsertExplicitNonKeySerialRoundTrip(t *testing.T) {
	for _, s := range explicitServers {
		if s.receipts == "" {
			continue
		}
		t.Run(s.name, func(t *testing.T) {
			db := s.open(t)
			ctx := context.Background()
			explicitExec(t, db, s.receipts)

			ctl := explReceipt{ID: "ctl", Seq: 55, Note: "control"}
			if _, err := momo.Insert[explReceipt](db).Model(&ctl).Exec(ctx); err != nil {
				t.Fatal(err)
			}
			if got := receiptSeqs(t, db)["ctl"]; got == 0 || got == 55 {
				t.Fatalf("without Explicit seq = %d, want a generated number other than 55", got)
			}

			one := explReceipt{ID: "one", Seq: 1000, Note: "x"}
			if _, err := momo.Insert[explReceipt](db).Model(&one).Explicit(explRSeq).Exec(ctx); err != nil {
				t.Fatal(err)
			}
			many := []explReceipt{{ID: "m1", Seq: 2001, Note: "a"}, {ID: "m2", Seq: 2002, Note: "b"}}
			if _, err := momo.Insert[explReceipt](db).Models(many).Explicit(explRSeq).Exec(ctx); err != nil {
				t.Fatal(err)
			}
			if _, err := momo.Insert[explReceipt](db).Values(explRID.Set("v"), explRSeq.Set(3000), explRNote.Set("v")).Explicit(explRSeq).Exec(ctx); err != nil {
				t.Fatal(err)
			}
			up := explReceipt{ID: "one", Seq: 1000, Note: "changed"}
			if _, err := momo.Upsert[explReceipt](db).Model(&up).Explicit(explRSeq).Exec(ctx); err != nil {
				t.Fatal(err)
			}

			got := receiptSeqs(t, db)
			for id, want := range map[string]int64{"one": 1000, "m1": 2001, "m2": 2002, "v": 3000} {
				if got[id] != want {
					t.Errorf("receipt %s seq = %d, want %d (all: %v)", id, got[id], want, got)
				}
			}
			rows, err := momo.Query[explReceipt](ctx, db, "SELECT id, seq, note FROM receipts WHERE id = 'one'")
			if err != nil || len(rows) != 1 || rows[0].Note != "changed" {
				t.Fatalf("upsert did not update the row: %+v %v", rows, err)
			}
		})
	}
}

// Catches: Explicit on a generated integer primary key (PostgreSQL BY DEFAULT
// identity, SQLite INTEGER PRIMARY KEY AUTOINCREMENT, MySQL and MariaDB
// AUTO_INCREMENT) that does not keep the caller's key, or an insert without
// Explicit that stops generating one.
func TestInsertExplicitGeneratedKeyRoundTrip(t *testing.T) {
	for _, s := range explicitServers {
		t.Run(s.name, func(t *testing.T) {
			db := s.open(t)
			ctx := context.Background()
			explicitExec(t, db, s.keyed)

			rows := []explByDefault{{ID: 700, Body: "a"}, {ID: 701, Body: "b"}}
			if _, err := momo.Insert[explByDefault](db).Models(rows).Explicit(explDID).Exec(ctx); err != nil {
				t.Fatal(err)
			}
			one := explByDefault{ID: 800, Body: "c"}
			if _, err := momo.Insert[explByDefault](db).Model(&one).Explicit(explDID).Exec(ctx); err != nil {
				t.Fatal(err)
			}
			if one.ID != 800 {
				t.Errorf("model id = %d after an explicit insert, want 800 (LAST_INSERT_ID must not overwrite it)", one.ID)
			}
			drop := explByDefault{ID: 900, Body: "d"}
			if _, err := momo.Insert[explByDefault](db).Model(&drop).Exec(ctx); err != nil {
				t.Fatal(err)
			}
			got, err := momo.Query[explByDefault](ctx, db, "SELECT id, body FROM default_rows")
			if err != nil {
				t.Fatal(err)
			}
			ids := map[string]int64{}
			for _, r := range got {
				ids[r.Body] = r.ID
			}
			if ids["a"] != 700 || ids["b"] != 701 || ids["c"] != 800 {
				t.Errorf("ids = %v, want a=700 b=701 c=800", ids)
			}
			if ids["d"] == 900 || ids["d"] == 0 {
				t.Errorf("without Explicit id = %d, want a generated one", ids["d"])
			}
		})
	}
}

// Catches: a GENERATED ALWAYS identity column that PostgreSQL still refuses
// ("cannot insert a non-DEFAULT value") because Explicit did not render
// OVERRIDING SYSTEM VALUE, in a single statement and in every chunk of a bulk
// insert, or an insert without Explicit that no longer generates the value.
func TestInsertExplicitIdentityAlwaysPostgres(t *testing.T) {
	db := testopen.Postgres(t)
	ctx := context.Background()
	explicitExec(t, db, "CREATE TABLE always_rows (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, body text NOT NULL)")

	if _, err := momo.Insert[explAlways](db).Model(&explAlways{ID: 41, Body: "one"}).Explicit(explAID).Exec(ctx); err != nil {
		t.Fatalf("explicit insert on a GENERATED ALWAYS column: %v", err)
	}
	many := make([]explAlways, 0, 40000) // 2 columns per row: over one statement's 65535 parameters
	for i := range 40000 {
		many = append(many, explAlways{ID: int64(1000 + i), Body: "bulk"})
	}
	if _, err := momo.Insert[explAlways](db).Models(many).Explicit(explAID).Exec(ctx); err != nil {
		t.Fatalf("chunked explicit insert: %v", err)
	}
	if _, err := momo.Insert[explAlways](db).Model(&explAlways{ID: 99999, Body: "gen"}).Exec(ctx); err != nil {
		t.Fatalf("insert without Explicit: %v", err)
	}
	got, err := momo.Query[explAlways](ctx, db, "SELECT id, body FROM always_rows")
	if err != nil {
		t.Fatal(err)
	}
	ids := make([]int64, 0, len(got))
	for _, r := range got {
		ids = append(ids, r.ID)
	}
	slices.Sort(ids)
	if len(ids) != 40002 || !slices.Contains(ids, 41) || !slices.Contains(ids, 1000) || !slices.Contains(ids, 40999) || slices.Contains(ids, 99999) {
		t.Fatalf("%d ids stored, want 40002 with 41, 1000 and 40999 kept and 99999 replaced by a generated id", len(ids))
	}
}
