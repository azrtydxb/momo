package momo_test

import (
	"context"
	"errors"
	"testing"

	"github.com/azrtydxb/momo"
	"github.com/azrtydxb/momo/dialect"
	"github.com/azrtydxb/momo/internal/testdb/testopen"
)

const mysqlUsersDDL = "CREATE TABLE mr_users (id bigint NOT NULL AUTO_INCREMENT PRIMARY KEY, email varchar(100) NOT NULL UNIQUE, name varchar(100) NOT NULL)"

func mrUsers(t *testing.T, db *momo.DB) []mrUserT {
	t.Helper()
	rows, err := momo.Query[mrUserT](context.Background(), db, "SELECT id, email, name FROM mr_users ORDER BY id")
	if err != nil {
		t.Fatal(err)
	}
	return rows
}

// Catches: an upsert on UNIQUE(email) with an explicit AUTO_INCREMENT primary
// key reaching a real MySQL or MariaDB server. The refusal must be ErrUnsupported
// before any statement is sent: neither the seeded row is updated nor a new row
// is written, for DoUpdate, DoNothing and several rows.
func TestUpsertSecondaryTargetWithExplicitKeyWritesNothingOnMySQL(t *testing.T) {
	testopen.EachMySQL(t, func(t *testing.T, db *momo.DB) {
		ctx := context.Background()
		explicitExec(t, db, mysqlUsersDDL)
		explicitExec(t, db, "INSERT INTO mr_users (id, email, name) VALUES (1, 'a@example.com', 'seed')")

		hit := mrUserT{ID: 2, Email: "a@example.com", Name: "changed"}
		fresh := []mrUserT{{ID: 3, Email: "b@example.com", Name: "b"}, {ID: 4, Email: "c@example.com", Name: "c"}}
		attempts := map[string]func() error{
			"DoUpdate": func() error {
				_, err := momo.Upsert[mrUserT](db).Model(&hit).Explicit(mrUserID).
					OnConflict(mrUserEmail).DoUpdate(mrUserName.SetExcluded()).Exec(ctx)
				return err
			},
			"DoNothing": func() error {
				_, err := momo.Upsert[mrUserT](db).Model(&hit).Explicit(mrUserID).
					OnConflict(mrUserEmail).DoNothing().Exec(ctx)
				return err
			},
			"Models": func() error {
				_, err := momo.Upsert[mrUserT](db).Models(fresh).Explicit(mrUserID).
					OnConflict(mrUserEmail).DoUpdate(mrUserName.SetExcluded()).Exec(ctx)
				return err
			},
		}
		for name, run := range attempts {
			if err := run(); !errors.Is(err, momo.ErrUnsupported) {
				t.Errorf("%s: err = %v, want ErrUnsupported", name, err)
			}
		}
		rows := mrUsers(t, db)
		if len(rows) != 1 || rows[0].ID != 1 || rows[0].Email != "a@example.com" || rows[0].Name != "seed" {
			t.Fatalf("rows = %+v, want only the untouched seed row", rows)
		}
	})
}

// Catches: PostgreSQL or SQLite mishandling the same call. ON CONFLICT names
// the email key, so a conflict on email updates the existing row and keeps its
// id (the explicit id of the losing row is discarded), while a row that does not
// conflict is stored with the explicit id.
func TestUpsertSecondaryTargetWithExplicitKeyOnPostgresAndSQLite(t *testing.T) {
	testopen.Each(t, func(t *testing.T, db *momo.DB, d dialect.Name) {
		ctx := context.Background()
		ddl := "CREATE TABLE mr_users (id INTEGER PRIMARY KEY AUTOINCREMENT, email TEXT NOT NULL UNIQUE, name TEXT NOT NULL)"
		if d == dialect.Postgres {
			ddl = "CREATE TABLE mr_users (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email text NOT NULL UNIQUE, name text NOT NULL)"
		}
		explicitExec(t, db, ddl)
		explicitExec(t, db, "INSERT INTO mr_users (id, email, name) VALUES (1, 'a@example.com', 'seed')")

		hit := mrUserT{ID: 2, Email: "a@example.com", Name: "changed"}
		if _, err := momo.Upsert[mrUserT](db).Model(&hit).Explicit(mrUserID).
			OnConflict(mrUserEmail).DoUpdate(mrUserName.SetExcluded()).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		fresh := mrUserT{ID: 50, Email: "b@example.com", Name: "b"}
		if _, err := momo.Upsert[mrUserT](db).Model(&fresh).Explicit(mrUserID).
			OnConflict(mrUserEmail).DoUpdate(mrUserName.SetExcluded()).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		rows := mrUsers(t, db)
		if len(rows) != 2 || rows[0].ID != 1 || rows[0].Name != "changed" || rows[1].ID != 50 || rows[1].Email != "b@example.com" {
			t.Fatalf("rows = %+v, want id 1 updated in place and id 50 inserted", rows)
		}
	})
}
