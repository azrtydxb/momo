func TestImportCommand(t *testing.T) {
	src := filepath.Join("..", "..", "internal", "compat", "gormfixture")
	dst := t.TempDir()
	var out, errOut bytes.Buffer
	code := runImport(&out, &errOut, []string{"gorm", "--src", src, "--out", dst})
	if code != 0 {
		t.Fatalf("exit %d: %s", code, errOut.String())
	}
	b, err := os.ReadFile(filepath.Join(dst, "models.go")) // #nosec G304 -- a path inside the test's own temporary directory
	if err != nil || !strings.Contains(string(b), "Code generated by momo") {
		t.Fatalf("models.go missing or not marked generated: %v", err)
	}
	if !strings.Contains(out.String(), "zero-value-handling") {
		t.Fatalf("report not printed: %s", out.String())
	}
}

func TestImportRefusesUnsupported(t *testing.T) {
	src := t.TempDir()
	if err := os.WriteFile(filepath.Join(src, "schema.go"), []byte("package schema\nimport \"entgo.io/ent\"\ntype X struct{ ent.Schema }\nfunc (X) Fields() []ent.Field { return nil }\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	dst := t.TempDir()
	var out, errOut bytes.Buffer
	if code := runImport(&out, &errOut, []string{"ent", "--src", src, "--out", dst}); code != 1 {
		t.Fatalf("unsupported builder must exit 1, got %d (stderr: %s)", code, errOut.String())
	}
	if _, err := os.Stat(filepath.Join(dst, "models.go")); err == nil {
		t.Fatal("nothing may be written when the report is unsupported")
	}
}

func TestImportUsageErrors(t *testing.T) {
	for name, args := range map[string][]string{
		"no source":      {},
		"unknown source": {"sqlalchemy", "--src", "x", "--out", "y"},
		"missing flags":  {"gorm"},
		"extra argument": {"gorm", "--src", "x", "--out", "y", "z"},
	} {
		var out, errOut bytes.Buffer
		if code := runImport(&out, &errOut, args); code != 2 {
			t.Errorf("%s: exit %d, want 2", name, code)
		}
	}
	var out, errOut bytes.Buffer
	if code := Run([]string{"import", "-h"}, &out, &errOut); code != 0 || !strings.Contains(out.String(), "momo import") {
		t.Fatalf("help: exit %d, out %q", code, out.String())
	}
}

func TestImportHelpFlagAsValueIsNotHelp(t *testing.T) {
	var out, errOut bytes.Buffer
	code := runImport(&out, &errOut, []string{"gorm", "--src", "-h", "--out", t.TempDir()})
	if code != 2 || strings.Contains(out.String(), "Usage:") {
		t.Fatalf("-h as the value of --src must not print help: exit %d, out %q", code, out.String())
	}
}

func TestImportWritesReportFile(t *testing.T) {
	src := filepath.Join("..", "..", "internal", "compat", "gormfixture")
	dst := t.TempDir()
	rf := filepath.Join(t.TempDir(), "report.txt")
	var out, errOut bytes.Buffer
	if code := runImport(&out, &errOut, []string{"gorm", "--src", src, "--out", dst, "--report", rf}); code != 0 {
		t.Fatalf("exit %d: %s", code, errOut.String())
	}
	b, err := os.ReadFile(rf) // #nosec G304 -- a path inside the test's own temporary directory
	if err != nil || string(b) != out.String() {
		t.Fatalf("report file differs from the printed report: %v", err)
	}
}
