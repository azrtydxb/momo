// Catches: plugins built in a different order from run to run, an unknown
// plugin or option accepted silently, or a relative dir that is not placed
// under the output base.
func TestPluginRegistration(t *testing.T) {
	ps, err := buildPlugins(map[string]map[string]any{
		"viz":     {"format": "mermaid", "dir": "docs/er"},
		"openapi": {"dir": "api", "title": "t", "version": "1", "base_path": "/v1", "handlers": true},
		"grpc":    {"dir": "rpc", "proto_package": "acme.v1", "go_package": "example.com/app/pb"},
		"graphql": {"dir": "graph", "models_package": "example.com/app/models"},
	}, "")
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, p := range ps {
		names = append(names, p.Name())
	}
	if strings.Join(names, ",") != "graphql,grpc,openapi,viz" {
		t.Fatalf("order=%v", names)
	}
	wantPlugins := []gen.Plugin{
		graphql.Plugin{Dir: "graph", ModelsPackage: "example.com/app/models"},
		grpc.Plugin{Dir: "rpc", ProtoPackage: "acme.v1", GoPackage: "example.com/app/pb"},
		openapi.Plugin{Dir: "api", Options: openapi.Options{Title: "t", Version: "1", BasePath: "/v1", Handlers: true}},
		viz.Plugin{Format: "mermaid", Out: "docs/er"},
	}
	if !reflect.DeepEqual(ps, wantPlugins) {
		t.Fatalf("options not mapped:\n got %#v\nwant %#v", ps, wantPlugins)
	}
	if _, err := buildPlugins(map[string]map[string]any{"soap": {}}, ""); err == nil || !strings.Contains(err.Error(), `unknown plugin "soap"`) {
		t.Fatalf("unknown plugin: %v", err)
	}
	if _, err := buildPlugins(map[string]map[string]any{"viz": {"colour": "red"}}, ""); err == nil || !strings.Contains(err.Error(), `unknown option "colour"`) {
		t.Fatalf("unknown option: %v", err)
	}

	out := filepath.Join(string(filepath.Separator), "work")
	ps, err = buildPlugins(map[string]map[string]any{"viz": {"format": "dot", "dir": "docs/er"}}, out)
	if err != nil {
		t.Fatal(err)
	}
	if want := (viz.Plugin{Format: "dot", Out: filepath.Join(out, "docs/er")}); len(ps) != 1 || !reflect.DeepEqual(ps[0], want) {
		t.Fatalf("plugins = %#v, want %#v", ps, want)
	}

	for name, cfg := range map[string]map[string]map[string]any{
		"viz format":      {"viz": {"format": "svg"}},
		"string option":   {"openapi": {"dir": "a", "title": 3}},
		"bool option":     {"openapi": {"dir": "a", "handlers": "yes"}},
		"missing dir":     {"graphql": {"package": "graph"}},
		"viz dir missing": {"viz": {"dir": 4}},
	} {
		if _, err := buildPlugins(cfg, ""); err == nil {
			t.Errorf("%s: accepted", name)
		}
	}
}

// Catches: the plugins section of momo.yaml not reaching the generator, or a
// relative dir resolved against the working directory instead of momo.yaml.
func TestGenerateRunsConfiguredPlugins(t *testing.T) {
	root := copyModule(t, exampleSrc)
	cfg := "version: 1\nplugins:\n  viz:\n    format: dot\n    dir: docs/er\n"
	if err := os.WriteFile(filepath.Join(root, "momo.yaml"), []byte(cfg), 0o600); err != nil {
		t.Fatal(err)
	}
	chdir(t, filepath.Join(root, "billing"))
	var out, errb bytes.Buffer
	if code := Run([]string{"generate"}, &out, &errb); code != 0 {
		t.Fatalf("generate: exit %d\n%s%s", code, out.String(), errb.String())
	}
	b, err := os.ReadFile(filepath.Join(root, "docs", "er", "schema.dot")) //nolint:gosec // test path
	if err != nil {
		t.Fatalf("the viz plugin did not write its diagram next to momo.yaml: %v", err)
	}
	if !strings.Contains(string(b), "Code generated by momo") {
		t.Errorf("diagram lacks the generated header:\n%s", b)
	}
}

// Catches: the ops and read_only options not reaching the plugins, an unknown
// operation accepted, or read_only overriding a model's own list.
func TestPluginOps(t *testing.T) {
	ps, err := buildPlugins(map[string]map[string]any{
		"openapi": {"dir": "api", "title": "t", "version": "1", "read_only": true},
		"grpc":    {"dir": "rpc", "ops": map[string]any{"Tag": []any{"list"}, "*": []any{"list", "get", "create"}}},
	}, "")
	if err != nil {
		t.Fatal(err)
	}
	if got := ps[0].(grpc.Plugin).Ops; !reflect.DeepEqual(got, apiquery.Ops{"Tag": {"list"}, "*": {"list", "get", "create"}}) {
		t.Errorf("grpc ops = %v", got)
	}
	if got := ps[1].(openapi.Plugin).Options.Ops; !reflect.DeepEqual(got, apiquery.Ops{"*": {"list", "get"}}) {
		t.Errorf("read_only ops = %v", got)
	}
	ps, err = buildPlugins(map[string]map[string]any{
		"openapi": {"dir": "api", "title": "t", "version": "1", "read_only": true, "ops": map[string]any{"Doc": []any{"list", "delete"}}},
	}, "")
	if err != nil {
		t.Fatal(err)
	}
	if got := ps[0].(openapi.Plugin).Options.Ops; !reflect.DeepEqual(got, apiquery.Ops{"Doc": {"list", "delete"}, "*": {"list", "get"}}) {
		t.Errorf("read_only with a model entry: %v", got)
	}
	for name, ops := range map[string]any{"unknown": []any{"drop"}, "empty": []any{}, "not a list": "list", "number": []any{1}} {
		if _, err := buildPlugins(map[string]map[string]any{"grpc": {"dir": "rpc", "ops": ops}}, ""); err == nil {
			t.Errorf("%s: accepted", name)
		}
	}
	if _, err := buildPlugins(map[string]map[string]any{"graphql": {"dir": "g", "ops": []any{"list"}}}, ""); err == nil {
		t.Error("graphql takes no ops")
	}
}
