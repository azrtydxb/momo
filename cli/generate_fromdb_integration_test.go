// legacyDDL is a small schema built by hand: serial and identity keys, a
// composite key, an enum, array, jsonb and numeric columns, defaults with
// commas, named and unnamed constraints, partial and unique indexes, and
// foreign keys with and without actions.
var legacyDDL = []string{
	`CREATE TYPE ticket_state AS ENUM ('open', 'closed')`,
	`CREATE TYPE "TicketPhase" AS ENUM ('new', 'done')`,
	`CREATE TABLE accounts (
		id bigserial PRIMARY KEY,
		email varchar(200) NOT NULL,
		name text,
		created_at timestamptz NOT NULL DEFAULT now(),
		settings jsonb,
		balance numeric(12,2) NOT NULL DEFAULT 0,
		normalized text GENERATED ALWAYS AS (lower(name)) STORED,
		label text GENERATED ALWAYS AS (coalesce(name, '') || ':' || email) STORED)`,
	`CREATE UNIQUE INDEX accounts_email_key ON accounts (email)`,
	// A unique expression index (issue 55).
	`CREATE UNIQUE INDEX accounts_email_lower_key ON accounts (lower(email))`,
	`CREATE TABLE projects (
		id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		account_id bigint NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
		title text NOT NULL,
		tags text[],
		archived boolean NOT NULL DEFAULT false,
		CHECK (char_length(title) > 0))`,
	`CREATE INDEX projects_account_id_idx ON projects (account_id)`,
	`CREATE INDEX projects_open_idx ON projects (account_id, title) WHERE NOT archived`,
	`CREATE TABLE tickets (
		id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
		project_id bigint REFERENCES projects (id) ON DELETE SET NULL,
		state ticket_state NOT NULL DEFAULT 'open',
		phase "TicketPhase" NOT NULL DEFAULT 'new',
		opened_at timestamp NOT NULL DEFAULT now(),
		body text NOT NULL DEFAULT 'a,b',
		CONSTRAINT tickets_project_state_key UNIQUE (project_id, state))`,
	`CREATE TABLE project_members (
		project_id bigint NOT NULL REFERENCES projects (id),
		account_id bigint NOT NULL REFERENCES accounts (id),
		role text NOT NULL,
		PRIMARY KEY (project_id, account_id))`,
	// A composite foreign key into the composite primary key (issue 54) on a
	// GENERATED ALWAYS identity key (issue 56).
	`CREATE TABLE project_notes (
		id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
		project_id bigint NOT NULL,
		account_id bigint NOT NULL,
		body text NOT NULL,
		CONSTRAINT project_notes_member_fkey FOREIGN KEY (project_id, account_id)
			REFERENCES project_members (project_id, account_id) ON DELETE CASCADE)`,
}

func execAll(t *testing.T, dsn string, stmts []string) {
	t.Helper()
	db, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = db.Close() })
	for _, s := range stmts {
		if _, err := db.ExecContext(context.Background(), s); err != nil {
			t.Fatalf("%v\n%s", err, s)
		}
	}
}

func fromDB(t *testing.T, args ...string) (code int, out, errOut string) {
	t.Helper()
	var o, e bytes.Buffer
	code = Run(append([]string{"generate", "--from-db", "MOMO_TEST_URL"}, args...), &o, &e)
	return code, o.String(), e.String()
}

// TestGenerateFromDBBaseline is the adoption path end to end: inspect a
// database, write the models and the init snapshot, generate, and baseline
// against the same database with no hand edit and no drift.
func TestGenerateFromDBBaseline(t *testing.T) {
	dsn := testdb.PostgresURL(t)
	execAll(t, dsn, legacyDDL)
	root := copyModule(t, t.TempDir())
	writeFile(t, filepath.Join(root, "momo.yaml"), `version: 1
packages:
  - ./models
dialects: [postgres]
migrate:
  dir:
    postgres: migrations/postgres
  url_env:
    postgres: MOMO_TEST_URL
  exclude: [vector, pgcrypto]
introspect:
  columns:
    - match: accounts.created_at
      tags: [created_at]
`)
	chdir(t, root)
	t.Setenv("MOMO_TEST_URL", dsn)

	code, out, errOut := fromDB(t)
	if code != 0 {
		t.Fatalf("generate --from-db: exit %d\n%s%s", code, out, errOut)
	}
	for _, want := range []string{"accounts_model.go", "project_members_model.go", "project_notes_model.go", "projects_model.go", "tickets_model.go"} {
		if _, err := os.Stat(filepath.Join(root, "models", want)); err != nil {
			t.Fatalf("missing %s: %v\n%s", want, err, out)
		}
	}
	notes, err := os.ReadFile(filepath.Join(root, "models", "project_notes_model.go")) //nolint:gosec // test path
	if err != nil || !strings.Contains(string(notes), `c.ForeignKey("project_notes_member_fkey"`) || !strings.Contains(string(notes), "identity:always") {
		t.Fatalf("the composite foreign key is not declared: %v\n%s", err, notes)
	}
	accts, err := os.ReadFile(filepath.Join(root, "models", "accounts_model.go")) //nolint:gosec // test path
	if err != nil || !strings.Contains(string(accts), `c.IndexExpr("accounts_email_lower_key"`) || !strings.Contains(string(accts), ".Unique()") {
		t.Fatalf("the unique expression index is not declared: %v\n%s", err, accts)
	}
	if !strings.Contains(string(accts), "generated:lower(name)") || !strings.Contains(string(accts), `c.Generated(&m.Label, `) || !strings.Contains(string(accts), "read_only") {
		t.Fatalf("the stored generated columns are not modeled as read-only fields: %s", accts)
	}
	if strings.Contains(out, "generated column is not modeled") {
		t.Fatalf("a stored generated column must not warn:\n%s", out)
	}
	files, _ := filepath.Glob(filepath.Join(root, "migrations", "postgres", "*_init.up.sql"))
	if len(files) != 1 {
		t.Fatalf("init migration: %v\n%s", files, out)
	}
	if initSQL, err := os.ReadFile(files[0]); err != nil || !strings.Contains(string(initSQL), "GENERATED ALWAYS AS (lower(") { //nolint:gosec // test path
		t.Fatalf("the init migration does not render the generated column: %v\n%s", err, initSQL)
	}
	version := strings.SplitN(filepath.Base(files[0]), "_", 2)[0]

	var o, e bytes.Buffer
	if c := Run([]string{"generate"}, &o, &e); c != 0 {
		t.Fatalf("generate: exit %d\n%s%s", c, o.String(), e.String())
	}
	if c, o, e := cliRun(t, dsn, "baseline", "--version", version); c != 0 {
		t.Fatalf("baseline: exit %d\n%s%s", c, o, e)
	}
	if c, o, e := cliRun(t, dsn, "diff", "after"); c != 0 || !strings.Contains(o, "no changes") {
		t.Fatalf("diff after baseline must be empty: exit %d\n%s%s", c, o, e)
	}
	if c, o, e := cliRun(t, dsn, "drift"); c != 0 {
		t.Fatalf("drift: exit %d\n%s%s", c, o, e)
	}

	// A second run changes nothing.
	code, out, errOut = fromDB(t)
	if code != 0 || strings.Contains(out, "create:") || strings.Contains(out, "update:") || !strings.Contains(out, "already holds the snapshot") {
		t.Fatalf("re-run: exit %d\n%s%s", code, out, errOut)
	}
	if code, out, _ = fromDB(t, "--check"); code != 0 {
		t.Fatalf("--check on a current tree: exit %d\n%s", code, out)
	}
}

// TestGenerateFromDBRerun changes the database and re-runs: a file nobody
// edited is rewritten, a hand-edited one is kept and reported.
func TestGenerateFromDBRerun(t *testing.T) {
	dsn := testdb.PostgresURL(t)
	execAll(t, dsn, legacyDDL)
	root := copyModule(t, t.TempDir())
	writeFile(t, filepath.Join(root, "momo.yaml"), "version: 1\npackages:\n  - ./models\ndialects: [postgres]\nmigrate:\n  exclude: [vector, pgcrypto]\n")
	chdir(t, root)
	t.Setenv("MOMO_TEST_URL", dsn)
	if code, out, errOut := fromDB(t, "--no-snapshot"); code != 0 {
		t.Fatalf("first run: exit %d\n%s%s", code, out, errOut)
	}
	accounts := filepath.Join(root, "models", "accounts_model.go")
	b, err := os.ReadFile(accounts) //nolint:gosec // test path
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(accounts, append(b, []byte("\n// kept by hand\n")...), 0o600); err != nil {
		t.Fatal(err)
	}
	execAll(t, dsn, []string{
		`ALTER TABLE accounts ADD COLUMN nickname text`,
		`ALTER TABLE projects ADD COLUMN notes text`,
	})
	code, out, errOut := fromDB(t, "--no-snapshot")
	if code != 1 || !strings.Contains(out, "conflict: models/accounts_model.go") || !strings.Contains(out, "update: models/projects_model.go") {
		t.Fatalf("re-run: exit %d, want 1 with a conflict and an update\n%s%s", code, out, errOut)
	}
	kept, _ := os.ReadFile(accounts) //nolint:gosec // test path
	if !strings.Contains(string(kept), "kept by hand") || strings.Contains(string(kept), "Nickname") {
		t.Fatal("the hand-edited file was changed")
	}
	side, err := os.ReadFile(accounts + ".new") //nolint:gosec // test path
	if err != nil || !strings.Contains(string(side), "Nickname") {
		t.Fatalf("regenerated version: %v", err)
	}
	projects, _ := os.ReadFile(filepath.Join(root, "models", "projects_model.go")) //nolint:gosec // test path
	if !strings.Contains(string(projects), "Notes") {
		t.Fatal("the untouched file was not updated")
	}
	if code, out, errOut = fromDB(t, "--no-snapshot", "--overwrite"); code != 0 {
		t.Fatalf("--overwrite: exit %d\n%s%s", code, out, errOut)
	}
	replaced, _ := os.ReadFile(accounts) //nolint:gosec // test path
	if !strings.Contains(string(replaced), "Nickname") {
		t.Fatal("--overwrite did not replace the file")
	}
}

// TestGenerateFromDBSnapshotFailureWritesNoModels: a migration directory whose
// snapshot cannot be read fails the init snapshot step; the model files must
// not have been written by then.
func TestGenerateFromDBSnapshotFailureWritesNoModels(t *testing.T) {
	dsn := testdb.PostgresURL(t)
	execAll(t, dsn, legacyDDL)
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "momo.yaml"), "version: 1\npackages:\n  - ./models\ndialects: [postgres]\nmigrate:\n  dir:\n    postgres: migrations/postgres\n  exclude: [vector, pgcrypto]\n")
	writeFile(t, filepath.Join(root, "migrations", "postgres", "20260101000000_bad.snapshot.json"), "not json")
	chdir(t, root)
	t.Setenv("MOMO_TEST_URL", dsn)
	code, out, errOut := fromDB(t)
	if code == 0 {
		t.Fatalf("a broken snapshot must fail the run\n%s%s", out, errOut)
	}
	if entries, _ := filepath.Glob(filepath.Join(root, "models", "*")); len(entries) != 0 {
		t.Fatalf("model files were left behind: %v", entries)
	}
}

// TestGenerateFromDBOnly is introspect.only end to end: a table outside the
// list gets no model and no place in the init snapshot, and migrate treats it
// as excluded, so baseline and drift see no unmanaged table.
func TestGenerateFromDBOnly(t *testing.T) {
	dsn := testdb.PostgresURL(t)
	execAll(t, dsn, legacyDDL)
	root := copyModule(t, t.TempDir())
	writeFile(t, filepath.Join(root, "momo.yaml"), `version: 1
packages:
  - ./models
dialects: [postgres]
migrate:
  dir:
    postgres: migrations/postgres
  url_env:
    postgres: MOMO_TEST_URL
  exclude: [vector, pgcrypto, project_notes]
introspect:
  only: [accounts, projects, project_*]
  skip: [project_notes]
`)
	chdir(t, root)
	t.Setenv("MOMO_TEST_URL", dsn)
	if code, out, errOut := fromDB(t); code != 0 {
		t.Fatalf("generate --from-db: exit %d\n%s%s", code, out, errOut)
	}
	for _, name := range []string{"accounts_model.go", "projects_model.go", "project_members_model.go"} {
		if _, err := os.Stat(filepath.Join(root, "models", name)); err != nil {
			t.Fatalf("missing %s: %v", name, err)
		}
	}
	for _, name := range []string{"tickets_model.go", "project_notes_model.go"} {
		if _, err := os.Stat(filepath.Join(root, "models", name)); err == nil {
			t.Fatalf("%s: a table outside only (or skipped inside it) got a model", name)
		}
	}
	files, _ := filepath.Glob(filepath.Join(root, "migrations", "postgres", "*_init.up.sql"))
	if len(files) != 1 {
		t.Fatalf("init migration: %v", files)
	}
	sqlText, err := os.ReadFile(files[0]) //nolint:gosec // test path
	if err != nil || strings.Contains(string(sqlText), "tickets") || strings.Contains(string(sqlText), "project_notes") {
		t.Fatalf("the init snapshot holds a table outside only: %v\n%s", err, sqlText)
	}
	version := strings.SplitN(filepath.Base(files[0]), "_", 2)[0]
	var o, e bytes.Buffer
	if c := Run([]string{"generate"}, &o, &e); c != 0 {
		t.Fatalf("generate: exit %d\n%s%s", c, o.String(), e.String())
	}
	if c, o, e := cliRun(t, dsn, "baseline", "--version", version); c != 0 {
		t.Fatalf("baseline: exit %d\n%s%s", c, o, e)
	}
	if c, o, e := cliRun(t, dsn, "drift"); c != 0 {
		t.Fatalf("drift must not report the tables outside only: exit %d\n%s%s", c, o, e)
	}
}

// TestGenerateFromDBDBDefaultAll is issue 77 against a real PostgreSQL: a NOT
// NULL column with a constant default is tagged dbdefault with
// introspect.dbdefault: all, and the generated metadata carries the flag, so
// Insert.Model leaves the unset field to the database default.
func TestGenerateFromDBDBDefaultAll(t *testing.T) {
	dsn := testdb.PostgresURL(t)
	execAll(t, dsn, []string{`CREATE TABLE overrides (
		id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		name text NOT NULL,
		version bigint NOT NULL DEFAULT 1,
		active boolean NOT NULL DEFAULT true)`})
	root := copyModule(t, t.TempDir())
	writeFile(t, filepath.Join(root, "momo.yaml"), "version: 1\npackages:\n  - ./models\ndialects: [postgres]\nmigrate:\n  exclude: [vector, pgcrypto]\nintrospect:\n  dbdefault: all\n")
	chdir(t, root)
	t.Setenv("MOMO_TEST_URL", dsn)
	if code, out, errOut := fromDB(t, "--no-snapshot"); code != 0 {
		t.Fatalf("generate --from-db: exit %d\n%s%s", code, out, errOut)
	}
	src, err := os.ReadFile(filepath.Join(root, "models", "overrides_model.go")) //nolint:gosec // test path
	if err != nil || !strings.Contains(string(src), `momo:"default:1,dbdefault"`) {
		t.Fatalf("version must carry dbdefault: %v\n%s", err, src)
	}
	// A non-zero constant default makes the field a pointer, so an explicit 0
	// or false is written (issue 90), and generate then has nothing to warn about.
	if m := regexp.MustCompile(`Version\s+\*int64\s`).Find(src); m == nil {
		t.Fatalf("Version must be a pointer:\n%s", src)
	}
	if m := regexp.MustCompile(`Active\s+\*bool\s`).Find(src); m == nil {
		t.Fatalf("Active must be a pointer:\n%s", src)
	}
	var o, e bytes.Buffer
	if c := Run([]string{"generate"}, &o, &e); c != 0 {
		t.Fatalf("generate: exit %d\n%s%s", c, o.String(), e.String())
	}
	if strings.Contains(e.String(), "warning:") {
		t.Fatalf("generate warns about pointer dbdefault fields: %s", e.String())
	}
	meta, err := os.ReadFile(filepath.Join(root, "models", "momo_gen.go")) //nolint:gosec // test path
	if err != nil || !strings.Contains(string(meta), "FlagDBDefault") {
		t.Fatalf("the generated metadata has no FlagDBDefault: %v\n%s", err, meta)
	}
}

// TestGenerateFromDBOnlySchemaQualified is `only: ["app.*"]` end to end: the
// glob matches schema.name like migrate.exclude does, so the tables of the app
// schema get models and the table in the current schema does not.
func TestGenerateFromDBOnlySchemaQualified(t *testing.T) {
	dsn := testdb.PostgresURL(t)
	execAll(t, dsn, []string{
		`DROP SCHEMA IF EXISTS app CASCADE`,
		`CREATE SCHEMA app`,
		`CREATE TABLE app.widgets (id bigint PRIMARY KEY, name text NOT NULL)`,
		`CREATE TABLE app.gadgets (id bigint PRIMARY KEY, name text NOT NULL)`,
		`CREATE TABLE legacy_only (id bigint PRIMARY KEY)`,
	})
	t.Cleanup(func() { execAll(t, dsn, []string{`DROP SCHEMA IF EXISTS app CASCADE`}) })
	// The test database runs in a schema of its own, which must come first.
	db, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = db.Close() })
	var current string
	if err := db.QueryRowContext(context.Background(), `SELECT current_schema()`).Scan(&current); err != nil {
		t.Fatal(err)
	}
	root := copyModule(t, t.TempDir())
	writeFile(t, filepath.Join(root, "momo.yaml"), `version: 1
packages:
  - ./models
dialects: [postgres]
migrate:
  schemas: [`+current+`, app]
  exclude: [vector, pgcrypto]
introspect:
  only: ["app.*"]
`)
	chdir(t, root)
	t.Setenv("MOMO_TEST_URL", dsn)
	if code, out, errOut := fromDB(t, "--no-snapshot"); code != 0 {
		t.Fatalf("generate --from-db: exit %d\n%s%s", code, out, errOut)
	}
	for _, name := range []string{"app_widgets_model.go", "app_gadgets_model.go"} {
		if _, err := os.Stat(filepath.Join(root, "models", name)); err != nil {
			t.Fatalf("missing %s: %v", name, err)
		}
	}
	if _, err := os.Stat(filepath.Join(root, "models", "legacy_only_model.go")); err == nil {
		t.Fatal("a table outside only got a model")
	}
}
