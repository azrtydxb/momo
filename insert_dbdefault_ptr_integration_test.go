// dbdPtrLive is the pointer form of dbdLive: NOT NULL columns that default to
// true and 3.
type dbdPtrLive struct {
	ID     int64
	Name   string
	Active *bool
	Level  *int64
}

var dbdPtrLiveMeta = momo.Meta[dbdPtrLive]{
	Table: "dbd_ptr_live",
	Columns: []momo.ColumnMeta{
		{Name: "id", Flags: momo.FlagPK | momo.FlagIdentity},
		{Name: "name"},
		{Name: "active", Flags: momo.FlagHasDefault | momo.FlagDBDefault},
		{Name: "level", Flags: momo.FlagHasDefault | momo.FlagDBDefault},
	},
	Ptr:      func(m *dbdPtrLive, i int) any { return [...]any{&m.ID, &m.Name, &m.Active, &m.Level}[i] },
	Value:    func(m *dbdPtrLive, i int) any { return [...]any{m.ID, m.Name, m.Active, m.Level}[i] },
	Identity: 0, Version: -1, SoftDelete: -1, CreatedAt: -1, UpdatedAt: -1,
	PK: []int{0},
}

func (*dbdPtrLive) MomoMeta() *momo.Meta[dbdPtrLive] { return &dbdPtrLiveMeta }

var dbdPtrLiveDDL = map[dialect.Name]string{
	dialect.Postgres: "CREATE TABLE dbd_ptr_live (id bigint generated by default as identity primary key, name text not null, active boolean not null default true, level bigint not null default 3)",
	dialect.SQLite:   "CREATE TABLE dbd_ptr_live (id integer primary key autoincrement, name text not null, active integer not null default 1, level integer not null default 3)",
	dialect.MySQL:    "CREATE TABLE dbd_ptr_live (id bigint primary key auto_increment, name varchar(100) not null, active boolean not null default true, level bigint not null default 3)",
}

// TestDBDefaultPointerLive is issue 90 against every available database: on a
// NOT NULL column with a non-zero default, a nil pointer takes the default and
// is read back, while a pointer to false or 0 is written as given. A dialect
// without RETURNING refuses the nil pointer (ErrUnsupported) but still writes
// explicit values.
func TestDBDefaultPointerLive(t *testing.T) {
	testopen.Each(t, func(t *testing.T, db *momo.DB, name dialect.Name) {
		ctx := context.Background()
		for _, stmt := range []string{"DROP TABLE IF EXISTS dbd_ptr_live", dbdPtrLiveDDL[name]} {
			if _, err := db.Driver().Exec(ctx, stmt, nil); err != nil {
				t.Fatalf("%s: %v", stmt, err)
			}
		}
		d := db.Driver().Dialect()
		stored := func(rowName string) (active, level int64) {
			rows, err := db.Driver().Query(ctx, "SELECT CASE WHEN active THEN 1 ELSE 0 END, level FROM dbd_ptr_live WHERE name = "+placeholder(db), []any{rowName})
			if err != nil {
				t.Fatal(err)
			}
			defer func() { _ = rows.Close() }()
			if !rows.Next() {
				t.Fatalf("row %q not stored", rowName)
			}
			if err := rows.Scan(&active, &level); err != nil {
				t.Fatal(err)
			}
			return active, level
		}

		// An explicit false and an explicit 0 are written, on every dialect.
		off := dbdPtrLive{Name: "off", Active: ptrTo(false), Level: ptrTo(int64(0))}
		if _, err := momo.Insert[dbdPtrLive](db).Model(&off).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if a, l := stored("off"); a != 0 || l != 0 {
			t.Fatalf("explicit false/0 stored as %d/%d, want 0/0", a, l)
		}
		if off.Active == nil || *off.Active || off.Level == nil || *off.Level != 0 {
			t.Fatalf("the pointers the caller set changed: %+v", off)
		}

		// An explicit true and 9 are written too.
		on := dbdPtrLive{Name: "on", Active: ptrTo(true), Level: ptrTo(int64(9))}
		if _, err := momo.Insert[dbdPtrLive](db).Model(&on).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if a, l := stored("on"); a != 1 || l != 9 {
			t.Fatalf("explicit true/9 stored as %d/%d", a, l)
		}

		// nil takes the database default and is read back into the pointer.
		unset := dbdPtrLive{Name: "unset"}
		_, err := momo.Insert[dbdPtrLive](db).Model(&unset).Exec(ctx)
		if !d.Returning && !d.InsertReturning {
			if !errors.Is(err, momo.ErrUnsupported) {
				t.Fatalf("%s cannot read the default back: err = %v, want ErrUnsupported", name, err)
			}
			return
		}
		if err != nil {
			t.Fatal(err)
		}
		if unset.Active == nil || !*unset.Active || unset.Level == nil || *unset.Level != 3 {
			t.Fatalf("defaults not read back into the pointers: %+v", unset)
		}
		if a, l := stored("unset"); a != 1 || l != 3 {
			t.Fatalf("nil stored as %d/%d, want the defaults 1/3", a, l)
		}

		// One statement mixing nil, an explicit false and an explicit 0.
		if !d.DefaultInValues {
			return // SQLite cannot put DEFAULT in a row; the mix is refused elsewhere
		}
		mixed := []dbdPtrLive{
			{Name: "m1"},
			{Name: "m2", Active: ptrTo(false), Level: ptrTo(int64(0))},
			{Name: "m3", Active: ptrTo(true)},
		}
		if _, err := momo.Insert[dbdPtrLive](db).Models(mixed).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if a, l := stored("m1"); a != 1 || l != 3 {
			t.Fatalf("m1 stored %d/%d, want 1/3", a, l)
		}
		if a, l := stored("m2"); a != 0 || l != 0 {
			t.Fatalf("m2 stored %d/%d, want 0/0", a, l)
		}
		if a, l := stored("m3"); a != 1 || l != 3 {
			t.Fatalf("m3 stored %d/%d, want 1/3", a, l)
		}
		if mixed[0].Active == nil || !*mixed[0].Active || mixed[2].Level == nil || *mixed[2].Level != 3 {
			t.Fatalf("mixed rows not read back: %+v", mixed)
		}
	})
}

// TestDBDefaultPointerUpdateModelLive: Update.Model leaves a nil dbdefault
// pointer out of SET (writing NULL would fail on the NOT NULL column), so the
// column keeps its stored value; a pointer to false or 0 is written.
func TestDBDefaultPointerUpdateModelLive(t *testing.T) {
	testopen.Each(t, func(t *testing.T, db *momo.DB, name dialect.Name) {
		ctx := context.Background()
		for _, stmt := range []string{"DROP TABLE IF EXISTS dbd_ptr_live", dbdPtrLiveDDL[name]} {
			if _, err := db.Driver().Exec(ctx, stmt, nil); err != nil {
				t.Fatalf("%s: %v", stmt, err)
			}
		}
		stored := func(id int64) (active, level int64) {
			rows, err := db.Driver().Query(ctx, "SELECT CASE WHEN active THEN 1 ELSE 0 END, level FROM dbd_ptr_live WHERE id = "+placeholder(db), []any{id})
			if err != nil {
				t.Fatal(err)
			}
			defer func() { _ = rows.Close() }()
			if !rows.Next() {
				t.Fatalf("row %d not stored", id)
			}
			if err := rows.Scan(&active, &level); err != nil {
				t.Fatal(err)
			}
			return active, level
		}
		m := dbdPtrLive{Name: "u", Active: ptrTo(false), Level: ptrTo(int64(9))}
		if _, err := momo.Insert[dbdPtrLive](db).Model(&m).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if m.ID == 0 { // no RETURNING (MySQL): read the id back
			rows, err := db.Driver().Query(ctx, "SELECT id FROM dbd_ptr_live WHERE name = "+placeholder(db), []any{"u"})
			if err != nil {
				t.Fatal(err)
			}
			if !rows.Next() || rows.Scan(&m.ID) != nil {
				t.Fatal("cannot read the inserted id")
			}
			_ = rows.Close()
		}

		// nil Active: not in SET, the stored false stays; the explicit 0 is written.
		up := dbdPtrLive{ID: m.ID, Name: "u2", Level: ptrTo(int64(0))}
		if _, err := momo.Update[dbdPtrLive](db).Model(&up).Exec(ctx); err != nil {
			t.Fatalf("a nil dbdefault pointer must not fail the update: %v", err)
		}
		if a, l := stored(m.ID); a != 0 || l != 0 {
			t.Fatalf("stored %d/%d, want active unchanged (0) and level 0", a, l)
		}

		// An explicit true is written, and a nil Level now keeps the 0.
		up = dbdPtrLive{ID: m.ID, Name: "u3", Active: ptrTo(true)}
		if _, err := momo.Update[dbdPtrLive](db).Model(&up).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if a, l := stored(m.ID); a != 1 || l != 0 {
			t.Fatalf("stored %d/%d, want 1/0", a, l)
		}
	})
}
