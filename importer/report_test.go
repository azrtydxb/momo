func TestImportReportListsSemanticChanges(t *testing.T) {
	var r Report
	r.Add(Change{Kind: "zero-value-handling", Source: "models/user.go:12:2", Model: "User", Field: "Active", Message: "zero value false is omitted on Create"})
	r.Add(Change{Kind: "go-default", Source: "models/user.go:14:2", Model: "User", Field: "Role", Message: "Go default applied before insert"})
	out := r.String()
	if !strings.Contains(out, "zero-value-handling") || !strings.Contains(out, "go-default") {
		t.Fatalf("report lost a change: %s", out)
	}
	if !r.Has("go-default") || r.Has("implicit-save") {
		t.Fatal("Has reports the wrong kinds")
	}
}

func TestReportSortedBySource(t *testing.T) {
	var r Report
	r.Add(Change{Kind: Naming, Source: "b.go:1:1", Message: "second"})
	r.Add(Change{Kind: Naming, Source: "a.go:9:1", Message: "first"})
	lines := strings.Split(strings.TrimSpace(r.String()), "\n")
	if len(lines) != 2 || !strings.HasPrefix(lines[0], "a.go") {
		t.Fatalf("report not sorted by source: %q", lines)
	}
}

func sampleModels() []Model {
	return []Model{{
		Name: "User", Table: "app_users", Source: "m.go:3:1",
		Fields: []Field{
			{Name: "ID", Column: "id", GoType: "int64", PK: true, Source: "m.go:4:2"},
			{Name: "Email", Column: "email", GoType: "string", SQLType: "varchar(255)", Unique: true, Source: "m.go:5:2"},
			{Name: "Note", Column: "note", GoType: "*string", Nullable: true, Source: "m.go:6:2"},
			{Name: "Seen", Column: "seen", GoType: "time.Time", Default: "now()", DefaultKind: "db", Source: "m.go:7:2"},
			{Name: "Role", Column: "role", GoType: "string", Default: "member", DefaultKind: "go", Source: "m.go:8:2"},
		},
	}}
}

func TestEmitWritesModelsThroughWriter(t *testing.T) {
	root := t.TempDir()
	w := gen.NewWriter(gen.WriterOptions{ModuleRoot: root})
	if err := Emit(sampleModels(), &Report{}, w, filepath.Join(root, "models"), "models"); err != nil {
		t.Fatal(err)
	}
	if _, err := w.Commit(); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(root, "models", "models.go"))
	if err != nil {
		t.Fatal(err)
	}
	got := string(b)
	for _, want := range []string{
		"// Code generated by momo ",
		"package models",
		`"time"`,
		"momo.Model `momo:\"table:app_users\"`",
		"`momo:\"pk,column:id\"`",
		"`momo:\"column:email,type:varchar(255),notnull,unique\"`",
		"`momo:\"column:note\"`",
		"`momo:\"column:seen,notnull,default:now()\"`",
		"`momo:\"column:role,notnull\"`",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("emitted source lacks %q:\n%s", want, got)
		}
	}
	if strings.Contains(got, "default:member") {
		t.Error("a Go-side default must not become a database default")
	}
}

func TestEmitRefusesUnsupported(t *testing.T) {
	root := t.TempDir()
	w := gen.NewWriter(gen.WriterOptions{ModuleRoot: root})
	var rep Report
	rep.Add(Change{Kind: Unsupported, Source: "m.go:9:1", Message: "polymorphic association"})
	err := Emit(sampleModels(), &rep, w, filepath.Join(root, "models"), "models")
	if !errors.Is(err, ErrUnsupported) || !strings.Contains(err.Error(), "m.go:9:1") {
		t.Fatalf("want ErrUnsupported naming the source, got %v", err)
	}
	if len(w.Outputs()) != 0 {
		t.Fatal("Emit buffered output despite an unsupported change")
	}
}

func TestEmitRejectsUnsafeValues(t *testing.T) {
	root := t.TempDir()
	cases := map[string]func(*Model){
		"comma default":  func(m *Model) { m.Fields[1].Default = "'a,b'"; m.Fields[1].DefaultKind = "db" },
		"bad field name": func(m *Model) { m.Fields[1].Name = "Em ail" },
		"unknown qual":   func(m *Model) { m.Fields[1].GoType = "uuid.UUID" },
		"backtick table": func(m *Model) { m.Table = "a`b" },
	}
	for name, mutate := range cases {
		t.Run(name, func(t *testing.T) {
			ms := sampleModels()
			mutate(&ms[0])
			w := gen.NewWriter(gen.WriterOptions{ModuleRoot: root})
			if err := Emit(ms, &Report{}, w, filepath.Join(root, "models"), "models"); err == nil {
				t.Fatal("Emit accepted a value it cannot represent")
			}
		})
	}
}

func TestEmitRejectsUnsafeStructure(t *testing.T) {
	root := t.TempDir()
	cases := map[string]func(*[]Model){
		"type is a call":      func(m *[]Model) { (*m)[0].Fields[1].GoType = "int; var x = f()" },
		"type is an operator": func(m *[]Model) { (*m)[0].Fields[1].GoType = "a+b" },
		"duplicate field":     func(m *[]Model) { (*m)[0].Fields[2].Name = "Email" },
		"field named Model":   func(m *[]Model) { (*m)[0].Fields[2].Name = "Model" },
		"model named momo":    func(m *[]Model) { (*m)[0].Name = "momo" },
		"duplicate model":     func(m *[]Model) { *m = append(*m, (*m)[0]) },
	}
	for name, mutate := range cases {
		t.Run(name, func(t *testing.T) {
			ms := sampleModels()
			mutate(&ms)
			w := gen.NewWriter(gen.WriterOptions{ModuleRoot: root})
			if err := Emit(ms, &Report{}, w, filepath.Join(root, "models"), "models"); err == nil {
				t.Fatal("Emit accepted unsafe input")
			}
		})
	}
	w := gen.NewWriter(gen.WriterOptions{ModuleRoot: root})
	if err := Emit(sampleModels(), &Report{}, w, filepath.Join(root, "models"), "_"); err == nil {
		t.Fatal("Emit accepted package _")
	}
}

func TestEmitRejectionTable(t *testing.T) {
	root := t.TempDir()
	cases := []struct {
		name   string
		mutate func(*[]Model)
		pkg    string
	}{
		{"duplicate model", func(m *[]Model) { *m = append(*m, (*m)[0]) }, "models"},
		{"duplicate field", func(m *[]Model) { (*m)[0].Fields[2].Name = "Email" }, "models"},
		{"field named Model", func(m *[]Model) { (*m)[0].Fields[2].Name = "Model" }, "models"},
		{"package underscore", func(*[]Model) {}, "_"},
		{"call as type", func(m *[]Model) { (*m)[0].Fields[1].GoType = "f()" }, "models"},
		{"operator as type", func(m *[]Model) { (*m)[0].Fields[1].GoType = "a+b" }, "models"},
		{"model named time", func(m *[]Model) { (*m)[0].Name = "time" }, "models"},
		{"model named sql", func(m *[]Model) { (*m)[0].Name = "sql" }, "models"},
		{"model named string", func(m *[]Model) { (*m)[0].Name = "string" }, "models"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			ms := sampleModels()
			tc.mutate(&ms)
			w := gen.NewWriter(gen.WriterOptions{ModuleRoot: root})
			if err := Emit(ms, &Report{}, w, filepath.Join(root, "models"), tc.pkg); err == nil {
				t.Fatal("Emit accepted unsafe input")
			}
		})
	}
}

// A trailing comment in a type must not swallow the struct tag.
func TestEmitPrintsTheParsedType(t *testing.T) {
	root := t.TempDir()
	ms := sampleModels()
	ms[0].Fields[1].GoType = "string // x"
	w := gen.NewWriter(gen.WriterOptions{ModuleRoot: root})
	if err := Emit(ms, &Report{}, w, filepath.Join(root, "models"), "models"); err != nil {
		t.Fatal(err)
	}
	out := string(w.Outputs()[0].Data)
	if strings.Contains(out, "// x") || !strings.Contains(out, "`momo:\"column:email,type:varchar(255),notnull,unique\"`") {
		t.Fatalf("the comment leaked into the model or swallowed the tag:\n%s", out)
	}
}
