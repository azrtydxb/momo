// Model is one source model in the neutral form every reader produces.
type Model struct {
	Name, Table string
	Fields      []Field
	// ForeignKeys are the belongs-to relations of the model; each one is
	// emitted as a relation field next to the columns.
	ForeignKeys []ForeignKey
	Source      string
}

// ForeignKey is a belongs-to relation with a database constraint.
type ForeignKey struct {
	Name       string // constraint name in the source database
	Field      string // Go name of the relation field, e.g. "Org"
	RefModel   string // Go name of the referenced model
	FKField    string // Go name of the local field that holds the key
	Columns    []string
	RefTable   string
	RefColumns []string
	// OnDelete and OnUpdate are SQL actions in upper case ("CASCADE"); empty is NO ACTION.
	OnDelete, OnUpdate string
}

// Field is one column of a Model.
type Field struct {
	Name, Column, GoType, SQLType string
	Nullable, PK, Unique, Index   bool
	// Serial marks an auto-incrementing integer key (a sequence-backed column).
	Serial bool
	// Identity marks a GENERATED BY DEFAULT AS IDENTITY integer key.
	Identity bool
	// UniqueIndex means Unique is a unique index rather than a UNIQUE
	// constraint (GORM uniqueIndex versus unique).
	UniqueIndex bool
	// IndexName and UniqueName are the source database's names for the index
	// or unique key; empty means the default name.
	IndexName, UniqueName string
	// Default is the default expression; DefaultKind is "db" (a SQL
	// default Momo keeps) or "go" (applied by the source ORM in Go, which
	// Momo does not reproduce).
	Default, DefaultKind string
	Source               string
}

// ErrUnsupported is returned by Emit when the report holds an unsupported
// change.
var ErrUnsupported = errors.New("importer: the source uses features Momo cannot import")

// stdImports maps the package qualifiers a field type may use to import paths.
var stdImports = map[string]string{
	"time": "time",
	"sql":  "database/sql",
	"json": "encoding/json",
}

// Emit writes the Momo model source for models into dir/models.go through w.
// dir must be absolute and inside the writer's module root. It refuses to
// write anything when rep holds an Unsupported change, and fails on a name or
// tag value Momo's tag grammar cannot carry.
func Emit(models []Model, rep *Report, w *gen.Writer, dir, pkg string) error {
	if rep != nil {
		if un := rep.Of(Unsupported); len(un) > 0 {
			var sb strings.Builder
			for _, c := range un {
				fmt.Fprintf(&sb, "\n  %s: %s", c.Source, c.Message)
			}
			return fmt.Errorf("%w:%s", ErrUnsupported, sb.String())
		}
	}
	if !token.IsIdentifier(pkg) || pkg == "_" {
		return fmt.Errorf("importer: %q is not a package name", pkg)
	}
	src, err := render(models, pkg)
	if err != nil {
		return err
	}
	if src, err = format.Source(src); err != nil {
		return fmt.Errorf("importer: the emitted source does not parse (importer bug or an unusable type): %w", err)
	}
	return w.File(filepath.Join(dir, "models.go"), src)
}

func render(models []Model, pkg string) ([]byte, error) {
	imports := map[string]bool{"github.com/azrtydxb/momo": true}
	var body bytes.Buffer
	seenModels := map[string]bool{}
	for _, m := range models {
		_, importName := stdImports[m.Name]
		if !token.IsIdentifier(m.Name) || m.Name == "_" || m.Name == "momo" || m.Name == "init" || importName || types.Universe.Lookup(m.Name) != nil {
			return nil, fmt.Errorf("importer: %s: %q cannot be a model type name (it must be an identifier that is not _, a predeclared identifier, or an import name such as momo, time, sql or json)", m.Source, m.Name)
		}
		if seenModels[m.Name] {
			return nil, fmt.Errorf("importer: %s: model %s is declared twice", m.Source, m.Name)
		}
		seenModels[m.Name] = true
		seenFields := map[string]bool{}
		mt := ""
		if m.Table != "" {
			if err := checkTagValue(m.Table); err != nil {
				return nil, fmt.Errorf("importer: model %s table: %w", m.Name, err)
			}
			mt = " `momo:" + strconv.Quote("table:"+m.Table) + "`"
		}
		fmt.Fprintf(&body, "// %s was imported by momo import.\ntype %s struct {\n\tmomo.Model%s\n", m.Name, m.Name, mt)
		for _, f := range m.Fields {
			if !token.IsIdentifier(f.Name) || f.Name == "_" {
				return nil, fmt.Errorf("importer: %s: %q is not a Go field name", f.Source, f.Name)
			}
			if f.Name == "Model" || seenFields[f.Name] {
				return nil, fmt.Errorf("importer: %s: field %s.%s is declared twice or collides with the embedded momo.Model", f.Source, m.Name, f.Name)
			}
			seenFields[f.Name] = true
			if f.GoType == "" {
				return nil, fmt.Errorf("importer: %s: field %s.%s has no Go type", f.Source, m.Name, f.Name)
			}
			goType, err := checkTypeExpr(f.GoType)
			if err != nil {
				return nil, fmt.Errorf("importer: %s: field %s.%s: %w", f.Source, m.Name, f.Name, err)
			}
			if err := collectImports(goType, imports); err != nil {
				return nil, fmt.Errorf("importer: %s: field %s.%s: %w", f.Source, m.Name, f.Name, err)
			}
			tag, err := fieldTag(f)
			if err != nil {
				return nil, fmt.Errorf("importer: %s: field %s.%s: %w", f.Source, m.Name, f.Name, err)
			}
			if tag != "" {
				tag = " `momo:" + strconv.Quote(tag) + "`"
			}
			fmt.Fprintf(&body, "\t%s %s%s\n", f.Name, goType, tag)
		}
		for _, fk := range m.ForeignKeys {
			line, err := relationField(fk)
			if err != nil {
				return nil, fmt.Errorf("importer: %s: model %s: %w", m.Source, m.Name, err)
			}
			body.WriteString(line)
		}
		body.WriteString("}\n\n")
	}
	var out bytes.Buffer
	out.WriteString(gen.Header())
	fmt.Fprintf(&out, "\n\npackage %s\n\nimport (\n", pkg)
	paths := make([]string, 0, len(imports))
	for p := range imports {
		paths = append(paths, p)
	}
	slices.Sort(paths)
	for _, p := range paths {
		fmt.Fprintf(&out, "\t%s\n", strconv.Quote(p))
	}
	out.WriteString(")\n\n")
	out.Write(body.Bytes())
	return out.Bytes(), nil
}

// collectImports adds the import path of every pkg.Name qualifier in goType.
func collectImports(goType string, into map[string]bool) error {
	for i := 0; i < len(goType); i++ {
		if goType[i] != '.' {
			continue
		}
		j := i
		for j > 0 && isIdentByte(goType[j-1]) {
			j--
		}
		qual := goType[j:i]
		if qual == "" {
			continue
		}
		path, ok := stdImports[qual]
		if !ok {
			return fmt.Errorf("type %q uses package %q, which the importer cannot place", goType, qual)
		}
		into[path] = true
	}
	return nil
}

func isIdentByte(b byte) bool {
	return b == '_' || b >= '0' && b <= '9' || b >= 'a' && b <= 'z' || b >= 'A' && b <= 'Z'
}

// checkTagValue rejects values the momo tag grammar cannot carry: a value
// ends at the next comma, and the tag lives in a raw string literal.
func checkTagValue(v string) error {
	if strings.ContainsAny(v, ",`\n\r") {
		return fmt.Errorf("value %q contains a comma, backtick or newline, which a momo tag cannot carry", v)
	}
	return nil
}

// numericPrecisionRE matches numeric(p,s) and decimal(p,s) written with digits only.
var numericPrecisionRE = regexp.MustCompile(`^(?i:numeric|decimal)\s*\(\s*([0-9]+)\s*,\s*([0-9]+)\s*\)$`)

// numericPrecision splits a numeric(p,s) type into its precision and scale.
func numericPrecision(sqlType string) (precision, scale string, ok bool) {
	m := numericPrecisionRE.FindStringSubmatch(strings.TrimSpace(sqlType))
	if m == nil {
		return "", "", false
	}
	return m[1], m[2], true
}

func fieldTag(f Field) (string, error) {
	var opts []string
	add := func(key, val string) error {
		if err := checkTagValue(val); err != nil {
			return fmt.Errorf("%s: %w", key, err)
		}
		opts = append(opts, key+":"+val)
		return nil
	}
	if f.PK {
		opts = append(opts, "pk")
	}
	if f.Serial {
		opts = append(opts, "serial")
	}
	if f.Identity {
		opts = append(opts, "identity")
	}
	if f.Column != "" {
		if err := add("column", f.Column); err != nil {
			return "", err
		}
	}
	if p, sc, ok := numericPrecision(f.SQLType); ok {
		// numeric(p,s) has a comma, which a type: value cannot carry; the
		// precision and scale tags build the same type.
		opts = append(opts, "precision:"+p)
		if sc != "0" {
			opts = append(opts, "scale:"+sc)
		}
	} else if f.SQLType != "" {
		if err := add("type", f.SQLType); err != nil {
			return "", err
		}
	}
	// Momo reads nullability from the Go type or the nullable tag; a plain
	// value type without notnull would otherwise be NOT NULL.
	ptr := strings.HasPrefix(f.GoType, "*")
	switch {
	case !f.Nullable && !f.PK && !ptr:
		opts = append(opts, "notnull")
	case f.Nullable && !ptr:
		opts = append(opts, "nullable")
	}
	if f.Unique || f.UniqueIndex {
		if f.UniqueName != "" {
			if err := add("unique", f.UniqueName); err != nil {
				return "", err
			}
		} else {
			opts = append(opts, "unique")
		}
	}
	if f.Index {
		if f.IndexName != "" {
			if err := add("index", f.IndexName); err != nil {
				return "", err
			}
		} else {
			opts = append(opts, "index")
		}
	}
	if f.Default != "" && f.DefaultKind != "go" {
		if err := add("default", f.Default); err != nil {
			return "", err
		}
	}
	return strings.Join(opts, ","), nil
}

// checkTypeExpr requires goType to parse as a Go type expression: names,
// pointers, selectors, slices, arrays with a literal length, maps and generic
// instantiations. Anything else (a call, an operator, a second declaration)
// would put arbitrary source into the model file.
//
// It returns the type printed from the parsed expression, which is what the
// emitter writes: trailing comments and odd spacing in the input never reach
// the model file.
func checkTypeExpr(goType string) (string, error) {
	e, err := parser.ParseExpr(goType)
	if err != nil {
		return "", fmt.Errorf("type %q does not parse: %w", goType, err)
	}
	if !isTypeExpr(e) {
		return "", fmt.Errorf("%q is not a type expression", goType)
	}
	var buf bytes.Buffer
	if err := format.Node(&buf, token.NewFileSet(), e); err != nil {
		return "", fmt.Errorf("type %q cannot be printed: %w", goType, err)
	}
	return buf.String(), nil
}

func isTypeExpr(e ast.Expr) bool {
	switch t := e.(type) {
	case *ast.Ident:
		return true
	case *ast.StarExpr:
		return isTypeExpr(t.X)
	case *ast.ParenExpr:
		return isTypeExpr(t.X)
	case *ast.SelectorExpr:
		_, ok := t.X.(*ast.Ident)
		return ok
	case *ast.ArrayType:
		if t.Len != nil {
			if lit, ok := t.Len.(*ast.BasicLit); !ok || lit.Kind != token.INT {
				return false
			}
		}
		return isTypeExpr(t.Elt)
	case *ast.MapType:
		return isTypeExpr(t.Key) && isTypeExpr(t.Value)
	case *ast.IndexExpr:
		return isTypeExpr(t.X) && isTypeExpr(t.Index)
	case *ast.IndexListExpr:
		if !isTypeExpr(t.X) {
			return false
		}
		for _, i := range t.Indices {
			if !isTypeExpr(i) {
				return false
			}
		}
		return true
	}
	return false
}

// relationField renders a belongs-to field.
func relationField(fk ForeignKey) (string, error) {
	if !token.IsIdentifier(fk.Field) || !token.IsIdentifier(fk.RefModel) || !token.IsIdentifier(fk.FKField) {
		return "", fmt.Errorf("relation %q to %q by %q needs identifier names", fk.Field, fk.RefModel, fk.FKField)
	}
	opts := []string{"belongs_to", "fk:" + fk.FKField}
	for key, val := range map[string]string{"on_delete": fk.OnDelete, "on_update": fk.OnUpdate} {
		if val == "" {
			continue
		}
		if err := checkTagValue(val); err != nil {
			return "", fmt.Errorf("%s: %w", key, err)
		}
		opts = append(opts, key+":"+strings.ToLower(strings.ReplaceAll(val, " ", "_")))
	}
	slices.Sort(opts[2:])
	return fmt.Sprintf("\t%s *%s `momo:%s`\n", fk.Field, fk.RefModel, strconv.Quote(strings.Join(opts, ","))), nil
}
