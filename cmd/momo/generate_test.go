package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const exampleSrc = "testdata/example"

func TestGenerateCheck(t *testing.T) {
	root := copyModule(t, exampleSrc)
	chdir(t, root)

	var out, errb bytes.Buffer
	if code := Run([]string{"generate", "./..."}, &out, &errb); code != 0 {
		t.Fatalf("generate: exit %d\n%s%s", code, out.String(), errb.String())
	}
	out.Reset()
	errb.Reset()
	if code := Run([]string{"generate", "--check", "./..."}, &out, &errb); code != 0 {
		t.Fatalf("current tree: exit %d\n%s%s", code, out.String(), errb.String())
	}
	edit := filepath.Join(root, "document", "momo_gen.go")
	b, err := os.ReadFile(edit) //nolint:gosec // test path
	if err != nil {
		t.Fatal(err)
	}
	drifted := append(b, []byte("\n// drift\n")...)
	if err := os.WriteFile(edit, drifted, 0o600); err != nil {
		t.Fatal(err)
	}
	out.Reset()
	errb.Reset()
	if code := Run([]string{"generate", "--check", "./..."}, &out, &errb); code != 1 {
		t.Fatalf("stale tree: exit %d want 1", code)
	}
	if !strings.Contains(out.String(), "stale:") {
		t.Fatalf("stale file not listed: %s", out.String())
	}
	after, err := os.ReadFile(edit) //nolint:gosec // test path
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(after, drifted) {
		t.Fatal("--check wrote to disk")
	}
}

func TestGenerateCheckOrphan(t *testing.T) {
	root := copyModule(t, exampleSrc)
	chdir(t, root)
	var out, errb bytes.Buffer
	if code := Run([]string{"generate", "./..."}, &out, &errb); code != 0 {
		t.Fatalf("generate: %d %s", code, errb.String())
	}
	if r, err := filepath.EvalSymlinks(root); err == nil {
		root = r
	}
	orphan := filepath.Join(root, "gone", "momo_gen.go")
	if err := os.MkdirAll(filepath.Dir(orphan), 0o750); err != nil {
		t.Fatal(err)
	}
	src := "// Code generated by momo v0.0.0 (format 1). DO NOT EDIT.\n\npackage gone\n"
	if err := os.WriteFile(orphan, []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}
	out.Reset()
	if code := Run([]string{"generate", "--check", "./..."}, &out, &errb); code != 1 {
		t.Fatalf("orphan: exit %d want 1", code)
	}
	if got := strings.Count(out.String(), "stale: "+orphan+"\n"); got != 1 {
		t.Fatalf("orphan not listed: %s", out.String())
	}
}

func TestGenerateDiagnostics(t *testing.T) {
	root := copyModule(t, exampleSrc)
	chdir(t, root)
	if err := os.WriteFile(filepath.Join(root, "bad.go"), []byte("package example\n\nvar x int = \"s\"\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	var out, errb bytes.Buffer
	if code := Run([]string{"generate", "./..."}, &out, &errb); code != 1 {
		t.Fatalf("exit %d want 1\n%s", code, errb.String())
	}
	if !strings.Contains(errb.String(), "bad.go:3:") {
		t.Fatalf("no positioned diagnostic: %q", errb.String())
	}
	if _, err := os.Stat(filepath.Join(root, "document", "momo_gen.go")); err == nil {
		t.Fatal("output written despite diagnostics")
	}
}

func TestGenerateConfigErrors(t *testing.T) {
	root := copyModule(t, exampleSrc)
	chdir(t, root)
	var out, errb bytes.Buffer
	if code := Run([]string{"generate", "-c", "missing.yaml"}, &out, &errb); code != 2 {
		t.Fatalf("missing config: exit %d want 2", code)
	}
	if err := os.WriteFile("momo.yaml", []byte("version: 1\nplugins:\n  nosuch: {}\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	errb.Reset()
	if code := Run([]string{"generate"}, &out, &errb); code != 2 || !strings.Contains(errb.String(), "nosuch") {
		t.Fatalf("unknown plugin: exit %d, %q", code, errb.String())
	}
}

