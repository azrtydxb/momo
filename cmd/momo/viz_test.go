// Catches: viz exiting 0 on a missing snapshot, ignoring --format or --out,
// or producing output without the generated header.
func TestVizCLI(t *testing.T) {
	var out, errb bytes.Buffer
	missing := filepath.Join(t.TempDir(), "missing.json")
	if code := Run([]string{"viz", "--snapshot", missing}, &out, &errb); code != 2 {
		t.Fatalf("missing snapshot: exit %d, want 2: %s", code, errb.String())
	}
	if code := Run([]string{"viz", "--format", "svg"}, &out, &errb); code != 2 {
		t.Fatalf("bad format: exit %d, want 2", code)
	}
	bad := filepath.Join(t.TempDir(), "bad.json")
	if err := os.WriteFile(bad, []byte("{not json"), 0o600); err != nil {
		t.Fatal(err)
	}
	if code := Run([]string{"viz", "--snapshot", bad}, &out, &errb); code != 2 {
		t.Fatalf("corrupt snapshot: exit %d, want 2", code)
	}

	chdir(t, "../../internal/testmodels/example")
	dst := filepath.Join(t.TempDir(), "schema.mmd")
	out.Reset()
	errb.Reset()
	if code := Run([]string{"viz", "--format", "mermaid", "--out", dst}, &out, &errb); code != 0 {
		t.Fatalf("viz from models: exit %d: %s", code, errb.String())
	}
	b, err := os.ReadFile(dst) //nolint:gosec // test path
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(b), "%% Code generated by momo") || !strings.Contains(string(b), "documents") {
		t.Fatalf("output lacks the generated header or the models: %q", b)
	}

	out.Reset()
	if code := Run([]string{"viz", "--format", "dot"}, &out, &errb); code != 0 {
		t.Fatalf("viz dot to stdout: exit %d: %s", code, errb.String())
	}
	if !strings.HasPrefix(out.String(), "// Code generated by momo") || !strings.Contains(out.String(), "digraph momo") {
		t.Fatalf("stdout = %q", out.String())
	}
}

// Catches: --snapshot reading the models instead of the snapshot file.
func TestVizCLISnapshot(t *testing.T) {
	snap := filepath.Join(t.TempDir(), "snapshot.json")
	body := `{"format_version":1,"dialect":"postgres","tables":[` +
		`{"name":"authors","columns":[{"name":"id","type":"bigint"}],"primary_key":["id"]},` +
		`{"name":"books","columns":[{"name":"id","type":"bigint"},{"name":"author_id","type":"bigint"}],"primary_key":["id"],` +
		`"foreign_keys":[{"name":"books_author_fk","columns":["author_id"],"ref_table":"authors","ref_columns":["id"]}]}]}`
	if err := os.WriteFile(snap, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	var out, errb bytes.Buffer
	if code := Run([]string{"viz", "--snapshot", snap}, &out, &errb); code != 0 {
		t.Fatalf("exit %d: %s", code, errb.String())
	}
	if !strings.Contains(out.String(), `authors ||--o{ books : "author_id"`) {
		t.Fatalf("snapshot edge missing:\n%s", out.String())
	}
}
