-- The database as it exists today: created and changed by hand, years before
-- Momo. Nothing in it records a migration history.
--
-- PostgreSQL names the primary key and foreign key constraints below
-- users_pkey, orders_pkey and orders_user_id_fkey. Momo's generator uses the
-- same names, which is why this schema and the models match.

CREATE TABLE users (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      varchar(200) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- A unique index, not a UNIQUE constraint: Momo models `unique` as an index,
-- and the baseline check treats the two as different objects.
CREATE UNIQUE INDEX users_email_key ON users (email);

CREATE TABLE orders (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint NOT NULL REFERENCES users (id),
    total_cents bigint NOT NULL,
    placed_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX orders_user_id_idx ON orders (user_id);

