// explReceipt is the NovaCRM Receipt: a text primary key plus a serial
// column that is not the key.
type explReceipt struct {
	ID   string
	Seq  int64
	Note string
}

var explReceiptMeta = &momo.Meta[explReceipt]{
	Table: "receipts",
	Columns: []momo.ColumnMeta{
		{Name: "id", Flags: momo.FlagPK},
		{Name: "seq", Flags: momo.FlagIdentity},
		{Name: "note"},
	},
	Ptr:   func(m *explReceipt, i int) any { return []any{&m.ID, &m.Seq, &m.Note}[i] },
	Value: func(m *explReceipt, i int) any { return []any{m.ID, m.Seq, m.Note}[i] },
	TableSchema: &schema.Table{Name: "receipts", PrimaryKey: []string{"id"}, Columns: []schema.Column{
		{Name: "id", Type: "text"},
		{Name: "seq", Type: "integer", Identity: "serial"},
		{Name: "note", Type: "text"},
	}},
	Identity: 1, Version: -1, SoftDelete: -1, CreatedAt: -1, UpdatedAt: -1,
	PK: []int{0},
}

func (*explReceipt) MomoMeta() *momo.Meta[explReceipt] { return explReceiptMeta }

// explIdentity is a model whose primary key is an identity column; kind picks
// GENERATED ALWAYS or GENERATED BY DEFAULT through its schema.
type explAlways struct {
	ID   int64
	Body string
}

type explByDefault struct {
	ID   int64
	Body string
}

func explIdentityMeta[T any](table, kind string, ptr func(*T, int) any, val func(*T, int) any) *momo.Meta[T] {
	return &momo.Meta[T]{
		Table:   table,
		Columns: []momo.ColumnMeta{{Name: "id", Flags: momo.FlagPK | momo.FlagIdentity}, {Name: "body"}},
		Ptr:     ptr,
		Value:   val,
		TableSchema: &schema.Table{Name: table, PrimaryKey: []string{"id"}, Columns: []schema.Column{
			{Name: "id", Type: "bigint", Identity: kind},
			{Name: "body", Type: "text"},
		}},
		Identity: 0, Version: -1, SoftDelete: -1, CreatedAt: -1, UpdatedAt: -1,
		PK: []int{0},
	}
}

var explAlwaysMeta = explIdentityMeta("always_rows", "always",
	func(m *explAlways, i int) any { return []any{&m.ID, &m.Body}[i] },
	func(m *explAlways, i int) any { return []any{m.ID, m.Body}[i] })

var explByDefaultMeta = explIdentityMeta("default_rows", "by_default",
	func(m *explByDefault, i int) any { return []any{&m.ID, &m.Body}[i] },
	func(m *explByDefault, i int) any { return []any{m.ID, m.Body}[i] })

func (*explAlways) MomoMeta() *momo.Meta[explAlways]       { return explAlwaysMeta }
func (*explByDefault) MomoMeta() *momo.Meta[explByDefault] { return explByDefaultMeta }

var (
	explRID   = momo.NewColumn[string]("receipts", "id", momo.FlagPK)
	explRSeq  = momo.NewColumn[int64]("receipts", "seq", momo.FlagIdentity)
	explRNote = momo.NewColumn[string]("receipts", "note", 0)
	explAID   = momo.NewColumn[int64]("always_rows", "id", momo.FlagPK|momo.FlagIdentity)
	explDID   = momo.NewColumn[int64]("default_rows", "id", momo.FlagPK|momo.FlagIdentity)
)

func explSQL(t *testing.T, q interface{ SQL() (momo.Compiled, error) }) string {
	t.Helper()
	c, err := q.SQL()
	if err != nil {
		t.Fatal(err)
	}
	return c.SQL
}

// Catches: Explicit that does not put the serial/identity/auto-increment
// column into the column list (the value is dropped as before), that renders
// OVERRIDING SYSTEM VALUE for a serial or BY DEFAULT column, that omits it for
// GENERATED ALWAYS, that leaks it into a dialect without the clause, or that
// changes the default insert, which must keep leaving identity columns out.
func TestInsertExplicitGoldenSQL(t *testing.T) {
	r := explReceipt{ID: "a", Seq: 7, Note: "n"}
	a := explAlways{ID: 5, Body: "b"}
	d := explByDefault{ID: 5, Body: "b"}
	cases := []struct {
		name  string
		dial  dialect.Name
		build func(q momo.Querier) interface{ SQL() (momo.Compiled, error) }
		want  string
	}{
		{"default drops serial", dialect.Postgres, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Insert[explReceipt](q).Model(&r)
		}, `INSERT INTO "receipts" ("id", "note") VALUES ($1, $2)`},
		{"default drops always identity", dialect.Postgres, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Insert[explAlways](q).Model(&a)
		}, `INSERT INTO "always_rows" ("body") VALUES ($1)`},
		{"postgres serial", dialect.Postgres, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Insert[explReceipt](q).Model(&r).Explicit(explRSeq)
		}, `INSERT INTO "receipts" ("id", "seq", "note") VALUES ($1, $2, $3)`},
		{"postgres always identity", dialect.Postgres, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Insert[explAlways](q).Model(&a).Explicit(explAID)
		}, `INSERT INTO "always_rows" ("id", "body") OVERRIDING SYSTEM VALUE VALUES ($1, $2)`},
		{"postgres by default identity", dialect.Postgres, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Insert[explByDefault](q).Model(&d).Explicit(explDID)
		}, `INSERT INTO "default_rows" ("id", "body") VALUES ($1, $2)`},
		{"sqlite", dialect.SQLite, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Insert[explReceipt](q).Model(&r).Explicit(explRSeq)
		}, `INSERT INTO "receipts" ("id", "seq", "note") VALUES (?, ?, ?)`},
		{"sqlite never renders OVERRIDING", dialect.SQLite, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Insert[explAlways](q).Model(&a).Explicit(explAID)
		}, `INSERT INTO "always_rows" ("id", "body") VALUES (?, ?)`},
		{"mysql", dialect.MySQL, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Insert[explReceipt](q).Model(&r).Explicit(explRSeq)
		}, "INSERT INTO `receipts` (`id`, `seq`, `note`) VALUES (?, ?, ?)"},
		{"mysql auto increment key", dialect.MySQL, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Insert[explByDefault](q).Model(&d).Explicit(explDID)
		}, "INSERT INTO `default_rows` (`id`, `body`) VALUES (?, ?)"},
		{"values postgres", dialect.Postgres, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Insert[explReceipt](q).Values(explRID.Set("a"), explRSeq.Set(7)).Explicit(explRSeq)
		}, `INSERT INTO "receipts" ("id", "seq") VALUES ($1, $2)`},
		{"values always identity", dialect.Postgres, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Insert[explAlways](q).Values(explAID.Set(5)).Explicit(explAID)
		}, `INSERT INTO "always_rows" ("id") OVERRIDING SYSTEM VALUE VALUES ($1)`},
		{"values rows", dialect.Postgres, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Insert[explAlways](q).Explicit(explAID).ValuesRows(
				[]momo.Assignment{explAID.Set(1)}, []momo.Assignment{explAID.Set(2)})
		}, `INSERT INTO "always_rows" ("id") OVERRIDING SYSTEM VALUE VALUES ($1), ($2)`},
		{"explicit zero is written as is", dialect.Postgres, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			z := explReceipt{ID: "a"}
			return momo.Insert[explReceipt](q).Model(&z).Explicit(explRSeq)
		}, `INSERT INTO "receipts" ("id", "seq", "note") VALUES ($1, $2, $3)`},
		{"on conflict", dialect.Postgres, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Insert[explReceipt](q).Model(&r).Explicit(explRSeq).OnConflict(explRID).DoNothing()
		}, `INSERT INTO "receipts" ("id", "seq", "note") VALUES ($1, $2, $3) ON CONFLICT ("id") DO NOTHING`},
		{"upsert serial", dialect.Postgres, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			return momo.Upsert[explReceipt](q).Model(&r).Explicit(explRSeq)
		}, `INSERT INTO "receipts" ("id", "seq", "note") VALUES ($1, $2, $3) ON CONFLICT ("id") DO UPDATE SET "note" = EXCLUDED."note"`},
		{"upsert always identity key", dialect.Postgres, func(q momo.Querier) interface{ SQL() (momo.Compiled, error) } {
			z := explAlways{Body: "b"} // a zero key is written because the caller opted in
			return momo.Upsert[explAlways](q).Model(&z).Explicit(explAID)
		}, `INSERT INTO "always_rows" ("id", "body") OVERRIDING SYSTEM VALUE VALUES ($1, $2) ON CONFLICT ("id") DO UPDATE SET "body" = EXCLUDED."body"`},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := explSQL(t, tc.build(momo.New(fakedriver.New(tc.dial)))); got != tc.want {
				t.Fatalf("got  %s\nwant %s", got, tc.want)
			}
		})
	}
}

// Catches: a zero Explicit value that is replaced by a database default, and
// a model value that is not the bound argument.
func TestInsertExplicitBindsStructValue(t *testing.T) {
	drv := fakedriver.New(dialect.Postgres)
	r := explReceipt{ID: "a", Seq: 41}
	z := explReceipt{ID: "b"}
	for _, m := range []*explReceipt{&r, &z} {
		if _, err := momo.Insert[explReceipt](momo.New(drv)).Model(m).Explicit(explRSeq).Exec(t.Context()); err != nil {
			t.Fatal(err)
		}
	}
	calls := drv.Calls()
	if len(calls) != 2 || calls[0].Args[1] != int64(41) || calls[1].Args[1] != int64(0) {
		t.Fatalf("calls = %+v, want seq args 41 and 0", calls)
	}
}

// Catches: a chunked bulk insert whose later chunks lose the explicit column
// or the OVERRIDING SYSTEM VALUE clause because only the first chunk was
// planned with Explicit.
func TestInsertExplicitChunkedBulk(t *testing.T) {
	drv := newSmallLimit(6) // three columns per row: two rows per statement
	a := []explAlways{{ID: 1, Body: "a"}, {ID: 2, Body: "b"}, {ID: 3, Body: "c"}}
	if _, err := momo.Insert[explAlways](momo.New(drv)).Models(a).Explicit(explAID).Exec(t.Context()); err != nil {
		t.Fatal(err)
	}
	calls := drv.Calls()
	if len(calls) != 2 {
		t.Fatalf("%d statements, want 2", len(calls))
	}
	want := []string{
		`INSERT INTO "always_rows" ("id", "body") OVERRIDING SYSTEM VALUE VALUES ($1, $2), ($3, $4)`,
		`INSERT INTO "always_rows" ("id", "body") OVERRIDING SYSTEM VALUE VALUES ($1, $2)`,
	}
	for i, c := range calls {
		if c.SQL != want[i] {
			t.Errorf("statement %d:\ngot  %s\nwant %s", i, c.SQL, want[i])
		}
	}
	if calls[1].Args[0] != int64(3) {
		t.Errorf("last chunk id = %v, want 3", calls[1].Args[0])
	}
}

// Catches: Unnest dropping the explicit column or rendering the clause in the
// wrong place for a GENERATED ALWAYS column.
func TestInsertExplicitUnnest(t *testing.T) {
	a := []explAlways{{ID: 1, Body: "a"}, {ID: 2, Body: "b"}}
	got := explSQL(t, momo.Insert[explAlways](momo.New(fakedriver.New(dialect.Postgres))).Models(a).Explicit(explAID).Unnest())
	if !strings.Contains(got, `("id", "body") OVERRIDING SYSTEM VALUE SELECT * FROM unnest(`) {
		t.Fatalf("got %s", got)
	}
	r := []explReceipt{{ID: "a", Seq: 1}, {ID: "b", Seq: 2}}
	got = explSQL(t, momo.Insert[explReceipt](momo.New(fakedriver.New(dialect.Postgres))).Models(r).Explicit(explRSeq).Unnest())
	if !strings.Contains(got, `("id", "seq", "note") SELECT * FROM unnest(`) || strings.Contains(got, "OVERRIDING") {
		t.Fatalf("got %s", got)
	}
}

// Catches: Explicit that accepts a column that is not serial/identity, a
// column the model does not map, or a FromSelect/Copy it cannot honour, and so
// silently ignores the request instead of failing with ErrValidation.
func TestInsertExplicitValidation(t *testing.T) {
	r := explReceipt{ID: "a", Seq: 7}
	db := momo.New(fakedriver.New(dialect.Postgres))
	cases := map[string]momo.InsertQuery[explReceipt]{
		"not an identity column":   momo.Insert[explReceipt](db).Model(&r).Explicit(explRNote),
		"primary key not identity": momo.Insert[explReceipt](db).Model(&r).Explicit(explRID),
		"unmapped column":          momo.Insert[explReceipt](db).Model(&r).Explicit(momo.NewColumn[int64]("receipts", "nope", momo.FlagIdentity)),
		"with FromSelect":          momo.Insert[explReceipt](db).Explicit(explRSeq).FromSelect(momo.SelectExprs(momo.Value(int64(1))), explRNote),
		"values":                   momo.Insert[explReceipt](db).Values(explRID.Set("a")).Explicit(explRNote),
	}
	for name, q := range cases {
		t.Run(name, func(t *testing.T) {
			if _, err := q.SQL(); !errors.Is(err, momo.ErrValidation) {
				t.Fatalf("SQL() error = %v, want ErrValidation", err)
			}
		})
	}
	if _, err := momo.Insert[explReceipt](db).Explicit(explRSeq).Copy(t.Context(), []explReceipt{r}); !errors.Is(err, momo.ErrValidation) {
		t.Fatalf("Copy error = %v, want ErrValidation", err)
	}
}

// Catches: the default insert changing: a Values write to an identity column
// without Explicit must still be refused, not silently accepted.
func TestInsertWithoutExplicitStillRefusesIdentityValues(t *testing.T) {
	db := momo.New(fakedriver.New(dialect.Postgres))
	_, err := momo.Insert[explReceipt](db).Values(explRID.Set("a"), explRSeq.Set(7)).SQL()
	if !errors.Is(err, momo.ErrValidation) {
		t.Fatalf("error = %v, want ErrValidation", err)
	}
}
