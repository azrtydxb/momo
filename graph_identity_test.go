package momo_test

import (
	"context"
	"testing"

	"github.com/azrtydxb/momo"
	"github.com/azrtydxb/momo/dialect"
	"github.com/azrtydxb/momo/internal/testdb/testopen"
)

// The identity models below are hand-written so CreateGraph can be tested with
// database-generated keys: the child foreign key can only be right if the
// parent's identity was read back with RETURNING before the children insert.

type gParent struct {
	momo.Model `momo:"table:g_parents"`
	ID         int64
	Name       string
	Kids       []gKid
}

type gKid struct {
	momo.Model `momo:"table:g_kids"`
	ID         int64
	ParentID   int64
	Name       string
	Parent     *gParent
}

var gParentMeta = &momo.Meta[gParent]{
	Table:   "g_parents",
	Columns: []momo.ColumnMeta{{Name: "id", Flags: momo.FlagPK | momo.FlagIdentity}, {Name: "name"}},
	Ptr: func(m *gParent, i int) any {
		return []any{&m.ID, &m.Name}[i]
	},
	Value: func(m *gParent, i int) any {
		return []any{m.ID, m.Name}[i]
	},
	Identity: 0, Version: -1, SoftDelete: -1, CreatedAt: -1, UpdatedAt: -1, PK: []int{0},
}

var gKidMeta = &momo.Meta[gKid]{
	Table:   "g_kids",
	Columns: []momo.ColumnMeta{{Name: "id", Flags: momo.FlagPK | momo.FlagIdentity}, {Name: "parent_id"}, {Name: "name"}},
	Ptr: func(m *gKid, i int) any {
		return []any{&m.ID, &m.ParentID, &m.Name}[i]
	},
	Value: func(m *gKid, i int) any {
		return []any{m.ID, m.ParentID, m.Name}[i]
	},
	Identity: 0, Version: -1, SoftDelete: -1, CreatedAt: -1, UpdatedAt: -1, PK: []int{0},
}

func (*gParent) MomoMeta() *momo.Meta[gParent] { return gParentMeta }
func (*gKid) MomoMeta() *momo.Meta[gKid]       { return gKidMeta }

var gKids = momo.Relation[gParent, gKid]{
	Name: "Kids", Kind: momo.HasMany,
	Parent: momo.TableRef{Name: "g_parents"}, Child: momo.TableRef{Name: "g_kids"},
	ParentMeta: gParentMeta, ChildMeta: gKidMeta,
	ParentCols: []string{"id"}, ChildCols: []string{"parent_id"}, ChildPK: []string{"id"},
	ParentKey:   func(p *gParent) ([]any, bool) { return []any{p.ID}, true },
	ChildKey:    func(c *gKid) ([]any, bool) { return []any{c.ParentID}, true },
	SetChildKey: func(c *gKid, k []any) { c.ParentID = k[0].(int64) },
	GetMany:     func(p *gParent) []gKid { return p.Kids },
	SetMany:     func(p *gParent, cs []gKid) { p.Kids = cs },
}

var gKidParent = momo.Relation[gKid, gParent]{
	Name: "Parent", Kind: momo.BelongsTo,
	Parent: momo.TableRef{Name: "g_kids"}, Child: momo.TableRef{Name: "g_parents"},
	ParentMeta: gKidMeta, ChildMeta: gParentMeta,
	ParentCols: []string{"parent_id"}, ChildCols: []string{"id"}, ChildPK: []string{"id"},
	ParentKey:    func(p *gKid) ([]any, bool) { return []any{p.ParentID}, true },
	ChildKey:     func(c *gParent) ([]any, bool) { return []any{c.ID}, true },
	SetParentKey: func(p *gKid, k []any) { p.ParentID = k[0].(int64) },
	GetOne:       func(p *gKid) *gParent { return p.Parent },
	SetOne:       func(p *gKid, c *gParent) { p.Parent = c },
}

func gSchema(t *testing.T, db *momo.DB, d dialect.Name) {
	t.Helper()
	pk := `BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`
	if d == dialect.SQLite {
		pk = `INTEGER PRIMARY KEY AUTOINCREMENT`
	}
	mustExec(t, db, `CREATE TABLE g_parents (id `+pk+`, name TEXT NOT NULL)`)
	mustExec(t, db, `CREATE TABLE g_kids (id `+pk+`, parent_id BIGINT NOT NULL REFERENCES g_parents(id), name TEXT NOT NULL)`)
}

func TestCreateGraphGeneratedIdentityPropagates(t *testing.T) {
	testopen.Each(t, func(t *testing.T, db *momo.DB, d dialect.Name) {
		gSchema(t, db, d)
		ctx := context.Background()

		// Parent first: the generated parent id lands in every child.
		p := &gParent{Name: "p", Kids: []gKid{{Name: "a"}, {Name: "b"}}}
		if err := momo.CreateGraph(ctx, db, p, gKids.Include()); err != nil {
			t.Fatal(err)
		}
		if p.ID == 0 || p.Kids[0].ID == 0 || p.Kids[1].ID == 0 || p.Kids[0].ID == p.Kids[1].ID {
			t.Fatalf("identities must be read back: %+v", p)
		}
		for _, k := range p.Kids {
			if k.ParentID != p.ID {
				t.Fatalf("child foreign key %d, want %d", k.ParentID, p.ID)
			}
		}
		if n := graphCount(t, db, `SELECT COUNT(*) FROM g_kids WHERE parent_id = ?`, p.ID); n != 2 {
			t.Fatalf("stored children: %d", n)
		}

		// Belongs-to first: the generated child (parent-side) id lands in the kid.
		k := &gKid{Name: "solo", Parent: &gParent{Name: "newparent"}}
		if err := momo.CreateGraph(ctx, db, k, gKidParent.Include()); err != nil {
			t.Fatal(err)
		}
		if k.Parent.ID == 0 || k.ParentID != k.Parent.ID {
			t.Fatalf("belongs-to key: %+v / %+v", k, k.Parent)
		}
		if n := graphCount(t, db, `SELECT COUNT(*) FROM g_kids k JOIN g_parents p ON p.id = k.parent_id WHERE p.name = 'newparent'`); n != 1 {
			t.Fatalf("stored kid: %d", n)
		}
	})
}
