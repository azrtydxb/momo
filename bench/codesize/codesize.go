// Package codesize measures the size and compile cost of the code that
// momo generate wrote for the benchmark models.
package codesize

import (
	"bufio"
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
	"time"
)

// Report is the generated-code size and compile cost of one package tree.
type Report struct {
	GeneratedFiles int   `json:"generated_files"`
	GeneratedBytes int64 `json:"generated_bytes"`
	GeneratedLines int   `json:"generated_lines"`
	// ModelPackageCompileMS is the median of five go build runs of the model
	// package, each after a content change to one generated file, so the
	// package is recompiled while its dependencies stay cached.
	ModelPackageCompileMS int64 `json:"model_package_compile_ms"`
}

const generatedPrefix = "// Code generated by momo"

// Measure walks dir for files that start with the generator header and builds
// the package in dir five times.
func Measure(ctx context.Context, dir string) (Report, error) {
	var rep Report
	var first string
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") {
			return err
		}
		raw, err := os.ReadFile(path) // #nosec G304 -- path comes from walking dir
		if err != nil {
			return err
		}
		if !strings.HasPrefix(string(raw), generatedPrefix) {
			return nil
		}
		rep.GeneratedFiles++
		rep.GeneratedBytes += int64(len(raw))
		sc := bufio.NewScanner(bytes.NewReader(raw))
		sc.Buffer(make([]byte, 0, 64*1024), 4*1024*1024)
		for sc.Scan() {
			rep.GeneratedLines++
		}
		if first == "" && filepath.Dir(path) == dir {
			first = path
		}
		return sc.Err()
	})
	if err != nil {
		return rep, err
	}
	if first == "" {
		return rep, fmt.Errorf("codesize: no generated file directly in %s", dir)
	}
	ms, err := compileMedianMS(ctx, dir, first)
	if err != nil {
		return rep, err
	}
	rep.ModelPackageCompileMS = ms
	return rep, nil
}

func compileMedianMS(ctx context.Context, dir, file string) (int64, error) {
	raw, err := os.ReadFile(file) // #nosec G304 -- file was found by Measure
	if err != nil {
		return 0, err
	}
	tmp, err := os.MkdirTemp("", "codesize-")
	if err != nil {
		return 0, err
	}
	defer func() { _ = os.RemoveAll(tmp) }()
	// Warm the dependencies once so the timed runs compile only the package.
	if err := goBuild(ctx, dir, ""); err != nil {
		return 0, err
	}
	var runs []int64
	for n := 0; n < 5; n++ {
		changed := filepath.Join(tmp, fmt.Sprintf("changed%d.go", n))
		body := append(slices.Clone(raw), fmt.Appendf(nil, "\n// nonce %d %d\n", n, time.Now().UnixNano())...)
		if err := os.WriteFile(changed, body, 0o600); err != nil {
			return 0, err
		}
		overlay := filepath.Join(tmp, fmt.Sprintf("overlay%d.json", n))
		ov, err := json.Marshal(map[string]map[string]string{"Replace": {file: changed}})
		if err != nil {
			return 0, err
		}
		if err := os.WriteFile(overlay, ov, 0o600); err != nil {
			return 0, err
		}
		start := time.Now()
		if err := goBuild(ctx, dir, overlay); err != nil {
			return 0, err
		}
		runs = append(runs, max(time.Since(start).Milliseconds(), 1))
	}
	slices.Sort(runs)
	return runs[len(runs)/2], nil
}

func goBuild(ctx context.Context, dir, overlay string) error {
	args := []string{"build"}
	if overlay != "" {
		args = append(args, "-overlay", overlay)
	}
	args = append(args, ".")
	cmd := exec.CommandContext(ctx, "go", args...) // #nosec G204 -- fixed arguments
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("codesize: go build in %s: %v\n%s", dir, err, out)
	}
	return nil
}
