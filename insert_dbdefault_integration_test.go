// dbdLive keeps constant database defaults, so one model runs on every dialect.
type dbdLive struct {
	ID   int64
	Name string
	Tag  string
	N    int64
}

var dbdLiveMeta = momo.Meta[dbdLive]{
	Table: "dbd_live",
	Columns: []momo.ColumnMeta{
		{Name: "id", Flags: momo.FlagPK | momo.FlagIdentity},
		{Name: "name"},
		{Name: "tag", Flags: momo.FlagHasDefault | momo.FlagDBDefault},
		{Name: "n", Flags: momo.FlagHasDefault | momo.FlagDBDefault},
	},
	Ptr:      func(m *dbdLive, i int) any { return [...]any{&m.ID, &m.Name, &m.Tag, &m.N}[i] },
	Value:    func(m *dbdLive, i int) any { return [...]any{m.ID, m.Name, m.Tag, m.N}[i] },
	Identity: 0, Version: -1, SoftDelete: -1, CreatedAt: -1, UpdatedAt: -1,
	PK: []int{0},
}

func (*dbdLive) MomoMeta() *momo.Meta[dbdLive] { return &dbdLiveMeta }

var dbdLiveDDL = map[dialect.Name]string{
	dialect.Postgres: "CREATE TABLE dbd_live (id bigint generated by default as identity primary key, name text not null, tag text not null default 'auto', n integer not null default 7)",
	dialect.SQLite:   "CREATE TABLE dbd_live (id integer primary key autoincrement, name text not null, tag text not null default 'auto', n integer not null default 7)",
	dialect.MySQL:    "CREATE TABLE dbd_live (id bigint primary key auto_increment, name varchar(100) not null, tag varchar(20) not null default 'auto', n int not null default 7)",
}

// TestDBDefaultLive checks the dbdefault tag against every available database:
// a zero field takes the database default and is read back, a set field is
// written as given, mixed rows write DEFAULT where the dialect has it, and a
// dialect without RETURNING refuses instead of leaving the model stale.
func TestDBDefaultLive(t *testing.T) {
	testopen.Each(t, func(t *testing.T, db *momo.DB, name dialect.Name) {
		ctx := context.Background()
		for _, stmt := range []string{"DROP TABLE IF EXISTS dbd_live", dbdLiveDDL[name]} {
			if _, err := db.Driver().Exec(ctx, stmt, nil); err != nil {
				t.Fatalf("%s: %v", stmt, err)
			}
		}
		d := db.Driver().Dialect()
		stored := func(rowName string) (tag string, n int64) {
			rows, err := db.Driver().Query(ctx, "SELECT tag, n FROM dbd_live WHERE name = "+placeholder(db), []any{rowName})
			if err != nil {
				t.Fatal(err)
			}
			defer func() { _ = rows.Close() }()
			if !rows.Next() {
				t.Fatalf("row %q not stored", rowName)
			}
			if err := rows.Scan(&tag, &n); err != nil {
				t.Fatal(err)
			}
			return tag, n
		}

		// A column that is set is written as given, on every dialect.
		set := dbdLive{Name: "set", Tag: "mine", N: 3}
		if _, err := momo.Insert[dbdLive](db).Model(&set).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if tag, n := stored("set"); tag != "mine" || n != 3 || set.Tag != "mine" {
			t.Fatalf("set values: stored %q/%d, model %+v", tag, n, set)
		}

		one := dbdLive{Name: "one"}
		_, err := momo.Insert[dbdLive](db).Model(&one).Exec(ctx)
		if !d.Returning && !d.InsertReturning {
			if !errors.Is(err, momo.ErrUnsupported) {
				t.Fatalf("%s cannot read the default back: err = %v, want ErrUnsupported", name, err)
			}
			return
		}
		if err != nil {
			t.Fatal(err)
		}
		if one.Tag != "auto" || one.N != 7 {
			t.Fatalf("defaults not read back: %+v", one)
		}
		if tag, n := stored("one"); tag != "auto" || n != 7 {
			t.Fatalf("stored %q/%d", tag, n)
		}
		if d.OnDuplicateKey && one.ID == 0 {
			t.Fatalf("MariaDB must still read the generated key: %+v", one)
		}

		// Every row unset: the columns leave the statement.
		uniform := []dbdLive{{Name: "u1"}, {Name: "u2"}, {Name: "u3"}}
		if _, err := momo.Insert[dbdLive](db).Models(uniform).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		for _, m := range uniform {
			if m.Tag != "auto" || m.N != 7 {
				t.Fatalf("uniform rows: %+v", uniform)
			}
		}

		// Mixed rows: DEFAULT inside VALUES, or a clear refusal on SQLite.
		mixed := []dbdLive{{Name: "m1"}, {Name: "m2", Tag: "set", N: 5}, {Name: "m3"}}
		_, err = momo.Insert[dbdLive](db).Models(mixed).Exec(ctx)
		if !d.DefaultInValues {
			if !errors.Is(err, momo.ErrUnsupported) {
				t.Fatalf("mixed rows on %s: err = %v, want ErrUnsupported", name, err)
			}
		} else {
			if err != nil {
				t.Fatal(err)
			}
			if mixed[0].Tag != "auto" || mixed[0].N != 7 || mixed[1].Tag != "set" || mixed[1].N != 5 || mixed[2].Tag != "auto" {
				t.Fatalf("mixed rows: %+v", mixed)
			}
			if tag, n := stored("m2"); tag != "set" || n != 5 {
				t.Fatalf("m2 stored %q/%d", tag, n)
			}
		}

		// A chunked bulk insert reads every chunk back.
		chunked := make([]dbdLive, 9)
		for i := range chunked {
			chunked[i].Name = "chunk"
		}
		limited := momo.New(db.Driver(), momo.WithMaxParams(5))
		if _, err := momo.Insert[dbdLive](limited).Models(chunked).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		for i, m := range chunked {
			if m.Tag != "auto" || m.N != 7 {
				t.Fatalf("chunked[%d] not read back: %+v", i, m)
			}
		}
	})
}

// dbdUUID takes its id and timestamp from PostgreSQL functions.
type dbdUUID struct {
	ID        string
	Name      string
	CreatedAt time.Time
}

var dbdUUIDMeta = momo.Meta[dbdUUID]{
	Table: "dbd_uuid",
	Columns: []momo.ColumnMeta{
		{Name: "id", Flags: momo.FlagPK | momo.FlagHasDefault | momo.FlagDBDefault},
		{Name: "name", Flags: momo.FlagUnique},
		{Name: "created_at", Flags: momo.FlagHasDefault | momo.FlagDBDefault},
	},
	Ptr:      func(m *dbdUUID, i int) any { return [...]any{&m.ID, &m.Name, &m.CreatedAt}[i] },
	Value:    func(m *dbdUUID, i int) any { return [...]any{m.ID, m.Name, m.CreatedAt}[i] },
	Identity: -1, Version: -1, SoftDelete: -1, CreatedAt: -1, UpdatedAt: -1,
	PK: []int{0},
}

func (*dbdUUID) MomoMeta() *momo.Meta[dbdUUID] { return &dbdUUIDMeta }

// TestDBDefaultGenRandomUUIDAndNow is the case of issue 69: gen_random_uuid()
// and now() defaults survive Insert.Model and come back through RETURNING.
func TestDBDefaultGenRandomUUIDAndNow(t *testing.T) {
	testopen.Each(t, func(t *testing.T, db *momo.DB, name dialect.Name) {
		if name != dialect.Postgres {
			t.Skip("gen_random_uuid() and now() defaults are PostgreSQL")
		}
		ctx := context.Background()
		for _, stmt := range []string{
			"DROP TABLE IF EXISTS dbd_uuid",
			"CREATE TABLE dbd_uuid (id uuid primary key default gen_random_uuid(), name text not null unique, created_at timestamptz not null default now())",
		} {
			if _, err := db.Driver().Exec(ctx, stmt, nil); err != nil {
				t.Fatalf("%s: %v", stmt, err)
			}
		}

		a := dbdUUID{Name: "a"}
		if _, err := momo.Insert[dbdUUID](db).Model(&a).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if len(a.ID) != 36 || time.Since(a.CreatedAt).Abs() > 5*time.Minute {
			t.Fatalf("defaults not read back: %+v", a)
		}

		given := "00000000-0000-0000-0000-000000000001"
		ms := []dbdUUID{{Name: "b"}, {ID: given, Name: "c"}, {Name: "d"}}
		if _, err := momo.Insert[dbdUUID](db).Models(ms).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if ms[1].ID != given || len(ms[0].ID) != 36 || len(ms[2].ID) != 36 || ms[0].ID == ms[2].ID {
			t.Fatalf("mixed rows: %+v", ms)
		}
		if ms[0].CreatedAt.IsZero() || ms[2].CreatedAt.IsZero() {
			t.Fatalf("created_at not read back: %+v", ms)
		}

		// An upsert that hits the existing row keeps its stored id and reads it back.
		again := dbdUUID{Name: "a"}
		nameCol := momo.NewColumn[string]("dbd_uuid", "name", momo.FlagUnique)
		if _, err := momo.Upsert[dbdUUID](db).OnConflict(nameCol).DoUpdate().Model(&again).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if again.ID != a.ID {
			t.Fatalf("upsert read back id %q, the stored row has %q", again.ID, a.ID)
		}
	})
}
