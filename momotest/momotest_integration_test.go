func migrations() fstest.MapFS {
	return fstest.MapFS{
		"20260101000000_items.up.sql": {Data: []byte(
			`CREATE TABLE items (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE);`)},
	}
}

// rowQuerier is what both the pool driver and a driver transaction offer.
type rowQuerier interface {
	Query(ctx context.Context, sql string, args []any) (momo.Rows, error)
}

func scalar[T any](t *testing.T, q rowQuerier, sql string, args ...any) T {
	t.Helper()
	rows, err := q.Query(t.Context(), sql, args)
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	var v T
	if !rows.Next() {
		t.Fatalf("%s: no row (%v)", sql, rows.Err())
	}
	if err := rows.Scan(&v); err != nil {
		t.Fatal(err)
	}
	return v
}

func countItems(t *testing.T, q rowQuerier) int64 {
	t.Helper()
	return scalar[int64](t, q, "SELECT count(*) FROM items")
}

func schemaExists(t *testing.T, name string) bool {
	t.Helper()
	conn, err := pgx.Connect(t.Context(), os.Getenv(momotest.DefaultEnv))
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close(context.WithoutCancel(t.Context()))
	var n int
	if err := conn.QueryRow(t.Context(), "SELECT count(*) FROM pg_namespace WHERE nspname = $1", name).Scan(&n); err != nil {
		t.Fatal(err)
	}
	return n > 0
}

// TestNewParallelIsolation runs many parallel tests that each insert the same
// unique name: they only succeed if every test has its own schema.
func TestNewParallelIsolation(t *testing.T) {
	// A MySQL or MariaDB job lists its own dialect and has no PostgreSQL URL:
	// every subtest would skip and the count below would be 0.
	if os.Getenv(momotest.DefaultEnv) == "" && os.Getenv("MOMO_INTEGRATION_DIALECTS") != "" &&
		!strings.Contains(strings.ToLower(os.Getenv("MOMO_INTEGRATION_DIALECTS")), "postgres") {
		t.Skip("PostgreSQL is not in MOMO_INTEGRATION_DIALECTS")
	}
	schemas := make(chan string, 8)
	t.Run("group", func(t *testing.T) {
		for i := range 8 {
			t.Run(fmt.Sprint(i), func(t *testing.T) {
				t.Parallel()
				db := momotest.New(t, momotest.WithMigrations(migrations()))
				ctx := t.Context()
				if _, err := momo.Exec(ctx, db, "INSERT INTO items (name) VALUES (?)", "same"); err != nil {
					t.Fatal(err)
				}
				if n := countItems(t, db.Driver()); n != 1 {
					t.Fatalf("items = %d, want 1: another test's rows are visible", n)
				}
				// A real commit works in this mode.
				if err := db.Tx(ctx, momo.TxOptions{}, func(tx *momo.Tx) error {
					_, err := momo.Exec(ctx, tx, "INSERT INTO items (name) VALUES (?)", "committed")
					return err
				}); err != nil {
					t.Fatal(err)
				}
				if n := countItems(t, db.Driver()); n != 2 {
					t.Fatalf("items after commit = %d, want 2", n)
				}
				schemas <- scalar[string](t, db.Driver(), "SELECT current_schema()")
			})
		}
	})
	close(schemas)
	seen := map[string]bool{}
	for s := range schemas {
		if seen[s] {
			t.Errorf("schema %s was used by two tests", s)
		}
		seen[s] = true
		if schemaExists(t, s) {
			t.Errorf("schema %s still exists after its test finished", s)
		}
	}
	if len(seen) != 8 {
		t.Errorf("saw %d schemas, want 8", len(seen))
	}
}

func TestNewWithoutMigrationsIsEmpty(t *testing.T) {
	db := momotest.New(t)
	n := scalar[int64](t, db.Driver(),
		"SELECT count(*) FROM information_schema.tables WHERE table_schema = current_schema()")
	if n != 0 {
		t.Fatalf("tables = %d, want 0", n)
	}
}

func TestNewTxRollsBack(t *testing.T) {
	t.Run("write", func(t *testing.T) {
		tx := momotest.NewTx(t, momotest.WithMigrations(migrations()))
		if _, err := momo.Exec(t.Context(), tx, "INSERT INTO items (name) VALUES (?)", "gone"); err != nil {
			t.Fatal(err)
		}
		if n := countItems(t, tx.DriverTx()); n != 1 {
			t.Fatalf("items = %d, want 1", n)
		}
	})
	tx := momotest.NewTx(t, momotest.WithMigrations(migrations()))
	if n := countItems(t, tx.DriverTx()); n != 0 {
		t.Fatalf("items = %d after the writing test ended, want 0: its transaction was not rolled back", n)
	}
}

func TestNewTxRefusesCommit(t *testing.T) {
	tx := momotest.NewTx(t, momotest.WithMigrations(migrations()))
	if err := tx.Commit(t.Context()); !errors.Is(err, momo.ErrAdoptedTx) {
		t.Fatalf("Commit = %v, want ErrAdoptedTx", err)
	}
	// Savepoints work, and a failed one leaves the transaction usable.
	err := tx.Tx(t.Context(), func(inner *momo.Tx) error {
		if _, err := momo.Exec(t.Context(), inner, "INSERT INTO items (name) VALUES (?)", "a"); err != nil {
			return err
		}
		_, err := momo.Exec(t.Context(), inner, "INSERT INTO items (name) VALUES (?)", "a")
		return err
	})
	if !errors.Is(err, momo.ErrUniqueViolation) {
		t.Fatalf("duplicate insert in savepoint = %v, want ErrUniqueViolation", err)
	}
	if n := countItems(t, tx.DriverTx()); n != 0 {
		t.Fatalf("items = %d after the rolled-back savepoint, want 0", n)
	}
}

func TestNewTxParallel(t *testing.T) {
	t.Run("group", func(t *testing.T) {
		for i := range 8 {
			t.Run(fmt.Sprint(i), func(t *testing.T) {
				t.Parallel()
				tx := momotest.NewTx(t, momotest.WithMigrations(migrations()))
				if _, err := momo.Exec(t.Context(), tx, "INSERT INTO items (name) VALUES (?)", fmt.Sprint("p", i)); err != nil {
					t.Fatal(err)
				}
				if n := countItems(t, tx.DriverTx()); n != 1 {
					t.Fatalf("items = %d, want 1: another test's rows are visible", n)
				}
			})
		}
	})
	tx := momotest.NewTx(t, momotest.WithMigrations(migrations()))
	if n := countItems(t, tx.DriverTx()); n != 0 {
		t.Fatalf("items = %d after the parallel tests, want 0", n)
	}
}

// failTB turns Fatalf into a recorded failure that stops the goroutine, so a
// test can observe what Seed does on error.
type failTB struct {
	testing.TB
	failed bool
}

func (f *failTB) Helper() {}
func (f *failTB) Fatalf(string, ...any) {
	f.failed = true
	runtime.Goexit()
}

func TestSeedIsAtomic(t *testing.T) {
	tx := momotest.NewTx(t, momotest.WithMigrations(migrations()))
	insert := func(name string) momotest.Step {
		return func(ctx context.Context, q momo.Querier) error {
			_, err := momo.Exec(ctx, q, "INSERT INTO items (name) VALUES (?)", name)
			return err
		}
	}
	momotest.Seed(t, tx, insert("a"), insert("b"))
	if n := countItems(t, tx.DriverTx()); n != 2 {
		t.Fatalf("items = %d after Seed, want 2", n)
	}

	f := &failTB{TB: t}
	done := make(chan struct{})
	go func() { defer close(done); momotest.Seed(f, tx, insert("c"), insert("a")) }()
	<-done
	if !f.failed {
		t.Fatal("Seed with a duplicate did not fail the test")
	}
	if n := countItems(t, tx.DriverTx()); n != 2 {
		t.Fatalf("items = %d after a failed Seed, want 2: the first step was kept", n)
	}
}
