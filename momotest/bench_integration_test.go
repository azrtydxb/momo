package momotest_test

import (
	"fmt"
	"strings"
	"testing"
	"testing/fstest"

	"github.com/azrtydxb/momo/momotest"
)

// benchTB gives each benchmark iteration its own cleanup list, so the clone or
// schema of one iteration is removed before the next one is timed.
type benchTB struct {
	testing.TB
	cleanups []func()
}

func (b *benchTB) Cleanup(f func()) { b.cleanups = append(b.cleanups, f) }

func (b *benchTB) release() {
	for i := len(b.cleanups) - 1; i >= 0; i-- {
		b.cleanups[i]()
	}
	b.cleanups = nil
}

// wideMigrations creates n tables with two indexes each, the shape that makes a
// per-test rebuild expensive.
func wideMigrations(n int) fstest.MapFS {
	var sb strings.Builder
	for i := range n {
		fmt.Fprintf(&sb, "CREATE TABLE bench_t%d (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, a text NOT NULL, b bigint NOT NULL, c text);\n", i)
		fmt.Fprintf(&sb, "CREATE INDEX bench_t%d_a ON bench_t%d (a);\nCREATE INDEX bench_t%d_b ON bench_t%d (b, c);\n", i, i, i, i)
	}
	return fstest.MapFS{"20260101000000_bench.up.sql": {Data: []byte(sb.String())}}
}

// BenchmarkMomotestNew times one momotest.New plus its cleanup-free setup on a
// 100-table schema: "schema" rebuilds the schema for every call (the
// default), "clone" (WithTemplateClone) copies the template database. The template is
// built before the timer starts.
func BenchmarkMomotestNew(b *testing.B) {
	fsys := wideMigrations(100)
	for _, mode := range []struct {
		name string
		opts []momotest.Option
	}{
		{"schema", nil},
		{"clone", []momotest.Option{momotest.WithTemplateClone()}},
	} {
		b.Run(mode.name, func(b *testing.B) {
			opts := append([]momotest.Option{momotest.WithMigrations(fsys)}, mode.opts...)
			warm := &benchTB{TB: b}
			momotest.New(warm, opts...)
			warm.release()
			b.ResetTimer()
			for range b.N {
				tb := &benchTB{TB: b}
				momotest.New(tb, opts...)
				b.StopTimer()
				tb.release()
				b.StartTimer()
			}
		})
	}
}
