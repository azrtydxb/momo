// dbdRun has a unique name, so a duplicate fails the run that carries it, and a
// dbdefault tag, so rows that set it and rows that do not form separate runs on
// SQLite.
type dbdRun struct {
	ID   int64
	Name string
	Tag  string
}

var dbdRunMeta = momo.Meta[dbdRun]{
	Table: "dbd_runs",
	Columns: []momo.ColumnMeta{
		{Name: "id", Flags: momo.FlagPK | momo.FlagIdentity},
		{Name: "name"},
		{Name: "tag", Flags: momo.FlagHasDefault | momo.FlagDBDefault},
	},
	Ptr:      func(m *dbdRun, i int) any { return [...]any{&m.ID, &m.Name, &m.Tag}[i] },
	Value:    func(m *dbdRun, i int) any { return [...]any{m.ID, m.Name, m.Tag}[i] },
	Identity: 0, Version: -1, SoftDelete: -1, CreatedAt: -1, UpdatedAt: -1,
	PK: []int{0},
}

func (*dbdRun) MomoMeta() *momo.Meta[dbdRun] { return &dbdRunMeta }

var dbdRunDDL = map[dialect.Name]string{
	dialect.Postgres: "CREATE TABLE dbd_runs (id bigint generated by default as identity primary key, name text not null unique, tag text not null default 'auto')",
	dialect.SQLite:   "CREATE TABLE dbd_runs (id integer primary key autoincrement, name text not null unique, tag text not null default 'auto')",
}

// dbdRunSetup recreates dbd_runs holding one row, "taken".
func dbdRunSetup(t *testing.T, db *momo.DB, d dialect.Name) {
	t.Helper()
	ctx := context.Background()
	for _, stmt := range []string{
		"DROP TABLE IF EXISTS dbd_runs",
		dbdRunDDL[d],
		"INSERT INTO dbd_runs (name, tag) VALUES ('taken', 'old')",
	} {
		if _, err := db.Driver().Exec(ctx, stmt, nil); err != nil {
			t.Fatalf("%s: %v", stmt, err)
		}
	}
	t.Cleanup(func() { _, _ = db.Driver().Exec(context.Background(), "DROP TABLE IF EXISTS dbd_runs", nil) })
}

// failingRuns is three runs on SQLite: tag set, tag unset, tag set again. The
// third carries the duplicate name and fails.
func failingRuns() []dbdRun {
	return []dbdRun{{Name: "run1", Tag: "x"}, {Name: "run2"}, {Name: "taken", Tag: "y"}}
}

func countRuns(t *testing.T, q momo.Querier) int64 {
	t.Helper()
	n, err := momo.Select[dbdRun](q).Count(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	return n
}

// Catches: a split insert that commits its first runs when a later run fails
// (a unique violation in run 3), on a pooled DB and inside a Tx, where only a
// savepoint may roll back and the caller's own rows must survive.
func TestSplitInsertIsAtomicIntegration(t *testing.T) {
	testopen.Each(t, func(t *testing.T, db *momo.DB, d dialect.Name) {
		ctx := context.Background()
		dbdRunSetup(t, db, d)

		if _, err := momo.Insert[dbdRun](db).Models(failingRuns()).Exec(ctx); err == nil {
			t.Fatal("insert with a duplicate in run 3 succeeded")
		}
		if n := countRuns(t, db); n != 1 {
			t.Fatalf("%d rows after the failed insert on a DB, want only the seeded one", n)
		}

		if d != dialect.SQLite {
			return // PostgreSQL runs one statement, with no savepoint to test
		}
		err := db.Tx(ctx, momo.TxOptions{}, func(tx *momo.Tx) error {
			if _, err := momo.Insert[dbdRun](tx).Model(&dbdRun{Name: "kept", Tag: "k"}).Exec(ctx); err != nil {
				return err
			}
			if _, err := momo.Insert[dbdRun](tx).Models(failingRuns()).Exec(ctx); err == nil {
				t.Error("insert with a duplicate in run 3 succeeded inside a Tx")
			}
			if n := countRuns(t, tx); n != 2 {
				t.Errorf("%d rows inside the Tx after the failed insert, want taken and kept", n)
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
		if n := countRuns(t, db); n != 2 {
			t.Fatalf("%d rows after commit, want taken and kept", n)
		}
	})
}

// Catches: Rows closed early leaving the earlier runs committed when a later
// run fails. Close runs the remaining runs, reports the error and rolls the
// whole insert back.
func TestSplitInsertRowsClosedEarlyIntegration(t *testing.T) {
	testopen.Each(t, func(t *testing.T, db *momo.DB, d dialect.Name) {
		ctx := context.Background()
		dbdRunSetup(t, db, d)
		nameCol := momo.NewColumn[string]("dbd_runs", "name", 0)

		rows, err := momo.Insert[dbdRun](db).Models(failingRuns()).Returning(nameCol).Rows(ctx)
		if err == nil {
			rows.Next() // read the first row only, then stop
			err = rows.Close()
		}
		if err == nil {
			t.Fatal("Rows of an insert with a duplicate in run 3 reported no error")
		}
		if n := countRuns(t, db); n != 1 {
			t.Fatalf("%d rows after the failed Rows insert, want only the seeded one", n)
		}
	})
}
