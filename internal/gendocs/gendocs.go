// Package gendocs writes the parts of the documentation that restate facts the
// code already holds: which databases are usable, the dialect capability
// flags, the Go to SQL type table and the dependency versions. Each fact goes
// into a generated block, a span of a Markdown file between
// <!-- generated:NAME --> and <!-- /generated:NAME --> markers; the prose around
// a block stays hand-written. Run it with go generate ./internal/gendocs; CI
// runs go generate for the whole repository and fails on any resulting diff.
//
// The package reads the dialect and typemap packages and the repository's
// files. It imports no database driver and no package that needs cgo, so it
// runs on the lint job's plain Go setup.
package gendocs

//go:generate go run ./cmd/gendocs

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Target names a documentation file and the generated blocks it holds.
type Target struct {
	File   string
	Blocks []string
}

// Targets lists every file the generator writes, in a fixed order.
var Targets = []Target{
	{"README.md", []string{"status"}},
	{"llms.txt", []string{"status"}},
	{"docs/ai-guide.md", []string{"status"}},
	{"docs/supported-versions.md", []string{"status", "dependencies"}},
	{"docs/migrations.md", []string{"status"}},
	{"docs/capabilities.md", []string{"status", "capabilities", "features"}},
	{"docs/TYPE_MAPPING.md", []string{"typemap"}},
}

const note = "<!-- Generated by go generate ./internal/gendocs from the code. Do not edit by hand. -->"

// Markers returns the begin and end marker lines of the block name.
func Markers(name string) (begin, end string) {
	return "<!-- generated:" + name + " -->", "<!-- /generated:" + name + " -->"
}

// Render returns the text of the block name for the repository at root,
// without a trailing newline.
func Render(root, name string) (string, error) {
	switch name {
	case "status":
		return statusBlock(root)
	case "capabilities":
		return capabilitiesBlock(root)
	case "features":
		return featuresBlock(root)
	case "typemap":
		return typemapBlock()
	case "dependencies":
		return dependenciesBlock(root)
	}
	return "", fmt.Errorf("gendocs: unknown block %q", name)
}

// span finds the marker lines of name in lines and returns their indexes.
func span(lines []string, name string) (b, e int, err error) {
	begin, end := Markers(name)
	b, e = -1, -1
	for i, l := range lines {
		switch strings.TrimSpace(l) {
		case begin:
			if b >= 0 {
				return 0, 0, fmt.Errorf("marker %s appears twice", begin)
			}
			b = i
		case end:
			if e >= 0 {
				return 0, 0, fmt.Errorf("marker %s appears twice", end)
			}
			e = i
		}
	}
	if b < 0 || e < 0 {
		return 0, 0, fmt.Errorf("markers %s and %s not both found", begin, end)
	}
	if e < b {
		return 0, 0, fmt.Errorf("marker %s comes before %s", end, begin)
	}
	return b, e, nil
}

// Splice returns doc with the block name replaced by body.
func Splice(doc, name, body string) (string, error) {
	lines := strings.Split(doc, "\n")
	b, e, err := span(lines, name)
	if err != nil {
		return "", err
	}
	out := append([]string{}, lines[:b+1]...)
	out = append(out, "", note, "")
	out = append(out, strings.Split(strings.TrimRight(body, "\n"), "\n")...)
	out = append(out, "")
	out = append(out, lines[e:]...)
	return strings.Join(out, "\n"), nil
}

// Extract returns the body of the block name in doc, the text Splice put there.
func Extract(doc, name string) (string, error) {
	lines := strings.Split(doc, "\n")
	b, e, err := span(lines, name)
	if err != nil {
		return "", err
	}
	text := strings.Trim(strings.Join(lines[b+1:e], "\n"), "\n")
	text = strings.TrimPrefix(text, note)
	return strings.Trim(text, "\n"), nil
}

// StripBlocks returns doc with every generated block removed, for checks on
// the hand-written prose.
func StripBlocks(doc string) string {
	var out []string
	in := false
	for _, l := range strings.Split(doc, "\n") {
		t := strings.TrimSpace(l)
		switch {
		case strings.HasPrefix(t, "<!-- generated:"):
			in = true
		case strings.HasPrefix(t, "<!-- /generated:"):
			in = false
		case !in:
			out = append(out, l)
		}
	}
	return strings.Join(out, "\n")
}

func readFile(path string) (string, error) {
	b, err := os.ReadFile(path) // #nosec G304 -- the repository's own files
	return string(b), err
}

// Generate rewrites every generated block under root. It writes a file only
// when its content changes.
func Generate(root string) error {
	for _, t := range Targets {
		path := filepath.Join(root, filepath.FromSlash(t.File))
		doc, err := readFile(path)
		if err != nil {
			return err
		}
		out := doc
		for _, name := range t.Blocks {
			body, err := Render(root, name)
			if err != nil {
				return fmt.Errorf("%s: %s: %w", t.File, name, err)
			}
			out, err = Splice(out, name, body)
			if err != nil {
				return fmt.Errorf("%s: %s: %w", t.File, name, err)
			}
		}
		if out != doc {
			if err := os.WriteFile(path, []byte(out), 0o644); err != nil { // #nosec G306 -- documentation, world readable
				return err
			}
		}
	}
	return nil
}

// Stale returns one line per generated block whose text in the repository
// differs from what Render produces.
func Stale(root string) ([]string, error) {
	var out []string
	for _, t := range Targets {
		doc, err := readFile(filepath.Join(root, filepath.FromSlash(t.File)))
		if err != nil {
			return nil, err
		}
		for _, name := range t.Blocks {
			want, err := Render(root, name)
			if err != nil {
				return nil, fmt.Errorf("%s: %s: %w", t.File, name, err)
			}
			got, err := Extract(doc, name)
			if err != nil {
				return nil, fmt.Errorf("%s: %s: %w", t.File, name, err)
			}
			if got != strings.Trim(want, "\n") {
				out = append(out, t.File+": block "+name)
			}
		}
	}
	return out, nil
}
