// Command reference writes docs/reference.md: every exported identifier of the
// core and feature packages with the first sentence of its doc comment. It is
// run by go generate; the file is never edited by hand.
package main

//go:generate go run . -root ../../..

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/azrtydxb/momo/internal/docscheck"
)

func main() {
	root := flag.String("root", ".", "module root")
	flag.Parse()
	pkgs, err := docscheck.ReferencePackages(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	out := filepath.Join(*root, "docs", "reference.md")
	if err := os.WriteFile(out, []byte(render(pkgs)), 0o644); err != nil { // #nosec G306 -- a published docs page
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func render(pkgs []*docscheck.Package) string {
	var b strings.Builder
	b.WriteString("<!-- Code generated by go generate (internal/gendocs/reference); DO NOT EDIT. -->\n\n")
	b.WriteString("# API reference\n\n")
	b.WriteString("Every exported identifier of the core package and the feature packages, with the first sentence of its doc comment. ")
	b.WriteString("Methods are listed as `pkg.Type.Method`. The full text of each comment is on [pkg.go.dev](https://pkg.go.dev/github.com/azrtydxb/momo).\n")
	for _, p := range pkgs {
		path := "github.com/azrtydxb/momo"
		if p.Dir != "." {
			path += "/" + p.Dir
		}
		fmt.Fprintf(&b, "\n## %s\n\nImport path: `%s`\n\n", p.Name, path)
		b.WriteString("| Identifier | Kind | Synopsis |\n| --- | --- | --- |\n")
		ids := append([]docscheck.Ident(nil), p.Idents...)
		sort.SliceStable(ids, func(i, j int) bool { return ids[i].Name < ids[j].Name })
		for _, id := range ids {
			syn := strings.ReplaceAll(id.Synopsis(), "|", `\|`)
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", id.Key(p.Name), id.Kind, syn)
		}
	}
	return b.String()
}
