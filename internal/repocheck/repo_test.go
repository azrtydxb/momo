package repocheck

import (
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const spdxTag = "SPDX-License-Identifier: Apache-2.0"

func repoRoot(t *testing.T) string {
	t.Helper()
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	return filepath.Join(wd, "..", "..")
}

func TestRepoFiles(t *testing.T) {
	root := repoRoot(t)
	for _, p := range []string{
		"LICENSE", "SECURITY.md", "CONTRIBUTING.md", "CODE_OF_CONDUCT.md",
		".github/ISSUE_TEMPLATE/bug_report.yml",
		".github/ISSUE_TEMPLATE/feature_request.yml",
		".github/ISSUE_TEMPLATE/config.yml",
		".github/PULL_REQUEST_TEMPLATE.md",
	} {
		if _, err := os.Stat(filepath.Join(root, p)); err != nil {
			t.Errorf("missing %s: %v", p, err)
		}
	}
	lic, err := os.ReadFile(filepath.Join(root, "LICENSE"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(lic), "Apache License") || !strings.Contains(string(lic), "Version 2.0, January 2004") {
		t.Error("LICENSE is not the Apache-2.0 text")
	}
	err = filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			switch d.Name() {
			// .claude holds local agent worktrees (gitignored); they are
			// separate checkouts, not part of this tree.
			case ".git", "testdata", ".procoder", ".claude":
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") {
			return nil
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if strings.HasPrefix(string(b), "// Code generated by momo ") {
			return nil
		}
		head := string(b)
		if len(head) > 600 {
			head = head[:600]
		}
		if !strings.Contains(head, spdxTag) {
			t.Errorf("%s: missing SPDX header", path)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}
