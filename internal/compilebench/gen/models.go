package main

import (
	"fmt"
	"strings"
)

// col is one model column.
type col struct {
	Name string // Go field name, also the companion package's variable name
	Type string // Go type without the pointer
	Null bool   // a pointer field: the companion emits a NullColumn
	Tag  string // momo struct tag value, without quotes
}

// rowType is the type a Row tuple uses for the column: NULLable columns scan
// into a pointer.
func (c col) rowType() string {
	if c.Null {
		return "*" + c.Type
	}
	return c.Type
}

// model is one generated model struct.
type model struct {
	Idx      int
	Type     string // Rec007
	Pkg      string // rec007, the companion package
	Table    string
	Cols     []col
	Parent   bool // belongs_to the previous model
	Children bool // has_many of the next model
	Peers    bool // many2many with the model two ahead
}

// extras are the optional columns. Each model keeps a deterministic subset, so
// the models do not all share one struct layout (identical layouts would
// collapse into one generic shape and hide the fan-out being measured).
var extras = []col{
	{Name: "Email", Type: "string", Tag: "size:200"},
	{Name: "Status", Type: "string", Tag: "size:50"},
	{Name: "Score", Type: "int64"},
	{Name: "Ratio", Type: "float64"},
	{Name: "Active", Type: "bool"},
	{Name: "Note", Type: "string", Null: true},
	{Name: "Born", Type: "time.Time"},
	{Name: "Hits", Type: "int64"},
	{Name: "Slug", Type: "string", Tag: "size:100"},
	{Name: "Weight", Type: "float64", Null: true},
}

func newModels(n int) []model {
	ms := make([]model, n)
	for i := range ms {
		cols := []col{
			{Name: "ID", Type: "int64", Tag: "pk,identity"},
			{Name: "Name", Type: "string", Tag: "size:200,notnull"},
			{Name: "ParentID", Type: "int64", Tag: "index"},
		}
		for j, e := range extras {
			if (i*5+j*3)%7 < 4 {
				cols = append(cols, e)
			}
		}
		ms[i] = model{
			Idx:      i,
			Type:     fmt.Sprintf("Rec%03d", i),
			Pkg:      fmt.Sprintf("rec%03d", i),
			Table:    fmt.Sprintf("rec_%03d", i),
			Cols:     cols,
			Parent:   i > 0,
			Children: i < n-1,
			Peers:    i%4 == 0 && i+2 < n,
		}
	}
	return ms
}

// modelsSource is the hand-written part of the models package; momo generate
// adds the Meta and one companion package per model.
func modelsSource(ms []model) []byte {
	var b strings.Builder
	usesTime := false
	for _, m := range ms {
		for _, c := range m.Cols {
			usesTime = usesTime || c.Type == "time.Time"
		}
	}
	b.WriteString("// SPDX-License-Identifier: Apache-2.0\n\n")
	b.WriteString("// Package models is the compile-memory fixture's schema (generated by\n")
	b.WriteString("// internal/compilebench/gen, never committed).\npackage models\n\n")
	b.WriteString("import (\n")
	if usesTime {
		b.WriteString("\t\"time\"\n\n")
	}
	b.WriteString("\t\"github.com/azrtydxb/momo\"\n)\n\n")
	for _, m := range ms {
		fmt.Fprintf(&b, "// %s is model %d of the fixture.\ntype %s struct {\n", m.Type, m.Idx, m.Type)
		fmt.Fprintf(&b, "\tmomo.Model `momo:\"table:%s\"`\n", m.Table)
		for _, c := range m.Cols {
			typ := c.Type
			if c.Null {
				typ = "*" + typ
			}
			if c.Tag != "" {
				fmt.Fprintf(&b, "\t%s %s `momo:\"%s\"`\n", c.Name, typ, c.Tag)
			} else {
				fmt.Fprintf(&b, "\t%s %s\n", c.Name, typ)
			}
		}
		if m.Parent {
			fmt.Fprintf(&b, "\tParent *%s `momo:\"belongs_to,fk:ParentID\"`\n", ms[m.Idx-1].Type)
		}
		if m.Children {
			fmt.Fprintf(&b, "\tChildren []%s `momo:\"has_many,fk:ParentID\"`\n", ms[m.Idx+1].Type)
		}
		if m.Peers {
			fmt.Fprintf(&b, "\tPeers []%s `momo:\"many2many,join:%s_peers\"`\n", ms[m.Idx+2].Type, m.Table)
		}
		b.WriteString("}\n\n")
	}
	return []byte(b.String())
}
