package main

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// gen builds the caller package. Every query function takes a *momo.DB and
// returns an error; it is compiled, never run, so the values are arbitrary.
type gen struct {
	ms   []model
	root string
}

// fileB collects the imports one caller file needs.
type fileB struct{ imps map[string]string } // import path -> alias

func (f *fileB) use(path, alias string) { f.imps[path] = alias }

// shape writes one query statement list that declares err.
type shape struct {
	name string
	fn   func(g *gen, f *fileB, k int) string
}

var shapes []shape

func init() {
	for n := 1; n <= 8; n++ {
		shapes = append(shapes, shape{fmt.Sprintf("select-row%d", n), selectRow(n)})
	}
	shapes = append(shapes,
		shape{"select-model", selectModel},
		shape{"count-exists", countExists},
		shape{"where-and-or-not", whereAndOrNot},
		shape{"where-in-between", whereInBetween},
		shape{"join-row", joinRow(false)},
		shape{"left-join-row", joinRow(true)},
		shape{"order-limit-offset", orderLimitOffset},
		shape{"aggregate-group-by", aggregateGroupBy},
		shape{"aggregate-scalar", aggregateScalar},
		shape{"update-set-chain", updateSet},
		shape{"insert-values", insertValues},
		shape{"insert-model-returning", insertModel},
		shape{"upsert", upsert},
		shape{"relation-load", relationLoad},
		shape{"exists-subquery", existsSubquery},
	)
}

// callerFile writes queries first..last-1 as one source file.
func (g *gen) callerFile(first, last int) []byte {
	f := &fileB{imps: map[string]string{}}
	f.use("context", "context")
	f.use("github.com/azrtydxb/momo", "momo")
	var body strings.Builder
	for k := first; k < last; k++ {
		s := shapes[k%len(shapes)]
		stmts := s.fn(g, f, k)
		fmt.Fprintf(&body, "// Q%04d is a %s query.\nfunc Q%04d(ctx context.Context, db *momo.DB) error {\n%s\nreturn err\n}\n\n", k, s.name, k, stmts)
	}
	var b strings.Builder
	b.WriteString("// SPDX-License-Identifier: Apache-2.0\n\n")
	b.WriteString("// Package caller is the compile-memory fixture's query package (generated by\n")
	b.WriteString("// internal/compilebench/gen, never committed).\npackage caller\n\nimport (\n")
	paths := make([]string, 0, len(f.imps))
	for p := range f.imps {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		fmt.Fprintf(&b, "\t%s %q\n", f.imps[p], p)
	}
	b.WriteString(")\n\n")
	b.WriteString(body.String())
	return []byte(b.String())
}

// idx spreads the queries over the models: a stride that is coprime to most
// model counts, shifted each time the shape list wraps.
func (g *gen) idx(k int) int { return (k*37 + k/len(shapes)) % len(g.ms) }

func (g *gen) model(k int) model { return g.ms[g.idx(k)] }

// pair returns a model and the next one, the parent and child of a Children
// relation.
func (g *gen) pair(k int) (model, model) {
	j := min(g.idx(k), len(g.ms)-2)
	return g.ms[j], g.ms[j+1]
}

// triple returns three consecutive models, for a nested relation load.
func (g *gen) triple(k int) (model, model, model) {
	j := min(g.idx(k), len(g.ms)-3)
	return g.ms[j], g.ms[j+1], g.ms[j+2]
}

// pkg is the model's companion package, imported on first use.
func (g *gen) pkg(f *fileB, m model) string {
	f.use(g.root+"/models/"+m.Pkg, m.Pkg)
	return m.Pkg
}

// mtype is the model struct type, imported on first use.
func (g *gen) mtype(f *fileB, m model) string {
	f.use(g.root+"/models", "models")
	return "models." + m.Type
}

func (g *gen) ref(f *fileB, m model, c col) string { return g.pkg(f, m) + "." + c.Name }

func useType(f *fileB, t string) {
	if strings.Contains(t, "time.") {
		f.use("time", "time")
	}
}

// rowOf is the Row tuple type for the given column types.
func rowOf(f *fileB, types []string) string {
	for _, t := range types {
		useType(f, t)
	}
	return fmt.Sprintf("momo.Row%d[%s]", len(types), strings.Join(types, ", "))
}

// pick returns n columns of m starting at a spot that moves with k.
func pick(m model, k, n int) []col {
	start := (k / 3) % len(m.Cols)
	cs := make([]col, n)
	for i := range cs {
		cs[i] = m.Cols[(start+i)%len(m.Cols)]
	}
	return cs
}

func (g *gen) refs(f *fileB, m model, cs []col) []string {
	out := make([]string, len(cs))
	for i, c := range cs {
		out[i] = g.ref(f, m, c)
	}
	return out
}

func rowTypes(cs []col) []string {
	out := make([]string, len(cs))
	for i, c := range cs {
		out[i] = c.rowType()
	}
	return out
}

// lit is a literal of the column's type.
func lit(f *fileB, c col, k int) string {
	switch c.Type {
	case "int64":
		return strconv.Itoa(k%97 + 1)
	case "string":
		return strconv.Quote("v" + strconv.Itoa(k%89))
	case "float64":
		return strconv.Itoa(k%9) + ".5"
	case "bool":
		return strconv.FormatBool(k%2 == 0)
	case "time.Time":
		f.use("time", "time")
		return "time.Time{}"
	}
	panic("lit: unknown column type " + c.Type)
}

// pred is a predicate on one column of m; the column and the operator move
// with k.
func (g *gen) pred(f *fileB, m model, k int) string {
	c := m.Cols[(k*3+1)%len(m.Cols)]
	r := g.ref(f, m, c)
	if c.Null && k%7 == 0 {
		return r + ".IsNull()"
	}
	switch c.Type {
	case "int64":
		switch k % 6 {
		case 0:
			return fmt.Sprintf("%s.Eq(%s)", r, lit(f, c, k))
		case 1:
			return fmt.Sprintf("%s.Gt(%s)", r, lit(f, c, k))
		case 2:
			return fmt.Sprintf("%s.Lt(%s)", r, lit(f, c, k))
		case 3:
			return fmt.Sprintf("%s.Ne(%s)", r, lit(f, c, k))
		case 4:
			return fmt.Sprintf("%s.In(1, 2, 3, %s)", r, lit(f, c, k))
		}
		return fmt.Sprintf("%s.Between(1, %s)", r, lit(f, c, k))
	case "string":
		switch k % 4 {
		case 0:
			return fmt.Sprintf("%s.Eq(%s)", r, lit(f, c, k))
		case 1:
			return fmt.Sprintf("%s.Ne(%s)", r, lit(f, c, k))
		case 2:
			return fmt.Sprintf("%s.In(%s, \"b\")", r, lit(f, c, k))
		}
		return fmt.Sprintf("momo.Like(%s, \"x%%\")", r)
	case "float64":
		if k%2 == 0 {
			return fmt.Sprintf("%s.Gt(%s)", r, lit(f, c, k))
		}
		return fmt.Sprintf("%s.Between(0.5, %s)", r, lit(f, c, k))
	case "bool":
		return fmt.Sprintf("%s.Eq(%s)", r, lit(f, c, k))
	}
	if k%2 == 0 {
		return fmt.Sprintf("%s.Gt(%s)", r, lit(f, c, k))
	}
	return fmt.Sprintf("%s.Le(%s)", r, lit(f, c, k))
}

// orderBy is an ORDER BY item on a column of m.
func (g *gen) orderBy(f *fileB, m model, k int) string {
	c := m.Cols[(k*5+2)%len(m.Cols)]
	if k%2 == 0 {
		return g.ref(f, m, c) + ".Asc()"
	}
	return g.ref(f, m, c) + ".Desc()"
}

func selectRow(n int) func(*gen, *fileB, int) string {
	return func(g *gen, f *fileB, k int) string {
		m := g.model(k)
		cs := pick(m, k, n)
		term := []string{"All", "First", "One"}[k%3]
		return fmt.Sprintf("_, err := momo.Select[%s](db).From(%s.Table).Columns(%s).Where(%s).OrderBy(%s).Limit(%d).%s(ctx)",
			rowOf(f, rowTypes(cs)), g.pkg(f, m), strings.Join(g.refs(f, m, cs), ", "), g.pred(f, m, k), g.orderBy(f, m, k), 10+k%90, term)
	}
}

func selectModel(g *gen, f *fileB, k int) string {
	m := g.model(k)
	return fmt.Sprintf("_, err := momo.Select[%s](db).Where(%s, %s).OrderBy(%s).Limit(%d).All(ctx)",
		g.mtype(f, m), g.pred(f, m, k), g.pred(f, m, k+1), g.orderBy(f, m, k), 5+k%50)
}

func countExists(g *gen, f *fileB, k int) string {
	m := g.model(k)
	term := "Count"
	if k%2 == 1 {
		term = "Exists"
	}
	return fmt.Sprintf("_, err := momo.Select[%s](db).Where(%s).%s(ctx)", g.mtype(f, m), g.pred(f, m, k), term)
}

func whereAndOrNot(g *gen, f *fileB, k int) string {
	m := g.model(k)
	return fmt.Sprintf("_, err := momo.Select[%s](db).Where(momo.And(%s, momo.Or(%s, %s), momo.Not(%s))).All(ctx)",
		g.mtype(f, m), g.pred(f, m, k), g.pred(f, m, k+1), g.pred(f, m, k+2), g.pred(f, m, k+3))
}

func whereInBetween(g *gen, f *fileB, k int) string {
	m := g.model(k)
	p := g.pkg(f, m)
	return fmt.Sprintf("_, err := momo.Select[%s](db).Where(%s.ID.In(1, 2, 3, %d), %s.ParentID.NotIn(%d), %s.ID.Between(1, %d)).All(ctx)",
		g.mtype(f, m), p, k%50, p, k%7, p, 100+k%900)
}

func joinRow(left bool) func(*gen, *fileB, int) string {
	return func(g *gen, f *fileB, k int) string {
		a, b := g.pair(k)
		na, nb := 1+k%3, 1+(k/3)%3
		ca, cb := pick(a, k, na), pick(b, k+1, nb)
		var types []string
		for _, c := range ca {
			types = append(types, c.rowType())
		}
		for _, c := range cb {
			t := c.rowType()
			if left && !c.Null {
				t = "*" + t
			}
			types = append(types, t)
		}
		refs := append(g.refs(f, a, ca), g.refs(f, b, cb)...)
		join := "Join"
		if left {
			join = "LeftJoin"
		}
		return fmt.Sprintf("_, err := momo.Select[%s](db).From(%s.Table).%s(%s.Table, %s.ParentID.EqExpr(%s.ID)).Columns(%s).Where(%s).OrderBy(%s).Limit(%d).All(ctx)",
			rowOf(f, types), g.pkg(f, a), join, g.pkg(f, b), g.pkg(f, b), g.pkg(f, a),
			strings.Join(refs, ", "), g.pred(f, a, k), g.orderBy(f, a, k), 20+k%30)
	}
}

func orderLimitOffset(g *gen, f *fileB, k int) string {
	m := g.model(k)
	cs := pick(m, k, 4)
	return fmt.Sprintf("_, err := momo.Select[%s](db).From(%s.Table).Columns(%s).Where(%s).OrderBy(%s, %s, %s.ID.Asc()).Limit(%d).Offset(%d).All(ctx)",
		rowOf(f, rowTypes(cs)), g.pkg(f, m), strings.Join(g.refs(f, m, cs), ", "),
		g.pred(f, m, k), g.orderBy(f, m, k), g.orderBy(f, m, k+1), g.pkg(f, m), 10+k%20, k%100)
}

func aggregateGroupBy(g *gen, f *fileB, k int) string {
	m := g.model(k)
	p := g.pkg(f, m)
	return fmt.Sprintf("_, err := momo.Select[momo.Row3[string, int64, *int64]](db).From(%s.Table).Columns(%s.Name, momo.CountAll(), momo.Max(%s.ID)).Where(%s).GroupBy(%s.Name).Having(momo.CountAll().Gt(%d)).OrderBy(momo.Desc(momo.CountAll())).All(ctx)",
		p, p, p, g.pred(f, m, k), p, k%5)
}

func aggregateScalar(g *gen, f *fileB, k int) string {
	m := g.model(k)
	p := g.pkg(f, m)
	return fmt.Sprintf("_, err := momo.Select[momo.Row4[int64, *int64, *float64, *int64]](db).From(%s.Table).Columns(momo.CountAll(), momo.Sum(%s.ID), momo.Avg(%s.ID), momo.Min(%s.ID)).Where(%s).One(ctx)",
		p, p, p, p, g.pred(f, m, k))
}

// assignments is n Set/SetNull calls on columns after the primary key.
func (g *gen) assignments(f *fileB, m model, k, n int) string {
	rest := m.Cols[1:]
	parts := make([]string, n)
	for i := range parts {
		c := rest[(k+i)%len(rest)]
		r := g.ref(f, m, c)
		if c.Null && (k+i)%3 == 0 {
			parts[i] = r + ".SetNull()"
			continue
		}
		parts[i] = fmt.Sprintf("%s.Set(%s)", r, lit(f, c, k+i))
	}
	return strings.Join(parts, ", ")
}

func updateSet(g *gen, f *fileB, k int) string {
	m := g.model(k)
	return fmt.Sprintf("_, err := momo.Update[%s](db).Set(%s).Where(%s, %s.ID.Eq(%d)).Exec(ctx)",
		g.mtype(f, m), g.assignments(f, m, k, 1+k%5), g.pred(f, m, k), g.pkg(f, m), k%1000+1)
}

func insertValues(g *gen, f *fileB, k int) string {
	m := g.model(k)
	return fmt.Sprintf("_, err := momo.Insert[%s](db).Values(%s).Exec(ctx)", g.mtype(f, m), g.assignments(f, m, k, 2+k%4))
}

func insertModel(g *gen, f *fileB, k int) string {
	m := g.model(k)
	t := g.mtype(f, m)
	return fmt.Sprintf("var row %s\nrow.Name = %q\n_, err := momo.Insert[%s](db).Model(&row).ReturningAll().One(ctx)", t, "n"+strconv.Itoa(k), t)
}

func upsert(g *gen, f *fileB, k int) string {
	m := g.model(k)
	t := g.mtype(f, m)
	rest := m.Cols[1:]
	a, b := rest[k%len(rest)], rest[(k+1)%len(rest)]
	return fmt.Sprintf("var row %s\nrow.Name = %q\n_, err := momo.Upsert[%s](db).Model(&row).OnConflict(%s.ID).DoUpdate(%s.SetExcluded(), %s.SetExcluded()).Exec(ctx)",
		t, "n"+strconv.Itoa(k), t, g.pkg(f, m), g.ref(f, m, a), g.ref(f, m, b))
}

func relationLoad(g *gen, f *fileB, k int) string {
	a, b := g.pair(k)
	ta, tb := g.mtype(f, a), g.mtype(f, b)
	pa, pb := g.pkg(f, a), g.pkg(f, b)
	switch k % 6 {
	case 0:
		return fmt.Sprintf("var rows []%s\nerr := momo.Load(ctx, db, rows, %s.Children)", ta, pa)
	case 1:
		return fmt.Sprintf("var rows []%s\nerr := momo.Load(ctx, db, rows, %s.Children, momo.LoadWhere[%s](%s), momo.LoadOrderBy[%s](%s))",
			ta, pa, tb, g.pred(f, b, k), tb, g.orderBy(f, b, k))
	case 2:
		return fmt.Sprintf("_, err := momo.Select[%s](db).Where(%s).Preload(%s.Children).All(ctx)", ta, g.pred(f, a, k), pa)
	case 3:
		x, y, z := g.triple(k)
		return fmt.Sprintf("_, err := momo.Select[%s](db).Preload(%s.Children.Then(%s.Children.Scope(momo.LoadPerParentLimit[%s](3)))).All(ctx)",
			g.mtype(f, x), g.pkg(f, x), g.pkg(f, y), g.mtype(f, z))
	case 4:
		if a.Peers {
			return fmt.Sprintf("var rows []%s\nerr := momo.LoadAll(ctx, db, rows, %s.Children, %s.Peers)", ta, pa, pa)
		}
		return fmt.Sprintf("var rows []%s\nerr := momo.LoadAll(ctx, db, rows, %s.Children)", ta, pa)
	}
	return fmt.Sprintf("_, err := momo.Select[%s](db).Where(%s).Preload(%s.Parent).All(ctx)", tb, g.pred(f, b, k), pb)
}

func existsSubquery(g *gen, f *fileB, k int) string {
	a, b := g.pair(k)
	if k%2 == 0 {
		return fmt.Sprintf("_, err := momo.Select[%s](db).Where(%s.Children.Has(%s)).All(ctx)", g.mtype(f, a), g.pkg(f, a), g.pred(f, b, k))
	}
	return fmt.Sprintf("_, err := momo.Select[%s](db).Where(momo.Exists(momo.Select[momo.Row1[int64]](db).From(%s.Table).Columns(%s.ID).Where(%s.ParentID.EqExpr(%s.ID)))).All(ctx)",
		g.mtype(f, a), g.pkg(f, b), g.pkg(f, b), g.pkg(f, b), g.pkg(f, a))
}
