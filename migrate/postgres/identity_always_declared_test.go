func identityAlwaysSchema(t *testing.T) *schema.Schema {
	t.Helper()
	dir, err := filepath.Abs("../../gen/testdata/fixtures")
	if err != nil {
		t.Fatal(err)
	}
	g, diags, err := gen.Load([]string{"./identityalways"}, gen.Config{Dir: dir})
	if err != nil || len(diags) != 0 {
		t.Fatalf("load: %v %v", err, diags)
	}
	s, sd := gen.BuildSchema(g.Models, gen.Config{Dialects: []dialect.Name{dialect.Postgres}})
	if len(sd) != 0 {
		t.Fatalf("schema diagnostics: %v", sd)
	}
	s.Extensions = []schema.Extension{{Name: "vector"}} // inspection reports every installed extension
	return s
}

// TestDeclaredIdentityAlways is issue 56 on PostgreSQL: identity:always
// renders GENERATED ALWAYS AS IDENTITY, inspects back as always without a
// diff, and the database refuses a client-supplied value. A later switch of
// the kind is an ALTER COLUMN ... SET GENERATED.
func TestDeclaredIdentityAlways(t *testing.T) {
	ctx := context.Background()
	db := testopen.Postgres(t)
	desired := identityAlwaysSchema(t)

	stmts := planStatements(t, &schema.Schema{Dialect: "postgres"}, desired, migrate.DiffOptions{})
	var sql strings.Builder
	for _, s := range stmts {
		sql.WriteString(s.SQL + "\n")
	}
	if !strings.Contains(sql.String(), "GENERATED ALWAYS AS IDENTITY") || !strings.Contains(sql.String(), "GENERATED BY DEFAULT AS IDENTITY") {
		t.Errorf("rendered SQL lacks both identity kinds:\n%s", sql.String())
	}
	applyStatements(t, db, stmts)

	exec := func(q string) error {
		_, err := db.Driver().Exec(ctx, q, nil)
		return err
	}
	if err := exec(`INSERT INTO ledger (body) VALUES ('a')`); err != nil {
		t.Fatal(err)
	}
	if err := exec(`INSERT INTO ledger (seq, body) VALUES (99, 'b')`); err == nil {
		t.Fatal("a client-supplied value for a GENERATED ALWAYS column was accepted")
	}

	got := inspectNow(t, db)
	want := identityAlwaysSchema(t)
	if err := mpg.New().Canonicalize(ctx, pinned(t, db), want); err != nil {
		t.Fatalf("canonicalize: %v", err)
	}
	if !schema.Equal(got, want) {
		t.Fatalf("round trip has a diff:\n%s", migratetest.Diff(got, want))
	}
	if again, _, err := migrate.Diff(got, want, migrate.DiffOptions{}); err != nil || len(again) != 0 {
		t.Fatalf("second diff must be empty: %v %+v", err, again)
	}

	// Switching the kind is a metadata change.
	switched := identityAlwaysSchema(t)
	led := slices.IndexFunc(switched.Tables, func(tb schema.Table) bool { return tb.Name == "ledger" })
	switched.Tables[led].Columns[0].Identity = "by_default"
	applyStatements(t, db, planStatements(t, got, switched, migrate.DiffOptions{}))
	if err := exec(`INSERT INTO ledger (seq, body) VALUES (99, 'b')`); err != nil {
		t.Fatalf("by default must accept a supplied value after the switch: %v", err)
	}
}
