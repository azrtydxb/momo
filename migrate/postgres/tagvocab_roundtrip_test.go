// tagvocabSchema loads the tag vocabulary fixture and builds its schema.
func tagvocabSchema(t *testing.T) *schema.Schema {
	t.Helper()
	dir, err := filepath.Abs("../../gen/testdata/fixtures")
	if err != nil {
		t.Fatal(err)
	}
	g, diags, err := gen.Load([]string{"./tagvocab"}, gen.Config{Dir: dir})
	if err != nil || len(diags) != 0 {
		t.Fatalf("load: %v %v", err, diags)
	}
	s, sd := gen.BuildSchema(g.Models, gen.Config{Dialects: []dialect.Name{dialect.Postgres}})
	if len(sd) != 0 {
		t.Fatalf("schema diagnostics: %v", sd)
	}
	return s
}

// TestTagVocabularyRoundTrip is the migration and inspection half of S-70:
// every tag reaches the generated schema, the rendered SQL, and survives
// apply-then-inspect without drift.
func TestTagVocabularyRoundTrip(t *testing.T) {
	desired := tagvocabSchema(t)

	// Schema half: each tag's effect is present before any SQL is involved.
	art, ok := desired.Table("articles")
	if !ok {
		t.Fatal("articles missing")
	}
	wantTypes := map[string]string{
		"title": "varchar(200)", "price": "numeric(10,2)", "notes": "text",
		"embedding": "vector(3)", "half": "halfvec(4)", "sparse": "sparsevec(5)", "flags": "bit(8)",
		"state": "article_state",
	}
	for col, typ := range wantTypes {
		c, ok := art.Column(col)
		if !ok || c.Type != typ {
			t.Errorf("column %s = %+v, want type %s", col, c, typ)
		}
	}

	if c, _ := art.Column("slug"); c == nil || c.Default != "'untitled'" || c.Nullable {
		t.Errorf("slug = %+v", c)
	}
	if c, _ := art.Column("summary"); c == nil || c.Comment != "short summary" || !c.Nullable {
		t.Errorf("summary = %+v", c)
	}
	if c, _ := art.Column("id"); c == nil || c.Identity != "by_default" {
		t.Errorf("id = %+v", c)
	}
	if ix, ok := art.Index("articles_title_sorted"); !ok || len(ix.Parts) != 1 || !ix.Parts[0].Desc || ix.Parts[0].Nulls != "last" {
		t.Errorf("articles_title_sorted = %+v", ix)
	}
	if ix, ok := art.Index("articles_slug_uniq"); !ok || !ix.Unique {
		t.Errorf("articles_slug_uniq = %+v", ix)
	}
	if ix, ok := art.Index("articles_emb_hnsw"); !ok || ix.Method != "hnsw" {
		t.Errorf("articles_emb_hnsw = %+v", ix)
	}
	if len(art.Checks) != 1 || art.Checks[0].Expr != "rating BETWEEN 0 AND 5" {
		t.Errorf("checks = %+v", art.Checks)
	}
	if len(art.ForeignKeys) != 1 || art.ForeignKeys[0].OnDelete != "CASCADE" || art.ForeignKeys[0].OnUpdate != "RESTRICT" {
		t.Errorf("foreign keys = %+v", art.ForeignKeys)
	}
	if org, _ := desired.Table("orgs"); org == nil {
		t.Error("orgs missing")
	} else if c, _ := org.Column("name"); c == nil || c.Collate != "C" || c.Comment != "the org name" || c.Type != "varchar(80)" {
		t.Errorf("orgs.name = %+v", c)
	}
	if _, ok := desired.Table("article_tags"); !ok {
		t.Error("join table article_tags missing")
	}

	// Migration SQL half: each tag appears in the rendered statements.
	stmts := planStatements(t, &schema.Schema{Dialect: "postgres"}, desired, migrate.DiffOptions{})
	var sql strings.Builder
	for _, s := range stmts {
		sql.WriteString(s.SQL + "\n")
	}
	lower := strings.ToLower(sql.String())
	for _, frag := range []string{
		"varchar(200)", "numeric(10,2)", "vector(3)", "halfvec(4)", "sparsevec(5)", "bit(8)",
		"collate", "check", "on delete cascade", "on update restrict", "article_tags", `using "hnsw"`, "desc",
		"nulls last", "comment on column", "default 'untitled'", "generated by default as identity",
	} {
		if !strings.Contains(lower, frag) {
			t.Errorf("rendered SQL lacks %q:\n%s", frag, sql.String())
		}
	}

	// Inspection half: apply to PostgreSQL, inspect, compare.
	//
	// Declared expression text (the CHECK here) is canonicalized through the
	// database before it is compared, exactly as the engine does for drift:
	// PostgreSQL deparses `BETWEEN` into two comparisons, so the raw tag text
	// is not what inspection reads back.
	db := testopen.Postgres(t)
	applyStatements(t, db, stmts)
	got := inspectNow(t, db)
	want := tagvocabSchema(t)
	if err := mpg.New().Canonicalize(context.Background(), pinned(t, db), want); err != nil {
		t.Fatalf("canonicalize: %v", err)
	}
	if !schema.Equal(got, want) {
		t.Fatalf("round trip has a diff:\n%s", migratetest.Diff(got, want))
	}
	again, _, err := migrate.Diff(got, want, migrate.DiffOptions{})
	if err != nil || len(again) != 0 {
		t.Fatalf("second diff must be empty: %v %+v", err, again)
	}
}
