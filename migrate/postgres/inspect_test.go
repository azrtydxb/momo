func mustExec(t *testing.T, d momo.Driver, sql string) {
	t.Helper()
	if _, err := d.Exec(context.Background(), sql, nil); err != nil {
		t.Fatalf("exec %q: %v", sql, err)
	}
}

func pinned(t *testing.T, db *momo.DB) momo.PinnedConn {
	t.Helper()
	p, ok := db.Driver().(momo.Pinner)
	if !ok {
		t.Fatal("driver cannot pin")
	}
	c, err := p.Pin(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = c.Release() })
	return c
}

// inspectOnce inspects on a connection released before it returns. pinned
// holds its connection until t.Cleanup, so it is for a test that deliberately
// keeps one; a one-shot call through it leaks a pool slot per use.
func inspectOnce(ctx context.Context, t *testing.T, db *momo.DB, opts migrate.InspectOptions) (*schema.Schema, error) {
	t.Helper()
	c, err := db.Driver().(momo.Pinner).Pin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = c.Release() }()
	return mpg.New().Inspect(ctx, c, opts)
}

func TestPostgresInspectColumnsAndConstraints(t *testing.T) {
	db := testopen.Postgres(t)
	ctx := context.Background()
	mustExec(t, db.Driver(), `CREATE EXTENSION IF NOT EXISTS vector`)
	mustExec(t, db.Driver(), `CREATE TYPE status AS ENUM ('draft','live')`)
	mustExec(t, db.Driver(), `CREATE TABLE orgs (id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY)`)
	mustExec(t, db.Driver(), `CREATE TABLE docs (
        id bigint PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
        org_id bigint NOT NULL REFERENCES orgs(id) ON DELETE CASCADE ON UPDATE SET NULL,
        state status NOT NULL DEFAULT 'draft',
        emb vector(3),
        CONSTRAINT docs_state_check CHECK (id > 0)
    )`)
	c := pinned(t, db)
	got, err := mpg.New().Inspect(ctx, c, migrate.InspectOptions{Schemas: []string{testdb.Schema(t)}})
	if err != nil {
		t.Fatal(err)
	}
	docs, ok := got.Table("docs")
	if !ok {
		t.Fatal("docs missing")
	}
	if len(docs.ForeignKeys) != 1 {
		t.Fatalf("want one foreign key, got %+v", docs.ForeignKeys)
	}
	if docs.ForeignKeys[0].OnDelete != "CASCADE" || docs.ForeignKeys[0].OnUpdate != "SET NULL" {
		t.Fatalf("fk actions: %+v", docs.ForeignKeys[0])
	}
	col, ok := docs.Column("state")
	if !ok {
		t.Fatalf("column %q missing", "state")
	}
	if col.Enum != "status" || col.Default != "'draft'::status" {
		t.Fatalf("enum column: %+v", col)
	}
	col, ok = docs.Column("id")
	if !ok {
		t.Fatalf("column %q missing", "id")
	}
	if col.Identity != "always" {
		t.Fatalf("identity: %+v", col)
	}
	col, ok = docs.Column("emb")
	if !ok {
		t.Fatalf("column %q missing", "emb")
	}
	if col.Type != "vector(3)" {
		t.Fatalf("vector type: %+v", col)
	}
	if len(got.Enums) == 1 && !slices.Equal(got.Enums[0].Values, []string{"draft", "live"}) {
		t.Fatalf("enum values: %+v", got.Enums[0].Values)
	}
	if len(got.Enums) != 1 || len(got.Extensions) != 1 {
		t.Fatalf("enums/extensions: %+v %+v", got.Enums, got.Extensions)
	}
	if len(docs.Checks) != 1 || docs.Checks[0].Expr != "(id > 0)" {
		t.Fatalf("checks: %+v", docs.Checks)
	}
	if len(docs.PrimaryKey) != 1 || docs.PrimaryKey[0] != "id" {
		t.Fatalf("pk: %+v", docs.PrimaryKey)
	}
	if docs.ForeignKeys[0].RefTable != "orgs" || docs.ForeignKeys[0].RefColumns[0] != "id" {
		t.Fatalf("fk ref: %+v", docs.ForeignKeys[0])
	}
}

func TestPostgresInspectCollateCommentSerialUnique(t *testing.T) {
	db := testopen.Postgres(t)
	mustExec(t, db.Driver(), `CREATE TABLE people (
        id bigserial PRIMARY KEY,
        name text COLLATE "C" NOT NULL,
        email text UNIQUE,
        plain text
    )`)
	mustExec(t, db.Driver(), `COMMENT ON COLUMN people.name IS 'full name'`)
	// Empty Schemas resolves to current_schema().
	got, err := inspectOnce(context.Background(), t, db, migrate.InspectOptions{})
	if err != nil {
		t.Fatal(err)
	}
	people, ok := got.Table("people")
	if !ok {
		t.Fatal("people missing")
	}
	if people.Schema != "" || len(got.Schemas) != 0 {
		t.Fatalf("current schema must be implicit: %q %+v", people.Schema, got.Schemas)
	}
	name, _ := people.Column("name")
	if name.Collate != "C" || name.Comment != "full name" || name.Nullable {
		t.Fatalf("name column: %+v", name)
	}
	plain, _ := people.Column("plain")
	if plain.Collate != "" || plain.Comment != "" || !plain.Nullable {
		t.Fatalf("plain column: %+v", plain)
	}
	id, _ := people.Column("id")
	if id.Identity != "serial" || id.Default != "" || id.Type != "bigint" {
		t.Fatalf("serial must report serial: %+v", id)
	}
	if len(people.Uniques) != 1 || people.Uniques[0].Columns[0] != "email" {
		t.Fatalf("uniques: %+v", people.Uniques)
	}
}

func TestPostgresInspectRoundTripCollateComment(t *testing.T) {
	db := testopen.Postgres(t)
	mustExec(t, db.Driver(), `CREATE TABLE t (name text COLLATE "C" NOT NULL)`)
	mustExec(t, db.Driver(), `COMMENT ON COLUMN t.name IS 'n'`)
	got, err := inspectOnce(context.Background(), t, db, migrate.InspectOptions{})
	if err != nil {
		t.Fatal(err)
	}
	want := &schema.Schema{FormatVersion: schema.FormatVersion, Dialect: "postgres", Tables: []schema.Table{{
		Name:    "t",
		Columns: []schema.Column{{Name: "name", Type: "text", Collate: "C", Comment: "n"}},
	}}}
	want.Extensions = got.Extensions // database-wide; testdb installs vector
	if !schema.Equal(got, want) {
		t.Fatalf("not equal:\n got %+v\nwant %+v", got.Tables, want.Tables)
	}
}

func TestPostgresInspectOtherSchemaAndPartitions(t *testing.T) {
	db := testopen.Postgres(t)
	cur := testdb.Schema(t)
	aux := cur + "_aux"
	mustExec(t, db.Driver(), `CREATE SCHEMA `+aux)
	t.Cleanup(func() { _, _ = db.Driver().Exec(context.Background(), `DROP SCHEMA `+aux+` CASCADE`, nil) })
	mustExec(t, db.Driver(), `CREATE TABLE `+aux+`.a (id int)`)
	mustExec(t, db.Driver(), `CREATE TABLE ev (ts timestamptz NOT NULL) PARTITION BY RANGE (ts)`)
	mustExec(t, db.Driver(), `CREATE TABLE ev_2026 PARTITION OF ev FOR VALUES FROM ('2026-01-01') TO ('2027-01-01')`)
	mustExec(t, db.Driver(), `ALTER TABLE ev ENABLE ROW LEVEL SECURITY`)
	got, err := inspectOnce(context.Background(), t, db, migrate.InspectOptions{Schemas: []string{cur, aux}})
	if err != nil {
		t.Fatal(err)
	}
	if len(got.Schemas) != 1 || got.Schemas[0].Name != aux {
		t.Fatalf("schemas: %+v", got.Schemas)
	}
	var a *schema.Table
	for i := range got.Tables {
		if got.Tables[i].Schema == aux && got.Tables[i].Name == "a" {
			a = &got.Tables[i]
		}
	}
	if a == nil {
		t.Fatalf("aux.a missing: %+v", got.Tables)
	}
	ev, _ := got.Table("ev")
	if ev == nil || ev.Partition == nil || ev.Partition.Strategy != "range" || ev.Partition.Key != "RANGE (ts)" {
		t.Fatalf("ev: %+v", ev)
	}
	if ev.RLS == nil || !ev.RLS.Enabled || ev.RLS.Forced {
		t.Fatalf("rls: %+v", ev.RLS)
	}
	child, _ := got.Table("ev_2026")
	if child == nil || child.PartitionOf == nil || child.PartitionOf.Parent != "ev" ||
		!strings.HasPrefix(child.PartitionOf.Bound, "FOR VALUES FROM (") {
		t.Fatalf("child: %+v", child)
	}
}

func TestPostgresInspectMixedCaseForeignKeyRoundTrip(t *testing.T) {
	db := testopen.Postgres(t)
	cur := testdb.Schema(t)
	aux := cur + "_aux"
	mustExec(t, db.Driver(), `CREATE SCHEMA `+aux)
	t.Cleanup(func() { _, _ = db.Driver().Exec(context.Background(), `DROP SCHEMA `+aux+` CASCADE`, nil) })
	mustExec(t, db.Driver(), `CREATE TABLE `+aux+`."Orgs" (id bigint PRIMARY KEY)`)
	mustExec(t, db.Driver(), `CREATE TABLE child (
        id bigint GENERATED ALWAYS AS IDENTITY,
        org_id bigint CONSTRAINT child_org_fk REFERENCES `+aux+`."Orgs"(id),
        qty int NOT NULL DEFAULT 5,
        double_qty int GENERATED ALWAYS AS (qty * 2) STORED
    )`)
	got, err := inspectOnce(context.Background(), t, db, migrate.InspectOptions{Schemas: []string{cur, aux}})
	if err != nil {
		t.Fatal(err)
	}
	want := &schema.Schema{
		FormatVersion: schema.FormatVersion, Dialect: "postgres",
		Schemas:    []schema.SchemaNamespace{{Name: aux}},
		Extensions: got.Extensions,
		Tables: []schema.Table{
			{Schema: aux, Name: "Orgs", PrimaryKey: []string{"id"},
				Columns: []schema.Column{{Name: "id", Type: "bigint"}}},
			{Name: "child", Columns: []schema.Column{
				{Name: "id", Type: "bigint", Identity: "always"},
				{Name: "org_id", Type: "bigint", Nullable: true},
				{Name: "qty", Type: "integer", Default: "5"},
				{Name: "double_qty", Type: "integer", Nullable: true, Generated: "(qty * 2)"},
			}, ForeignKeys: []schema.ForeignKey{{
				Name: "child_org_fk", Columns: []string{"org_id"},
				RefTable: aux + ".Orgs", RefColumns: []string{"id"},
			}}},
		},
	}
	if !schema.Equal(got, want) {
		gj, _ := json.MarshalIndent(schema.Normalized(got), "", " ")
		wj, _ := json.MarshalIndent(schema.Normalized(want), "", " ")
		t.Fatalf("not equal:\n got %s\nwant %s", gj, wj)
	}
}
