// genRow models a table with a stored generated column, the way `--from-db`
// declares one: a read-only field.
type genRow struct {
	ID         int64
	Name       string
	Normalized string
}

var genRowMeta = momo.Meta[genRow]{
	Table: "gen_rows",
	Columns: []momo.ColumnMeta{
		{Name: "id", Flags: momo.FlagPK | momo.FlagIdentity},
		{Name: "name"},
		{Name: "normalized", Flags: momo.FlagReadOnly},
	},
	Ptr:      func(m *genRow, i int) any { return [...]any{&m.ID, &m.Name, &m.Normalized}[i] },
	Value:    func(m *genRow, i int) any { return [...]any{m.ID, m.Name, m.Normalized}[i] },
	Identity: 0, Version: -1, SoftDelete: -1, CreatedAt: -1, UpdatedAt: -1,
	PK: []int{0},
	// Unnest takes the column types from here.
	TableSchema: &schema.Table{Name: "gen_rows", Columns: []schema.Column{
		{Name: "id", Type: "bigint"}, {Name: "name", Type: "text"}, {Name: "normalized", Type: "text"},
	}},
}

func (*genRow) MomoMeta() *momo.Meta[genRow] { return &genRowMeta }

var (
	genRowName       = momo.NewColumn[string]("gen_rows", "name", 0)
	genRowNormalized = momo.NewReadOnlyColumn[string]("gen_rows", "normalized", momo.FlagReadOnly)
)

var genRowDDL = map[dialect.Name]string{
	dialect.Postgres: "CREATE TABLE gen_rows (id bigint generated by default as identity primary key, name text not null, normalized text generated always as (lower(name)) stored)",
	dialect.SQLite:   "CREATE TABLE gen_rows (id integer primary key autoincrement, name text not null, normalized text generated always as (lower(name)) stored)",
	dialect.MySQL:    "CREATE TABLE gen_rows (id bigint primary key auto_increment, name varchar(100) not null, normalized varchar(100) generated always as (lower(name)) stored)",
}

// TestStoredGeneratedColumnLive checks a read-only field on a GENERATED ALWAYS
// ... STORED column against every available database: Insert.Model and
// Update.Model leave it out (the database refuses a write to it), and a typed
// select filters by it.
func TestStoredGeneratedColumnLive(t *testing.T) {
	testopen.Each(t, func(t *testing.T, db *momo.DB, name dialect.Name) {
		ctx := context.Background()
		for _, stmt := range []string{"DROP TABLE IF EXISTS gen_rows", genRowDDL[name]} {
			if _, err := db.Driver().Exec(ctx, stmt, nil); err != nil {
				t.Fatalf("%s: %v", stmt, err)
			}
		}

		// A value in the read-only field must not reach the INSERT.
		a := genRow{Name: "Ada", Normalized: "ignored"}
		b := genRow{Name: "Bob"}
		for _, m := range []*genRow{&a, &b} {
			if _, err := momo.Insert[genRow](db).Model(m).Exec(ctx); err != nil {
				t.Fatalf("Insert.Model wrote the generated column: %v", err)
			}
		}
		if _, err := momo.Insert[genRow](db).Models([]genRow{{Name: "Cy", Normalized: "ignored"}}).Exec(ctx); err != nil {
			t.Fatalf("Insert.Models wrote the generated column: %v", err)
		}

		// A typed select filters by the generated column and reads it back.
		// The insert does not read the read-only field back: the model keeps the
		// value it had, and the stored row holds the computed one.
		if a.Normalized != "ignored" || b.Normalized != "" {
			t.Fatalf("an insert must leave the read-only field as it was: %q, %q", a.Normalized, b.Normalized)
		}
		got, err := momo.Select[genRow](db).Where(genRowNormalized.Eq("ada")).All(ctx)
		if err != nil {
			t.Fatal(err)
		}
		if len(got) != 1 || got[0].Name != "Ada" || got[0].Normalized != "ada" {
			t.Fatalf("select by normalized = %+v, want Ada with normalized ada", got)
		}

		// Update.Model leaves it out too, and the database recomputes it.
		row := got[0]
		row.Name = "Ada Lovelace"
		row.Normalized = "ignored"
		if _, err := momo.Update[genRow](db).Model(&row).Exec(ctx); err != nil {
			t.Fatalf("Update.Model wrote the generated column: %v", err)
		}
		got, err = momo.Select[genRow](db).Where(genRowNormalized.Eq("ada lovelace")).All(ctx)
		if err != nil || len(got) != 1 || got[0].Name != "Ada Lovelace" {
			t.Fatalf("select after update = %+v, %v", got, err)
		}

		// A Set on the other column recomputes it as well.
		if _, err := momo.Update[genRow](db).Set(genRowName.Set("BOB")).Where(genRowName.Eq("Bob")).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		got, err = momo.Select[genRow](db).Where(genRowNormalized.Eq("bob")).All(ctx)
		if err != nil || len(got) != 1 || got[0].Name != "BOB" {
			t.Fatalf("select after Set = %+v, %v", got, err)
		}

		// stored reads the computed value of the row named n.
		stored := func(n string) string {
			t.Helper()
			r, err := momo.Select[genRow](db).Where(genRowName.Eq(n)).One(ctx)
			if err != nil {
				t.Fatalf("select %q: %v", n, err)
			}
			return r.Normalized
		}

		// ReturningAll names the column explicitly, so it carries the computed
		// value where the dialect has RETURNING.
		if db.Driver().Dialect().Returning {
			ret := genRow{Name: "Dee", Normalized: "ignored"}
			rows, err := momo.Insert[genRow](db).Model(&ret).ReturningAll().Rows(ctx)
			if err != nil {
				t.Fatal(err)
			}
			var back []genRow
			for rows.Next() {
				var r genRow
				if err := rows.ScanModel(&r); err != nil {
					t.Fatal(err)
				}
				back = append(back, r)
			}
			if err := rows.Close(); err != nil {
				t.Fatal(err)
			}
			if len(back) != 1 || back[0].Normalized != "dee" {
				t.Fatalf("ReturningAll = %+v, want the computed value", back)
			}
		}

		// Upsert, Model and Models, hitting an existing row by its key. The
		// table's only unique key is the primary key, so MySQL and MariaDB run
		// it as ON DUPLICATE KEY UPDATE too.
		up := genRow{ID: row.ID, Name: "ADA L", Normalized: "ignored"}
		if _, err := momo.Upsert[genRow](db).Model(&up).Exec(ctx); err != nil {
			t.Fatalf("Upsert.Model wrote the generated column: %v", err)
		}
		if n := stored("ADA L"); n != "ada l" {
			t.Fatalf("after Upsert.Model the stored value = %q, want ada l", n)
		}
		ups := []genRow{{ID: row.ID, Name: "ADA M", Normalized: "ignored"}, {ID: 900, Name: "New One", Normalized: "ignored"}}
		if _, err := momo.Upsert[genRow](db).Models(ups).Exec(ctx); err != nil {
			t.Fatalf("Upsert.Models wrote the generated column: %v", err)
		}
		if n, m := stored("ADA M"), stored("New One"); n != "ada m" || m != "new one" {
			t.Fatalf("after Upsert.Models the stored values = %q, %q", n, m)
		}

		// A bulk insert big enough to need several chunks.
		bulk := make([]genRow, 60)
		for i := range bulk {
			bulk[i] = genRow{Name: fmt.Sprintf("BULK%02d", i), Normalized: "ignored"}
		}
		limited := momo.New(db.Driver(), momo.WithMaxParams(20))
		if _, err := momo.Insert[genRow](limited).Models(bulk).Exec(ctx); err != nil {
			t.Fatalf("chunked Insert.Models wrote the generated column: %v", err)
		}
		if n := stored("BULK59"); n != "bulk59" {
			t.Fatalf("after the chunked insert the stored value = %q", n)
		}

		// PostgreSQL only: the unnest and COPY insert paths.
		if name == dialect.Postgres {
			un := []genRow{{Name: "UN1", Normalized: "ignored"}, {Name: "UN2", Normalized: "ignored"}}
			if _, err := momo.Insert[genRow](db).Unnest().Models(un).Exec(ctx); err != nil {
				t.Fatalf("Unnest wrote the generated column: %v", err)
			}
			if n := stored("UN2"); n != "un2" {
				t.Fatalf("after Unnest the stored value = %q", n)
			}
			cp := []genRow{{Name: "CP1", Normalized: "ignored"}, {Name: "CP2", Normalized: "ignored"}}
			if _, err := momo.Insert[genRow](db).Copy(ctx, cp); err != nil {
				t.Fatalf("Copy wrote the generated column: %v", err)
			}
			if n := stored("CP2"); n != "cp2" {
				t.Fatalf("after Copy the stored value = %q", n)
			}
		}
	})
}
