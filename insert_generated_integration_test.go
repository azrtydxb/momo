package momo_test

import (
	"context"
	"testing"

	"github.com/azrtydxb/momo"
	"github.com/azrtydxb/momo/dialect"
	"github.com/azrtydxb/momo/internal/testdb/testopen"
)

// genRow models a table with a stored generated column, the way `--from-db`
// declares one: a read-only field.
type genRow struct {
	ID         int64
	Name       string
	Normalized string
}

var genRowMeta = momo.Meta[genRow]{
	Table: "gen_rows",
	Columns: []momo.ColumnMeta{
		{Name: "id", Flags: momo.FlagPK | momo.FlagIdentity},
		{Name: "name"},
		{Name: "normalized", Flags: momo.FlagReadOnly},
	},
	Ptr:      func(m *genRow, i int) any { return [...]any{&m.ID, &m.Name, &m.Normalized}[i] },
	Value:    func(m *genRow, i int) any { return [...]any{m.ID, m.Name, m.Normalized}[i] },
	Identity: 0, Version: -1, SoftDelete: -1, CreatedAt: -1, UpdatedAt: -1,
	PK: []int{0},
}

func (*genRow) MomoMeta() *momo.Meta[genRow] { return &genRowMeta }

var (
	genRowName       = momo.NewColumn[string]("gen_rows", "name", 0)
	genRowNormalized = momo.NewReadOnlyColumn[string]("gen_rows", "normalized", momo.FlagReadOnly)
)

var genRowDDL = map[dialect.Name]string{
	dialect.Postgres: "CREATE TABLE gen_rows (id bigint generated by default as identity primary key, name text not null, normalized text generated always as (lower(name)) stored)",
	dialect.SQLite:   "CREATE TABLE gen_rows (id integer primary key autoincrement, name text not null, normalized text generated always as (lower(name)) stored)",
	dialect.MySQL:    "CREATE TABLE gen_rows (id bigint primary key auto_increment, name varchar(100) not null, normalized varchar(100) generated always as (lower(name)) stored)",
}

// TestStoredGeneratedColumnLive checks a read-only field on a GENERATED ALWAYS
// ... STORED column against every available database: Insert.Model and
// Update.Model leave it out (the database refuses a write to it), and a typed
// select filters by it.
func TestStoredGeneratedColumnLive(t *testing.T) {
	testopen.Each(t, func(t *testing.T, db *momo.DB, name dialect.Name) {
		ctx := context.Background()
		for _, stmt := range []string{"DROP TABLE IF EXISTS gen_rows", genRowDDL[name]} {
			if _, err := db.Driver().Exec(ctx, stmt, nil); err != nil {
				t.Fatalf("%s: %v", stmt, err)
			}
		}

		// A value in the read-only field must not reach the INSERT.
		a := genRow{Name: "Ada", Normalized: "ignored"}
		b := genRow{Name: "Bob"}
		for _, m := range []*genRow{&a, &b} {
			if _, err := momo.Insert[genRow](db).Model(m).Exec(ctx); err != nil {
				t.Fatalf("Insert.Model wrote the generated column: %v", err)
			}
		}
		if _, err := momo.Insert[genRow](db).Models([]genRow{{Name: "Cy", Normalized: "ignored"}}).Exec(ctx); err != nil {
			t.Fatalf("Insert.Models wrote the generated column: %v", err)
		}

		// A typed select filters by the generated column and reads it back.
		got, err := momo.Select[genRow](db).Where(genRowNormalized.Eq("ada")).All(ctx)
		if err != nil {
			t.Fatal(err)
		}
		if len(got) != 1 || got[0].Name != "Ada" || got[0].Normalized != "ada" {
			t.Fatalf("select by normalized = %+v, want Ada with normalized ada", got)
		}

		// Update.Model leaves it out too, and the database recomputes it.
		row := got[0]
		row.Name = "Ada Lovelace"
		row.Normalized = "ignored"
		if _, err := momo.Update[genRow](db).Model(&row).Exec(ctx); err != nil {
			t.Fatalf("Update.Model wrote the generated column: %v", err)
		}
		got, err = momo.Select[genRow](db).Where(genRowNormalized.Eq("ada lovelace")).All(ctx)
		if err != nil || len(got) != 1 || got[0].Name != "Ada Lovelace" {
			t.Fatalf("select after update = %+v, %v", got, err)
		}

		// A Set on the other column recomputes it as well.
		if _, err := momo.Update[genRow](db).Set(genRowName.Set("BOB")).Where(genRowName.Eq("Bob")).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		got, err = momo.Select[genRow](db).Where(genRowNormalized.Eq("bob")).All(ctx)
		if err != nil || len(got) != 1 || got[0].Name != "BOB" {
			t.Fatalf("select after Set = %+v, %v", got, err)
		}
	})
}
